    <h3 class="sec" id="r2-col">圆柱、圆锥、圆台</h3>
    <p>以矩形的一边所在直线为轴，其余三边旋转形成的面围成的旋转体叫做<strong>圆柱</strong>。矩形垂直于轴的两边各转出一个底面，这两圆全等且互相平行；平行于轴的那边转出侧面。圆柱的母线互相平行且都等于高。</p>
    <p>以直角三角形的一条直角边所在直线为轴，其余两边旋转形成的面围成的旋转体叫做<strong>圆锥</strong>。斜边转出侧面，另一条直角边转出底面，斜边就是母线，它的一端落在轴上的顶点，另一端落在底面圆周上。</p>
    <p>用平行于圆锥底面的平面截圆锥，底面与截面之间的部分叫做<strong>圆台</strong>。也可以看成以直角梯形垂直于底边的腰所在直线为轴，其余三边旋转形成的面围成的旋转体。上、下底面的半径不等时母线才倾斜；上底半径缩到零，圆台变成圆锥；上、下底半径相等，圆台变成圆柱。三种几何体因此共用一套描述，积1 的体积公式也把它们写成同一个式子的三种取值。</p>

    <h3 class="sec" id="r2-sphere">球与球面</h3>
    <p>以半圆的直径所在直线为轴，半圆面旋转一周形成的旋转体叫做<strong>球体</strong>，简称球；半圆的圆心叫做球心，半圆的半径叫做球的半径，半圆的直径叫做球的直径。半圆弧旋转形成的曲面叫做<strong>球面</strong>。</p>
    <p>球面是到球心距离等于半径的所有点组成的集合：<Katex tex="\{P\mid |OP|=R\}" />。球体则包含内部，是到球心距离不超过 <Katex tex="R" /> 的点的集合。球没有底面与母线，它的任何一个过球心的截面都是同样大的圆，这个圆叫做大圆；不过球心的截面圆都小一些。</p>
    <p>球面不能展开成平面图形，因此球的表面积与体积没有「展开图」可算，只能靠分割求和的极限（积2 说明）。这一点与柱、锥、台不同，后者都能把侧面展开成矩形、扇形或扇环。</p>

