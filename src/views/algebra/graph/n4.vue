    <h3 class="sec" id="n4-euler">欧拉回路与奇点</h3>
    <p>必要性来自度数：回路每经过一个顶点，进来一次再出去一次，用掉两条边，因此每个顶点在回路里出现的次数使得它的度数为偶数。若路径是开的，只有起点与终点各多出半条，度数为奇数。</p>
    <p>充分性用归纳：从任一点出发沿未用边一直走，走不动时停下，得到的闭道路若已用完所有边就是回路；否则选一个在道路上、还有剩余边的顶点，去掉这条闭道路，剩余部分仍满足奇点条件，递归地接回。</p>
    <p>这条构造就是弗勒里算法与希尔霍尔策算法的基础。画板只做判读，真正的路线可以按这个递归一步步写出来。</p>

    <h3 class="sec" id="n4-seven">七桥问题的回答</h3>
    <p>柯尼斯堡的四块陆地对应四个顶点，七座桥对应七条边。两岸各三座桥、两座岛各五座桥，四个顶点的度数都是奇数，按判据既没有欧拉回路也没有欧拉路径。</p>
    <p>欧拉 1736 年的这篇论文被认作图论的开端。它的贡献不在于给出走法，而在于说明：某些问题根本不需要逐一尝试，结构本身已经给出答案。</p>
    <p>画板的两个预设正对这条对比。七桥的红色顶点有四个；五边形每个顶点度数为 2，一条边接一条边走完就回到起点，不需要任何选择。</p>

    <h3 class="sec" id="n4-ham">哈密顿回路</h3>
    <p>哈密顿回路要求每个顶点恰好经过一次。它与欧拉回路的区别在于计数的对象：一个数边，一个数点。同一张图上两种回路可以一个有、一个没有。</p>
    <p>判断哈密顿回路没有简单判据。常用的是必要条件：若某个顶点被删掉后图分成 <Katex tex="c" /> 块，它至多被回路用掉两次，因此 <Katex tex="c" /> 不能超过这个顶点原先的度数。条件不满足就一定没有，满足也不能保证有。</p>
    <p>求最短的哈密顿回路是旅行商问题，属于组合优化里最著名的一类。规模稍大就无法枚举，实际用的是分支定界与近似算法。</p>

