      <div class="cap">图 统1b · <b>频率分布直方图机</b>：100 个成绩按组距分组，矩形的高取「频率 ÷ 组距」。金色折线连接各矩形顶端，橙色虚线是平均数，紫色虚线是中位数。看点：无论组数 k 取多少，面积之和恒为 1，这说明纵轴不能直接读频率，必须用面积读。k 取 5 时只看得出大致轮廓，取 12 时细节增多而每组的样本变少，锯齿更明显 —— 组距的选择是在「轮廓」与「细节」之间取舍。</div>
    </div>
    <p>与直方图配套的还有<b>频率分布折线图</b>：把各矩形顶边的中点依次连起来，两端落回横轴。样本量不断增大、组距不断缩小时，这条折线会逐渐逼近一条光滑曲线 —— 这条曲线就是总体分布的密度曲线。这条思路把统计与概率连了起来：总体的分布正是大量重复试验中频率稳定到的那个概率分布。</p>

    <h3 class="sec" id="t1-est">用样本估计总体</h3>
    <p>抽样的目的是用样本推断总体。频率分布直方图给出的是总体分布的近似形状，由它可以估计出总体中落在某个区间的个体所占的比例：把对应区间的矩形面积相加即可。</p>
    <p>这种估计有两个来源的误差。一是<b>抽样误差</b>：样本只是总体的一部分，换一批样本，统计量就会变；样本量越大，抽样误差越小，但不会消失。二是<b>分组误差</b>：数据分组后组内的具体取值被抹平，只能用组中值代替，组距越大这种损失越大。前者靠增加样本量控制，后者靠细化分组控制，两者都要付出成本。</p>

    <h3 class="sec" id="t1-pit">易错点</h3>
    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把直方图的纵轴当成频率。</strong>纵轴是「频率 ÷ 组距」，只有矩形的面积才是频率。组距为 10 时，高 0.03 的矩形对应的频率是 0.3，不是 0.03。</li>
        <li><strong>提示二：分层抽样按层人数平均分配。</strong>样本量要按各层人数比例分配，不是各层各取 <Katex tex="n" /> ÷ 层数。若各层人数不等而平均分配，样本的结构就与总体不一致，分层失去了意义。</li>
        <li><strong>提示三：以为样本量越大越没有误差。</strong>样本量增大会压缩抽样误差，却消灭不了它。只要不是普查，样本统计量与总体参数总会有差别。</li>
        <li><strong>提示四：用系统抽样处理有周期规律的总体。</strong>若总体按周期排列且间隔恰好等于周期，抽出的样本会全部落在同一相位上，产生系统性偏差。</li>
      </ul>
