    <h3 class="sec" id="t1-samp">简单随机抽样与分层抽样</h3>
    <p>简单随机抽样有两种常见做法：抽签法与随机数法。前者把每个个体编号后均匀混合，从中抽取；后者借助随机数表或计算机产生的随机数决定抽取哪些编号。两种做法都要求每个个体在每一步被抽到的机会相等，也就是等概率抽样。</p>
    <p>分层抽样适用的场合是总体内部差异明显、且这种差异与所考察的指标有关。把总体按差异分成若干层，层内差异小、层间差异大，再按比例分配样本量，抽出的样本就能在结构上与总体保持一致。分配公式为
      <Katex tex="n_i=n\cdot\dfrac{N_i}{N}" />，其中 <Katex tex="N_i" /> 是第 <Katex tex="i" /> 层的人数，<Katex tex="N" /> 是总体容量，<Katex tex="n" /> 是样本量。若按比例算得小数，用四舍五入或按小数部分从大到小补足整数个。</p>
    <p>还有一种常用的<b>系统抽样</b>：把总体编号后按固定的间隔 <Katex tex="k=N/n" /> 依次抽取。它实现简单，在总体没有周期性规律时效果与简单随机抽样相当；若总体恰好按周期排列，固定间隔会把周期性的偏差一并抽进样本。</p>

    <h3 class="sec" id="t1-hist">频率分布直方图</h3>
    <p>拿到样本后要看它的分布形态。做法是先确定组数与组距，把数据分组，统计各组的频数，再算出频率 <Katex tex="\text{频率}=\dfrac{\text{频数}}{\text{样本量}}" />。把每组的频率再除以组距，作为矩形的高，这样每块矩形的面积恰好等于该组的频率，全部矩形面积之和为 1。</p>
    <div class="board-wrap">
