    <p class="cap">图 电2a · <b>电场线与场强：点电荷、等量异种电荷、匀强电场</b>：点电荷档里左端一枚电荷，四周的射线是电场线，青色光点沿电场方向流动；试探点 P 上的紫色箭头是那一点的场强。看点一：把<b>电荷量 Q</b> 拖成负值，场线箭头与光点一起调头，P 上的 E 也翻向——场强方向的规定是「正电荷受力方向」。看点二：光点越靠近电荷走得越快、越远越慢，与场线的疏密对照着看；拖大距离 r，E 箭头变短，右栏橙点沿平方反比曲线向左下滑，读数栏的 E·r² 拖距离时不动。看点三：切到等量异种电荷档，光点从正电荷出发、沿弯曲的场线流向负电荷，靠近两极处明显加速，场线稀疏的地方放慢；拖大间距 d，场线整体变疏，中点场强按 8kQ/d² 迅速变小。看点四：切到匀强电场档，两块平行极板之间是一族等间距的平行场线，光点处处同速前进——板间每一点的大小与方向都相同，这就是「匀强」；拖大板距 d，场强按 E = U/d 反比减小，右栏橙点沿双曲线滑动，读数栏的 E·d 一行始终等于板间电压。</p>

    <h3 class="sec" id="e2-apply">叠加与算例</h3>
    <p>多个电荷同时存在时，空间中某一点的场强等于各个电荷单独在该点产生的场强的<strong>矢量和</strong>，这叫场强的叠加原理：</p>
    <p style="text-align:center"><Katex tex="\vec E=\vec E_1+\vec E_2+\cdots" display /></p>
    <p>计算时先逐个算出每个场源电荷在该点产生的场强大小与方向，再按平行四边形定则合成。共线时取正负化成代数和，不共线时不能省掉方向。</p>
    <p>举一个数：点电荷 <Katex tex="Q=3.0\ \mu\text{C}" />，求距离它 0.20 m 处的场强。</p>
    <p style="text-align:center"><Katex tex="E=9.0\times10^{9}\times\frac{3.0\times10^{-6}}{(0.20)^2}=6.75\times10^{5}\ \text{N/C}." display /></p>
    <p>方向沿连线背离电荷（<Katex tex="Q" /> 为正）。若在同一点放一个 <Katex tex="q=-2.0\times10^{-6}\ \text{C}" /> 的电荷，它受到的力是 <Katex tex="F=|q|E=1.35\ \text{N}" />，方向与场强相反，指向电荷。</p>
    <p>等量异种电荷的情形：两个电荷各带 3.0 μC、相距 0.30 m，连线中点处两个场强方向相同、大小都是 <Katex tex="kQ/(0.15)^2" />，合起来是</p>
    <p style="text-align:center"><Katex tex="E_{\text{中}}=2\times\frac{9.0\times10^{9}\times3.0\times10^{-6}}{(0.15)^2}=2.4\times10^{6}\ \text{N/C}," display /></p>
    <p>方向由正电荷指向负电荷。读数栏的「E·d²」一项跟着间距走时不变，可以拿它核对平方反比。</p>
    <p>在 P 点画图时要注意：两支场强沿各自连线方向，大小由 <Katex tex="kQ/r^2" /> 给出，合成时补成平行四边形。下面这块演示把同一条路子放大成可以拖着看的过程。</p>

