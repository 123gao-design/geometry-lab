    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把定义式里的 q₀ 当成场源电荷。</strong><Katex tex="E=F/q_0" /> 中的 <Katex tex="q_0" /> 是试探电荷，不是产生电场的那个电荷。场强由场源电荷与位置决定，换一个试探电荷，力变、比值不变。做题时先认清谁是场源、谁是试探电荷。</li>
        <li><strong>提示二：以为场强方向就是电荷受力的方向。</strong>场强的方向规定为正电荷受力的方向。负电荷受力的方向与场强相反，用 <Katex tex="F=qE" /> 时把负号带进去，方向自然对。</li>
        <li><strong>提示三：把电场线当成带电粒子的轨迹。</strong>电场线给出的是各点的场强方向；粒子的轨迹由初速度与受力共同决定，两者一般并不重合。只有初速度为零、且场线是直线时，轨迹才沿着场线。</li>
        <li><strong>提示四：以为电场线可以相交。</strong>电场中每一点的场强只有一个方向，两条电场线若相交，交点处就出现了两个方向，与场强的唯一性矛盾。画图时也要避免画出交叉的场线。</li>
