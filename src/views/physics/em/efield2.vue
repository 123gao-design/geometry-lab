    <h3 class="sec" id="e2-field">电场的引入</h3>
    <p>两个电荷没有接触，却彼此施加作用力。一种解释是「超距作用」——力瞬间跨越空间直接作用；另一种解释是「场」——电荷先在周围空间里建立起电场，另一个电荷处在电场中才受力。近代物理采用后一种图像，因为场的建立与传播需要时间，而且场本身携带能量与动量。</p>
    <p>于是两个电荷之间的相互作用可以拆成两步：电荷 <Katex tex="Q" /> 在周围激发电场；另一个电荷 <Katex tex="q" /> 放进这块空间，受到电场给它的力。第一步只与 <Katex tex="Q" /> 及其位置有关，第二步只与 <Katex tex="q" /> 及该点的场有关。用两个环节分别描述，比笼统地说「两个电荷互相吸引」清楚得多。</p>
    <p>电场是真实存在的物质，不是计算时的辅助工具。它有强弱、有方向，随位置变化；变化的电场还能脱离电荷独立传播，形成电磁波——这一点在电磁感应与交变电流几章里会再遇到。</p>

    <h3 class="sec" id="e2-def">电场强度</h3>
    <p>把同一个试探电荷 <Katex tex="q_0" /> 放到电场中的不同位置，它受到的力大小不同、方向也不同。在电场中某一点，比值 <Katex tex="F/q_0" /> 有一个确定的值，与试探电荷本身的大小、正负都无关：换一个带电量更大的试探电荷，力按比例变大，比值不变；换成负电荷，力的方向反过来，比值的大小仍不变。这个只由场本身决定的量，就是<strong>电场强度</strong>：</p>
    <p style="text-align:center"><Katex tex="E=\frac{F}{q_0}." display /></p>
    <p>电场强度是<strong>矢量</strong>。方向规定为<strong>正电荷</strong>在该点所受电场力的方向；如果是负电荷，它受力的方向与场强方向相反。单位由定义式给出：力的单位是 N、电荷量的单位是 C，所以场强的单位是 N/C；后面还会看到它与 V/m 是同一个单位。</p>
    <p>由定义式反过来，已知某点场强 <Katex tex="E" />，电荷 <Katex tex="q" /> 放在那里受到的电场力就是</p>
    <p style="text-align:center"><Katex tex="F=qE." display /></p>
    <p>这个式子里 <Katex tex="q" /> 带正负号时，力的方向自动正确：正电荷受力沿场强方向，负电荷受力逆着场强方向。使用时要分清两个角色：<Katex tex="Q" /> 是产生电场的场源电荷，<Katex tex="q_0" /> 或 <Katex tex="q" /> 是放进场里的试探电荷。场强只由 <Katex tex="Q" /> 与位置决定。</p>

    <h3 class="sec" id="e2-point">点电荷的场强</h3>
    <p>把试探电荷放在点电荷 <Katex tex="Q" /> 附近，距离为 <Katex tex="r" />，由库仑定律它受的力是 <Katex tex="F=k|Q|q_0/r^2" />，除以 <Katex tex="q_0" /> 就得到场强：</p>
    <p style="text-align:center"><Katex tex="E=k\frac{|Q|}{r^2}." display /></p>
    <p>这个式子说明：点电荷的场强只与场源电荷的电荷量和距离有关，与试探电荷无关；距离增大，场强按平方反比减小；正电荷的场强沿半径向外，负电荷的场强沿半径向内。</p>
    <p>点电荷的场强表达式与库仑定律是同一条规律的两种写法。前者说的是「这一点有多强」，后者说的是「放一个电荷上去受多大的力」；把 <Katex tex="F=qE" /> 与 <Katex tex="E=kQ/r^2" /> 乘起来，就回到了库仑定律。</p>

    <h3 class="sec" id="e2-lines">电场线</h3>
    <p>电场看不见摸不着，用一族曲线把它画出来，叫<strong>电场线</strong>。画法有三条规则：</p>
    <p>其一，电场线上每一点的<strong>切线方向</strong>就是该点的场强方向；其二，电场线的<strong>疏密</strong>表示场强的相对大小，密处强、疏处弱；其三，电场线从正电荷出发、终止于负电荷（或伸向无穷远、来自无穷远），在无电荷处不中断。</p>
    <p>由此还能推出两条性质：任意两条电场线不会相交，否则交点处将有两个场强方向，与「一点的场强只有一个方向」矛盾；电场线不是带电粒子的运动轨迹，它只给出各点场强的方向，粒子实际往哪里走还要看初速度和受力。</p>
    <p>要强调一点：电场线是为描述电场而画的假想曲线，实际空间中并没有这些线。它们的形状由场本身决定，不随你是否画出而改变。</p>

    <h3 class="sec" id="e2-typical">几种典型电场</h3>
    <p><strong>孤立点电荷</strong>：电场线是以电荷为中心的径向直线，正电荷向外发散、负电荷向内汇聚，越靠近电荷越密。</p>
    <p><strong>等量异种电荷</strong>：电场线从正电荷出发、终止于负电荷，中间的连线是一条直的场线，两侧的线向外弯曲。两电荷连线的中垂面上，场强方向与该平面平行（由正指向负那一侧），中点处场强最强，向两侧逐渐减弱。</p>
    <p><strong>等量同种电荷</strong>：两条电荷的场线互相排斥、向两侧弯曲，连线中点处场强为零——两个电荷在中点产生的场强等大反向，恰好抵消。</p>
    <p><strong>匀强电场</strong>：场强处处大小相等、方向相同，电场线是一族等间距的平行直线。两块靠近的平行金属板分别带等量异种电荷时，板间中间区域的电场就近似为匀强电场，这是后面带电粒子在电场中运动问题最常用的模型。</p>

