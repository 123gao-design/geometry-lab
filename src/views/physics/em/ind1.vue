    <h3 class="sec" id="i1-cond">产生感应电流的条件</h3>
    <p>磁1 讲过磁通量 <Katex tex="\Phi=BS\cos\theta" />，描述穿过某个面的磁感线条数。把一个闭合的导体回路放进磁场，回路围出的面积上就有一个磁通量。只要这个磁通量发生变化，回路里就有电流——不需要电源，也不需要回路本身带电。</p>
    <p>由 <Katex tex="\Phi=BS\cos\theta" /> 可以直接看出，能让磁通量变的方式只有三种：</p>
    <p>① 磁感应强度 <Katex tex="B" /> 变化——把磁铁移近或移远，或者让产生磁场的电流变化；② 回路的面积 <Katex tex="S" /> 变化——线圈被拉大或压扁，或者一根导体棒在导轨上滑动，把回路的面积改变；③ 回路与磁场的夹角 <Katex tex="\theta" /> 变化——线圈在磁场里转动。三种方式看来不同，落到磁通量上是一回事。</p>
    <p>两个前提缺一不可：回路必须<strong>闭合</strong>，磁通量必须<strong>变化</strong>。回路断开时没有电流，但电动势照样存在，这一点到下一章会再回到；磁通量再大，只要它不动，同样不会有电流。</p>
    <p>另外要分清「磁通量为零」与「磁通量不变」。线圈转到位时 <Katex tex="\theta=90^\circ" />，<Katex tex="\Phi=0" />，可它正在从正值往负值穿过零点，变化率最大，感应电流反而是最强的。判据始终是<strong>变化</strong>，不是此刻的数值。</p>

    <h3 class="sec" id="i1-law">楞次定律</h3>
    <p>感应电流一产生，它自己也产生磁场。楞次定律说的是：<strong>感应电流的磁场总要阻碍引起感应电流的磁通量的变化</strong>。把它拆成两句更便于使用：</p>
    <p style="text-align:center"><Katex tex="\text{原磁通量增加}\;\Rightarrow\;\text{感应磁场与原磁场反向},\qquad \text{原磁通量减少}\;\Rightarrow\;\text{感应磁场与原磁场同向}." display /></p>
    <p>下面这块板画的就是这条规则。条形磁铁的 N 极朝向线圈，磁铁靠近时穿过线圈的磁通量增加，线圈里的感应电流绕成一个方向，使线圈靠磁铁的一端显出 N 极，与磁铁的 N 极互相排斥；磁铁掉头远离时磁通量减少，电流反向，线圈靠磁铁的一端变成 S 极，反过来吸引磁铁。</p>

