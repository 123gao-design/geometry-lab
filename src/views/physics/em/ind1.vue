    <p class="cap">图 电11 · <b>磁铁与线圈：感应电流的方向</b>：左栏是条形磁铁与线圈，磁铁沿轴线往复，靠近时橙色箭头标出原磁场的走向。看点一：磁铁靠近的那半程，线圈上的绿色箭头逆时针绕行，远离的半程翻成顺时针（都从磁铁这一侧看），方向恰好在一个往复周期里翻一次。看点二：磁铁两端的紫色 F 箭头始终与运动方向相反——靠近时是斥力、远离时是引力，这是「阻碍」在力上的表现。看点三：右栏的蓝色曲线是磁通量随时间的变化，橙色点的切线在磁铁离得最近、运动最快处最陡，磁铁停在远处与近处时曲线过峰过谷、切线水平，感应电流归零。看点四：点「S 极朝向线圈」，原磁场整体反向，同一时刻的电流方向也跟着反过来，读数栏的电动势、电流大小不变。</p>

    <h3 class="sec" id="i1-steps">判断方向的四个步骤</h3>
    <p>拿到一道判断方向的题，按下面四步走，每一步都只回答一个问题：</p>
    <p><strong>第一步，定原磁场的方向。</strong>磁铁产生的要看是哪一极靠近，通电导线产生的用安培定则判断。原磁场穿过回路的正负号由回路的法线约定，但多数题目只需要知道「从哪一侧穿进去」。</p>
    <p><strong>第二步，判断磁通量在增加还是减少。</strong>看的是变化趋势：磁铁在靠近还是远离、回路面积在扩大还是收缩、磁场在增强还是减弱。这一步只看增减，不看到底多大。</p>
    <p><strong>第三步，由楞次定律定出感应电流的磁场方向。</strong>增加就取反向，减少就取同向。</p>
    <p><strong>第四步，用安培定则定出电流方向。</strong>右手握住线圈，四指沿感应电流的绕行方向，拇指所指就是感应磁场的方向；把已知方向反过来查一次，就是电流的绕行方向。</p>
    <p>第三步与第四步之间最容易出错的地方在观察角度。同一股电流，站在线圈的这一侧看是逆时针，走到另一侧看就成了顺时针。判断时先把观察方向说清楚——常见约定是「从磁铁这一侧看」或者「从纸面外看」，说清之后再落笔。</p>

    <h3 class="sec" id="i1-energy">从能量守恒看楞次定律</h3>
    <p>为什么一定是「阻碍」，而不能是「助长」？理由在能量上。磁铁靠近线圈时线圈排斥它，要让它继续靠近，外界必须克服这个斥力做功，这部分功转化成了回路里的电能，最终变成焦耳热。磁铁远离时线圈吸引它，磁铁要挣脱吸引继续远离，同样要克服引力做功。</p>
    <p>反过来设想：如果磁铁一靠近，线圈就吸引它，磁铁会自己越跑越快，动能与回路里的电能一起增加，没有任何东西在减少。这样的过程并不违反动量，却违反能量守恒。楞次定律之所以必然是「阻碍」，正是因为能量守恒这条底线不能破。</p>
    <p>同一件事还有两种常见的说法。<strong>阻碍相对运动</strong>：来拒去留，磁铁靠近时排斥、远离时吸引。<strong>阻碍面积变化</strong>：线圈处在磁场中而被拉大时，电流的磁场阻止它扩张；被压缩时，电流的磁场阻止它收缩。这两种说法与「阻碍磁通量变化」是同一句话的不同写法，遇到具体问题哪一个顺手就用哪一个。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把「阻碍」读成「阻止」。</strong>阻碍只是延缓变化、让外界多做一点功，并不能把变化拦下来。磁铁照样能插入线圈，只是需要克服斥力；面积照样能扩大，只是要拉得更费力。</li>
        <li><strong>提示二：把磁通量的正负与增减混为一谈。</strong>判据是 <Katex tex="\Delta\Phi" /> 的符号。磁场反向穿过线圈并且越来越强时，<Katex tex="\Phi" /> 是负的，可它在向更负的方向走，仍然算「增加」，感应磁场照旧与原磁场反向。</li>
        <li><strong>提示三：只背「增反减同」，不认「谁的变化」。</strong>「反」与「同」都是相对<strong>原磁场</strong>的方向说的，不是相对线圈的绕法。先把原磁场的方向找准，再谈反同。</li>
        <li><strong>提示四：把感应电流的磁场当成回路里新长出来的磁铁。</strong>感应磁场只在有磁通量变化时存在，变化一停它就消失；它的大小由变化快慢决定，与回路里原有的磁场强弱没有直接关系。</li>
      </ul>
