    <h3 class="sec" id="i3-what">自感现象</h3>
    <p>拿一只线圈通上电流，电流在周围产生磁场，这些磁感线同样穿过线圈围出的每一圈。前面两章说过，穿过回路的磁通量发生变化就产生感应电动势；现在变化的源头不是磁铁也不是外加磁场，而是<strong>回路自己的电流</strong>。</p>
    <p>线圈的几何形状不变时，它产生的磁场与电流成正比，穿过自身的磁通量也写得出 <Katex tex="\Phi=L i" />。电流变化 <Katex tex="\Delta i" />，磁通量变化 <Katex tex="\Delta\Phi=L\Delta i" />，代入法拉第定律并取单匝的形式，</p>
    <p style="text-align:center"><Katex tex="\varepsilon_L=\left|\dfrac{\Delta\Phi}{\Delta t}\right|=L\left|\dfrac{\Delta i}{\Delta t}\right|" display /></p>
    <p>系数 <Katex tex="L" /> 就是自感系数，也叫电感。它的单位由上式定出：<Katex tex="1\;\text{H}=1\;\text{V}\cdot\text{s}/\text{A}" />，即电流每秒变化 1 A 时产生 1 V 的自感电动势，自感系数就是 1 H。</p>
    <p>自感最直观的表现是「电流不能突变」。给一个带铁芯的线圈通电，电流不会像接纯电阻那样立刻跳到 <Katex tex="\varepsilon/R" />，而是按指数规律慢慢爬上去；断开电源时，线圈里的电流也不会立刻归零。中学实验里常见的那一对现象——合上开关灯泡延迟变亮、断开开关灯泡闪一下再灭——都由自感造成。</p>

    <PhysicsDemo :def="DEMO" />
    <p class="cap">图 电13 · <b>并联的电感与电阻：自感的两个阶段</b>：左栏是电源经开关分给并联的电感 L 与电阻 R，绿色小点沿导线流动，快慢与电流大小成正比。看点一：合上开关的瞬间，L 中的电流从零开始按指数上升，读数栏的「自感电动势」在刚合闸时最大，随后与电流变化率一起减小到零；同时刻 R 中的电流已经是它的终值。看点二：断开开关后，绿色小点不再经过电源，只在 L 与 R 之间绕圈——L 中的电流方向与原来相同、逐渐衰减，R 中的电流则反向，这正是「灯泡闪一下」的来历。看点三：右栏的曲线在合闸段是橙色的上升指数、在断闸段是青色的下降指数，两段的时间常数同为 τ = L/R，紫色虚线标出的 63% 位置就是 τ。看点四：点「涡流阻尼」，画面换成一个铜摆在两极之间摆动，摆片进入磁场时出现紫色涡流圈，振幅迅速衰减；紫色虚线是同初始角、没有阻尼的理想摆，两条曲线一对照，电磁阻尼的作用一目了然。</p>

    <h3 class="sec" id="i3-dir">自感电动势的方向</h3>
    <p>自感电动势的方向不需要另立规则，楞次定律照样适用：<strong>自感电动势总是阻碍电流的变化</strong>。把上一章的「增反减同」换成电流的语言：</p>
    <p>电流<strong>增大</strong>时，自感电动势与原电流<strong>反向</strong>，起扼制作用，就像电路里临时多了一只电源在顶住；电流<strong>减小</strong>时，自感电动势与原电流<strong>同向</strong>，维持原来的电流，就像回路里还留着一只电源继续供电。</p>
    <p>演示里断开开关那一刻最能说明问题：电源已经撤走，如果回路只有电阻，电流会立刻归零；但 L 中的电流按指数缓慢衰减，这期间 L 就充当了电源，把储存的磁场能释放出来供给电阻发热。R 中的电流反向，正是「L 顶着原方向的电流，回路因此反着绕」的结果。</p>
    <p>这条规律也解释了实际操作中的一个危险：断开大电感的电路时，电流变化率极大，自感电动势可以达到几百伏甚至更高，开关触点上会打火。日光灯启动器、继电器触点上的电容与二极管，就是为吸收这股电动势而设的。</p>

    <h3 class="sec" id="i3-tau">自感系数与时间常数</h3>
    <p>合闸之后线圈中的电流并不是直线上涨，解 <Katex tex="\varepsilon-\varepsilon_L=iR" /> 得到</p>
    <p style="text-align:center"><Katex tex="i=\dfrac{\varepsilon}{R}\left(1-e^{-Rt/L}\right),\qquad i=i_0\,e^{-Rt/L}" display /></p>
    <p>前一式是合闸之后的上升段，后一式是断开之后的衰减段。</p>
    <p>两式中反复出现同一个量 <Katex tex="\tau=L/R" />，单位是秒，叫<strong>时间常数</strong>。它决定电流变化的快慢：经过 τ 的时间，合闸后的电流达到终值的 63%，断开后的电流剩到初值的 37%；经过 3τ 大致到 95%，经过 5τ 已可看作稳定。演示右栏那条 63% 参考线与横轴的交点就是 τ。</p>
    <p>自感系数 <Katex tex="L" /> 由线圈本身决定：匝数越多、截面积越大、长度越短，L 越大；插入铁芯后 L 可以增大几百倍。这就是变压器与电磁铁都要有铁芯的原因——同样大小的电流能产生强得多的磁场，储藏的磁场能也更多。储存的磁场能可以写成 <Katex tex="E_L=\tfrac12Li^2" />。</p>
    <p>从量纲上核一遍 <Katex tex="\tau=L/R" />：<Katex tex="\text{H}/\Omega=\text{V}\cdot\text{s}/(\text{A}\cdot\text{V}/\text{A})=\text{s}" />，确实是时间。把「自感系数」拖大或把「电阻」拖小，τ 随之变大，右栏曲线变缓，这一格读数与曲线的形状是一致的。</p>

    <h3 class="sec" id="i3-eddy">涡流</h3>
    <p>把一块金属放进变化的磁场，或者让金属在磁场中运动，金属内部的每一小段都像一条闭合导线，被感生出电流。这些电流在整块金属里绕成一个个闭合的漩涡，所以叫<strong>涡流</strong>。</p>
    <p>演示第二档的铜摆就是一例：摆片扫过磁场区时，片内切割磁感线的面积在变化，涡流随之产生。根据楞次定律，涡流受的安培力总要阻碍引起它的相对运动，于是摆的振幅迅速衰减，最后停在磁场里——这就是<strong>电磁阻尼</strong>。无轨电车、过山车、部分健身器械的刹车都靠它：没有接触、没有磨损，制动力随速度增大，速度低了自动减弱。</p>
    <p>涡流也有用处。电磁炉让高频电流在锅底产生涡流，直接把锅加热；感应加热淬火用同样原理处理金属表层。有害的一面同样存在：变压器的铁芯处在交变磁场中，涡流会让铁芯发热，白白损耗电能，所以铁芯要造成一片片彼此绝缘的薄片（硅钢片），把涡流的回路切断，涡流小了，发热也就小了。</p>
    <p>看得出来，涡流与自感是同一件事的两种面貌：自感是电流变化在回路里激起电动势，涡流是磁通量变化在整块导体里激起电流。区别只在导体是被绕成了一个回路，还是一整片。</p>

