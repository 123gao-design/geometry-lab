    <h3 class="sec" id="a2-struct">互感：变压器怎样工作</h3>
    <p>把两个线圈套在同一个闭合铁芯上，就构成一台变压器。接电源的那个叫原线圈（初级），接负载的叫副线圈（次级）。原线圈通入交变电流，铁芯里的磁通量随之交变；这个磁通量同样穿过副线圈，副线圈就产生感应电动势。</p>
    <p>严格地说，这是一种互感现象：一个线圈中电流的变化，在另一个线圈里引起感应电动势。前面在自感那一章已经见过同一个机制——那里是线圈自己影响自己，这里是两个线圈通过铁芯互相影响。</p>
    <p>铁芯的作用是把磁通量尽可能约束在一条闭合路径里，让它几乎全部穿过两个线圈。如果磁通量有一部分漏到空气中，副边得到的电压就会低于按匝数比算出的值。分析计算时约定：漏磁忽略、线圈电阻不计、铁芯中的涡流与磁滞损耗不计，这样的变压器叫理想变压器。下一张图的所有读数都按理想情形给出。</p>
    <p>铁芯本身是硅钢片叠成的。整块金属在交变磁场里会产生涡流而发热，把铁芯做成相互绝缘的薄片叠起来，涡流被限制在每一片内部，损耗大幅减小。这是涡流理论在工程上的直接应用。</p>

    <PhysicsDemo :def="DEMO" />
    <p class="cap">图 电16 · <b>变压器：匝数比决定电压比</b>：左栏是闭合铁芯与两个线圈，左侧中间的圆圈带正弦符号表示交流电源，右侧方框是负载电阻，橙色小点沿铁芯环流动表示交变的磁通量。右栏上下两张图共用一条时间轴，上面是原边电压 u₁(t)、下面是副边电压 u₂(t)，两条曲线同频同相。看点一：读数栏「每匝电压 U₁/n₁」与「U₂/n₂」两行始终相等，这就是电压比等于匝数比的物理内容。看点二：把 n₂ 拖大，u₂ 的峰值按正比升高、u₂ 读数变大，同时副边电流变小，输入功率与输出功率依然相等。看点三：把负载电阻 R 拖大，副边电流与功率一起下降，但 U₂ 不受影响——变压器的输出电压由匝数比与输入电压决定，与负载无关，这与电源的内阻效应不同。看点四：把输入电压 U₁ 拖大，两张图的峰值按同一比例升高，横轴刻度与相位都不变——频率由电源决定，变压器不改变它。</p>

    <h3 class="sec" id="a2-volt">电压比等于匝数比</h3>
    <p>穿过每一匝线圈的磁通量相同，因此每一匝产生的感应电动势也相同。原线圈 <Katex tex="n_1" /> 匝的总电动势是每匝电动势的 <Katex tex="n_1" /> 倍，副线圈是 <Katex tex="n_2" /> 倍，两者之比就是匝数之比：</p>
    <p style="text-align:center"><Katex tex="\dfrac{U_1}{U_2}=\dfrac{n_1}{n_2}" display /></p>
    <p>这里的电压指有效值，比值对峰值同样成立——两侧的波形只差一个比例因子，相位与频率都一样。运用于工程时习惯写成「每匝电压」的形式：<Katex tex="U_1/n_1=U_2/n_2" />，左右两边都等于每匝分摊的电压。演示的读数栏把这两行同时列出，拖任何一个滑块它们都保持相等。</p>
    <p><Katex tex="n_2>n_1" /> 时 <Katex tex="U_2>U_1" />，叫升压变压器；<Katex tex="n_2<n_1" /> 时降压。发电厂送出时用升压，用户端用降压，一升一降之间电压落差可以做到几百倍。</p>

    <h3 class="sec" id="a2-power">功率与电流的关系</h3>
    <p>理想变压器没有能量损耗，原线圈输入的电功率全部由副线圈输出：</p>
    <p style="text-align:center"><Katex tex="P_1=P_2,\qquad U_1I_1=U_2I_2" display /></p>
    <p>把电压比代进去，立刻得到电流比：</p>
    <p style="text-align:center"><Katex tex="\dfrac{I_1}{I_2}=\dfrac{n_2}{n_1}" display /></p>
    <p>两条比例关系方向相反：电压升高的那一侧电流小，电压降低的那一侧电流大。这也符合直觉——功率守恒，一侧电压高，另一侧就必须用更大的电流补上。</p>
    <p>注意电流比这一式只对<strong>单个副线圈</strong>成立。若有多个副线圈，能量守恒应写成 <Katex tex="U_1I_1=U_2I_2+U_3I_3+\cdots" />，或者按每匝电流守恒写成 <Katex tex="n_1I_1=n_2I_2+n_3I_3+\cdots" />，这时不能简单地把 <Katex tex="I_1/I_2" /> 写成 <Katex tex="n_2/n_1" />。</p>
    <p>副边的电流由负载决定：<Katex tex="I_2=U_2/R" />。因此变压器的输出功率不是固定的，而是随负载变化；原边的电流也跟着负载走。空载时副边没有电流，原边也只吸取很小的励磁电流，理想模型中取为零。</p>

    <h3 class="sec" id="a2-limit">变压器不能做什么</h3>
    <p>变压器的全部机制建立在「变化的磁通量」上。把原线圈接到恒定电流上，铁芯里的磁通量不随时间变化，副线圈没有感应电动势，输出为零。所以变压器对直流不起作用，这是它与分压电阻最本质的区别。</p>
    <p>变压器也不改变频率。副边电压的频率由原边的交变频率决定，我国市电 50 Hz 经变压之后仍是 50 Hz，只是幅值变了。波形在理想模型里也不变，实际变压器在大功率下会出现轻微畸变。</p>
    <p>它更不能放大功率。输入多少能量，输出就多少能量，升压的同时电流按同一比例减小，功率原样传过去。把变压器当成「省电装置」或者「放大功率的装置」，是把电压与功率混为一谈。</p>
    <p>实际变压器有效率，一般大型电力变压器在 95% 以上，小型的低一些。损耗来自线圈电阻的焦耳热、铁芯的涡流与磁滞，以及漏磁。计算题里没有特别说明时按理想变压器处理。</p>

