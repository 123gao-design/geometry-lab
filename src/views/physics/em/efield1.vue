    <h3 class="sec" id="e1-charge">两种电荷</h3>
    <p>用丝绸摩擦过的玻璃棒能吸引碎纸屑，用毛皮摩擦过的橡胶棒也能吸引碎纸屑，但两根玻璃棒互相排斥、两根橡胶棒也互相排斥，玻璃棒与橡胶棒却互相吸引。这说明电荷只有两种，而且遵循一条简单的规律：<strong>同种电荷相互排斥，异种电荷相互吸引</strong>。</p>
    <p>习惯上把用丝绸摩擦过的玻璃棒所带的电荷叫正电荷，把用毛皮摩擦过的橡胶棒所带的电荷叫负电荷。这个命名是历史沿用的，与电子本身带负电的事实并不冲突。</p>
    <p>检验物体是否带电用<strong>验电器</strong>：一根金属杆下端挂两片金属箔，上端连一个金属球。带电体靠近或接触金属球时，电荷传到箔片上，两片箔片带同种电荷互相排斥而张开；张开的角度越大，说明带的电荷越多。验电器只能判断是否带电与电荷多少，判断不了正负——要判断正负，可以先用已知带电体靠近，看箔片是张开得更大还是合拢一些。</p>

    <h3 class="sec" id="e1-make">起电的三种方式</h3>
    <p><strong>摩擦起电</strong>：两种不同材料的物体相互摩擦，束缚电子能力弱的物体失去电子带正电，能力强的物体得到电子带负电。摩擦的过程是电子的转移，而不是创造了电荷。</p>
    <p><strong>接触起电</strong>：不带电的导体与带电体接触，电荷在两者之间重新分配。两个完全相同的金属球接触后再分开，若它们原先带等量同种电荷，就平分总电荷；若带等量异种电荷，则电荷中和，都不带电。</p>
    <p><strong>感应起电</strong>：把带电体靠近一个不带电的导体，导体靠近带电体的一端出现异种电荷、远离的一端出现同种电荷，这叫静电感应。此时若把导体接地，远离端的那部分电荷被导入大地，再断开接地、移走带电体，导体就带上了与带电体异种的电荷。整个过程没有电荷穿过导体与带电体之间的空气，只是导体内部的自由电子发生了移动。</p>
    <p>三种方式表面上看差别很大，本质却是同一条：电荷从一个物体转移到另一个物体，或者在一个物体内部重新分布。没有任何一种起电方式创造出了电荷。</p>

    <h3 class="sec" id="e1-quant">电荷守恒与元电荷</h3>
    <p>大量实验表明，电荷既不能被创造，也不能被消灭，只能从一个物体转移到另一个物体，或者从物体的一部分转移到另一部分；在转移过程中，电荷的代数和保持不变。这就是<strong>电荷守恒定律</strong>。摩擦起电时，两根棒所带的电荷总是等量异号，加起来恰好为零，正是这条定律的直接证据。</p>
    <p>进一步的研究发现，电荷量并不是连续的，而是某个最小值的整数倍。这个最小值叫<strong>元电荷</strong>：</p>
    <p style="text-align:center"><Katex tex="e=1.60\times10^{-19}\ \text{C}." display /></p>
    <p>任何带电体所带电荷量都是 <Katex tex="e" /> 的整数倍，这叫电荷的<strong>量子化</strong>。密立根用油滴实验测出了这个值。电子带电荷量 <Katex tex="-e" />，质子带电荷量 <Katex tex="+e" />，1 C 的电荷量相当于约 <Katex tex="6.25\times10^{18}" /> 个电子的电荷量之和，可见宏观带电体上电子数目的巨大。</p>

    <h3 class="sec" id="e1-law">库仑定律</h3>
    <p>真空中两个静止点电荷之间的相互作用力，与它们的电荷量的乘积成正比，与它们之间距离的平方成反比，作用力的方向沿两者的连线。写成式子就是<strong>库仑定律</strong>：</p>
    <p style="text-align:center"><Katex tex="F=k\frac{q_1q_2}{r^2}." display /></p>
    <p>其中 <Katex tex="k" /> 是静电力常量，实验测得</p>
    <p style="text-align:center"><Katex tex="k=9.0\times10^{9}\ \text{N}\cdot\text{m}^2/\text{C}^2." display /></p>
    <p>式中的 <Katex tex="q_1" />、<Katex tex="q_2" /> 取电荷量的绝对值，方向由电荷的正负另行判断：同号相斥，异号相吸。两点电荷所受的力大小相等、方向相反，沿同一条连线，这也是一对作用力与反作用力，与牛顿第三定律一致。</p>
    <p>库仑定律的适用条件是<strong>真空</strong>中的<strong>点电荷</strong>。所谓点电荷，是指带电体本身的线度远小于它们之间的距离，形状与电荷分布对相互作用的影响可以忽略。带电小球在电荷均匀分布时，可以把全部电荷看成集中在球心，但前提是球心距远大于球的半径；两球靠得很近时这条近似就失效了。介质中的库仑力比真空中要小，方向不变，大小变成 <Katex tex="F=kq_1q_2/(\varepsilon_r r^2)" />，其中 <Katex tex="\varepsilon_r" /> 是介质的相对介电常数。</p>
    <p>把库仑定律与万有引力定律放在一起看：两条式子都写成「乘积除以距离平方」，都是平方反比律；区别在于质量只有一种，引力永远表现为吸引，而电荷分正负两种，力既可能相斥也可能相吸。这个区别使得电荷系统既可以互相排斥而趋于分散，也可以互相吸引而聚拢。</p>
    <PhysicsDemo :def="DEMO" />
    <p class="cap">图 电1a · <b>库仑定律</b>：左栏两个点电荷并排摆在一条水平线上，橙色带正电、蓝色带负电，紫色箭头是它们之间的库仑力，绿色箭头是各自的速度。看点一：默认一正一负，两电荷从静止松手、沿连线相向靠近，越近力越大，力箭头、加速度与速度箭头一起变长；把 q₁ 或 q₂ 拖过零变成同号，两电荷立刻相互推开，右栏橙点沿曲线向左下滑。看点二：把某个电荷拖到 0，两电荷都不动——不带电的电荷不受库仑力。看点三：拖「间距 r」改的是释放距离，松手后距离由运动自己决定，读数栏的「间距变化率 v」与「加速度 a = F/m」逐帧给出这一步的数和方向。看点四：读数栏最后一行「F·r²」滑到哪儿都不变，正是 F ∝ 1/r² 的直接核对；到达边界停一拍后从 r 重新放开，同一段过程可以反复看。</p>

    <h3 class="sec" id="e1-add">多个电荷的叠加</h3>
    <p>两个以上的点电荷同时存在时，任意一个电荷所受的合力，等于其他各个电荷单独对它作用力的矢量和，这叫<strong>力的独立作用原理</strong>，也叫叠加原理。具体做法是：先逐个算出每对电荷之间的力的大小与方向，再按平行四边形定则合成。</p>
    <p>计算时要抓住「两条线」：一是每个力都沿对应两点电荷的连线，方向由电荷正负决定；二是各个力之间按矢量相加，不能把大小直接相加。若几个电荷共线，可以把沿同一直线方向的力取正、反方向取负，化成代数和；若不共线，就要画出平行四边形或用正交分解。</p>

    <PhysicsDemo :def="DEMO2" />
    <p class="cap">图 电1b · <b>多个电荷的叠加</b>：两个场源电荷 q₁、q₂ 固定在一水平线上，考察点 P 取在连线的中垂线上，那里放一个试探电荷 q₀；橙、青两支箭头是 q₁、q₂ 各自对 q₀ 的库仑力 F₁、F₂，紫色箭头是合力 F。右栏把三支力平移到同一起点，补成平行四边形，对角线就是合力。看点一：把 P 的高度 h 拖小，两支力的夹角张开，合力按余弦定理变小；拖大 h，两支力趋于平行，合力接近 F₁ + F₂，但按三角形两边之和仍不大于 F₁ + F₂。看点二：把 q₁ 或 q₂ 拖成负数，那一支力从排斥改成吸引、箭头调头；两个场源电荷一正一负且电荷量相等时，两支力的竖直分量恰好抵消，合力落在水平方向上、指向负电荷那一侧。看点三：把试探电荷 q₀ 拖到 0，三支箭头一起消失——不带电的电荷不受库仑力；向右拖大 q₀，三支箭头一起变长而平行四边形形状不变。看点四：读数栏把 F₁、F₂、夹角 θ 与合力分行列出，「余弦定理合成」一行与它上面的合力相等，「两种算法之差」恒为 0，矢量相加与余弦定理是同一件事；切到「场强的合成」一档，同一幅图里换成两个电荷在 P 点产生的场强与合场强，此时改 q₀ 不再影响任何一支箭头——场强只由场源与位置决定。</p>

    <h3 class="sec" id="e1-apply">算一遍：两点电荷</h3>
    <p>真空中两个点电荷，<Katex tex="q_1=3.0\times10^{-6}\ \text{C}" />，<Katex tex="q_2=-2.0\times10^{-6}\ \text{C}" />，相距 0.20 m。先算力的大小：</p>
    <p style="text-align:center"><Katex tex="F=9.0\times10^{9}\times\frac{3.0\times10^{-6}\times2.0\times10^{-6}}{(0.20)^2}." display /></p>
    <p>分子上的乘积是 <Katex tex="6.0\times10^{-12}\ \text{C}^2" />，乘以 <Katex tex="k" /> 得 <Katex tex="5.4\times10^{-2}\ \text{N}\cdot\text{m}^2" />，再除以 <Katex tex="0.040\ \text{m}^2" />：</p>
    <p style="text-align:center"><Katex tex="F\approx1.35\ \text{N}." display /></p>
    <p>两个电荷异号，所以互相吸引，力的方向沿连线指向对方。读数栏的「F·r²」一行给出 0.054 N·m²，把距离拖到 0.10 m，这个数不变，而力变成 5.4 N——距离减半，力增到四倍，这就是平方反比律。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把 r 当成两个球面之间的距离。</strong>库仑定律里的 r 是两个点电荷之间的距离，两个带电小球要取球心距。只有在球心距远大于球半径时，才能把球上的电荷看成集中在球心；两球靠得很近时，电荷会因相互吸引或排斥而重新分布，这条式子就不能直接用了。</li>
        <li><strong>提示二：混淆力的方向与电荷守恒。</strong>「同号相斥、异号相吸」说的是力的方向；电荷守恒说的是电荷的代数和不变。摩擦起电时两个物体带等量异号电荷，这是守恒的结果，与它们互相吸引是两件事。</li>
        <li><strong>提示三：以为库仑定律在任何距离都成立。</strong>它是真空里两个点电荷之间的规律。距离很小时带电体不能再看成点电荷；放进介质里，力要除以相对介电常数，比真空中更小。</li>
        <li><strong>提示四：算合力时把大小直接相加。</strong>库仑力是矢量，多个电荷对同一点电荷的作用要按平行四边形定则合成。共线时可以取正负化成代数和，不共线时不能省掉方向。</li>
      </ul>
