    <h3 class="sec" id="e6-prin">原理：周期只与摆长和 g 有关</h3>
    <p>摆球偏离平衡位置一个小角度 θ 时，重力沿圆弧切向的分量为 mg·sinθ，它指回平衡位置。小角情形下 sinθ ≈ θ ≈ s/L，回复力与位移成正比，比例系数是 mg/L，于是</p>
    <p style="text-align:center"><Katex tex="T=2\pi\sqrt{\frac{L}{g}}" display /></p>
    <p>这个式子给出三点信息。其一，周期与摆球质量无关；其二，周期与摆角无关（在小角前提下）；其三，周期只由摆长与当地的重力加速度决定。第三点正是本实验的依据，把它改写一下：</p>
    <p style="text-align:center"><Katex tex="g=\frac{4\pi^2L}{T^2}" display /></p>
    <p>再把两边平方，得到适合作图的线性形式：</p>
    <p style="text-align:center"><Katex tex="T^2=\frac{4\pi^2}{g}\,L" display /></p>
    <p>以 L 为横轴、T² 为纵轴，图线应当是一条过原点的直线，斜率 <Katex tex="k=4\pi^2/g" />。由斜率求 g，比单组数据直接代入更可靠：作图的点来自多次测量，单个点的误差被平均掉，纵截距是否为零还能反过来检验摆长量得对不对。</p>
    <p>「小角」有定量界限。严格解表明周期随摆角略有增大：</p>
    <p style="text-align:center"><Katex tex="T\approx T_0\left(1+\frac{\theta_0^2}{16}\right)" display /></p>
    <p>摆角 5° 时修正量约万分之三，10° 时约千分之二，15° 时约千分之五。中学实验要求摆角小于 5°，就是为了把这一项压到可以忽略的程度。</p>

    <h3 class="sec" id="e6-step">器材与步骤：量摆长、计时</h3>
    <p>器材：细线、小球、铁架台与铁夹、米尺、游标卡尺、秒表。</p>
    <p>把细线的一端系在小球上，另一端夹在铁夹上，悬点要固定牢靠、不能随摆动松动。用游标卡尺量出小球的直径，取一半得到半径；用米尺量出悬点到球顶的线长。两者相加才是摆长：</p>
    <p style="text-align:center"><Katex tex="L=l+\frac{d}{2}" display /></p>
    <p>其中 <Katex tex="l" /> 是悬点到球顶的线长，<Katex tex="d/2" /> 是摆球半径。</p>
    <p>摆长在 1 m 左右比较合适：太短则周期小、计时误差相对放大；太长则摆动不稳、空气阻力影响加重。</p>
    <p>把摆球拉开一个小角度（不超过 5°）后由静止释放，不要给初速度，否则摆球会在竖直面之外打转。等摆动稳定后开始计时：从摆球经过最低点开始按表，数到 30 次或 50 次全振动时再按停。经过最低点时摆球速度最大、位置最容易判定，起止点都选在这一位置，可以减小人工计时的判读误差。</p>
    <p>全振动的意思是摆球回到出发时的位置、并沿同一方向运动，一次完整的往返算一次；只数「单程」会把周期算成一半。计时结束时把总时间除以次数得到周期：</p>
    <p style="text-align:center"><Katex tex="T=\frac{t}{n}" display /></p>
    <p>改变摆长，重复测若干组，摆长覆盖 0.3 m 到 1.5 m 一段，每组都测 30 次以上。</p>

    <h3 class="sec" id="e6-data">数据处理：T²–L 图线</h3>
    <p>把每组数据算成 T 与 T²，以 L 为横轴、T² 为纵轴描点，用直线拟合。若图线过原点，说明摆长的零点取对了；若与纵轴有正截距，多半是摆长少算了球半径或者悬点位置取得偏下。</p>
    <p>取直线上相距较远的两点求斜率，再由 <Katex tex="g=4\pi^2/k" /> 算出重力加速度。也可以逐组用 <Katex tex="g_i=4\pi^2L_i/T_i^2" /> 求值再取平均，两种结果应当接近；斜率法的抗干扰能力更强。</p>
    <p>作为对照，用单摆周期公式反算的 g 应当与当地公认值落在同一个百分数区间内。若结果偏高，先查摆长是否量短了；若偏低，先查摆角是否太大、空气阻力是否明显。</p>

