    <p class="cap">图 实6 · <b>单摆与 T²–L 图</b>：左栏是悬挂的单摆，绿色标注给出悬点到球心的摆长 L，橙色弧标出最大摆角 10°，下方秒表记录 30 次全振动的用时；右栏以 L 为横轴、T² 为纵轴，蓝点是各摆长下的数据，橙点是当前摆长，绿虚线是理论直线。看点一：默认 L = 1.00 m，读数栏给出周期 2.007 s、30 次全振动约 60.2 s，反推的 g 正好是 9.8 m/s²。看点二：把摆长拖短，摆球画得更高、摆动更快，周期变短，右栏橙点沿直线向原点滑去。看点三：T²/L 一行始终等于 4π²/g，与摆长无关——这正是 T² 与 L 成正比的读法。看点四：图线过原点，说明摆长量到球心之后，剩下的关系确实是正比；若把球半径漏掉，所有点会整体左移，图线就不再严格过原点。</p>

    <h3 class="sec" id="e6-err">误差：摆长、摆角与计时</h3>
    <p>摆长是最容易出错的量。漏掉球半径会让 L 偏小，反推的 g 也跟着偏小；用米尺量时若从球顶量到悬点的铁夹外侧，又会让 L 偏大。规范做法是从悬点量到球心，或量到球顶再加半径。</p>
    <p>摆角过大是第二项系统误差。从上面的修正式可以看出，摆角越大周期越长，反推的 g 会系统性地偏小。控制摆角在 5° 以内，并且保证摆球在同一个竖直平面内摆动，不打转。</p>
    <p>计时误差来自人的反应时间。单次周期只有两秒左右，起停两次的反应时间可能就占十分之一，因此必须测多次全振动再取平均。次数越多、相对误差越小；30 到 50 次是常见的取值。</p>
    <p>空气阻力与悬点的微小松动也会影响结果。摆球越小、摆线越细，阻力越小；铁夹若随摆动松动，悬点实际在移动，摆长与周期都不稳。实验前要检查悬点是否牢固。</p>

