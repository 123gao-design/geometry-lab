      <ul class="tip-list">
        <li><strong>提示一：把摆线长当成摆长。</strong>单摆公式中的 L 是悬点到球心的距离，等于线长加球半径。漏掉半径时 L 偏小百分之几，g 就偏小同样的比例，这是满盘皆错的一步。</li>
        <li><strong>提示二：把一次往返算成一次振动。</strong>全振动要回到出发位置并沿同一方向运动。把单程当成一个周期，算出的周期只有真实值的一半，g 会差出四倍。</li>
