      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：以为必须先用天平称重物的质量。</strong>验证式两边都含 m，约掉之后只剩 ½v² 与 gh，本实验与质量无关。称质量只在对整条纸带逐点核对某一具体能量值时才有用。</li>
        <li><strong>提示二：用「第一个点是静止释放点」作为前提。</strong>振针打下第一个点时重物往往已有速度，把该点当作零速度点会让 ½v² 与 gh 同时偏小。稳妥的做法是任取两点比较增量，或挑第一、二点间距接近 2 mm 的纸带。</li>
        <li><strong>提示三：把计时器装歪。</strong>纸带倾斜会加大与限位孔之间的摩擦，实测动能偏小，看似「守恒不成立」，其实是装置问题。组装时用铅垂线或目测把计时器调竖直。</li>
        <li><strong>提示四：直接把误差全归给「读数不准」。</strong>若所有数据一致偏小、且偏差随下落距离单调增大，这是阻力作用的特征，不是读数问题。读数误差只让数据在直线两侧散开。</li>
        <li><strong>提示五：松手时用手托着重物往下送。</strong>托着送会带入额外的初速度或使重物不走直线，纸带头几个点的间距不再接近 2 mm。正确做法是捏住纸带上端，松手让它自由下落。</li>
