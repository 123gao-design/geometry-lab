    <h3 class="sec" id="e3-prin">原理：自由落体中的能量转化</h3>
    <p>重物从静止释放、只受重力，下落高度 <Katex tex="h" /> 时速度满足</p>
    <p style="text-align:center"><Katex tex="v^2=2gh" display /></p>
    <p>这个式子由运动学直接得来，也可以从能量角度看：重力做功 <Katex tex="mgh" /> 全部转化为动能，于是 <Katex tex="mgh=\tfrac{1}{2}mv^2" />。两种写法是一回事，但能量视角把结论推广到了受力更复杂、只要能写成「保守力做功」的情形。</p>
    <p>实验要验证的形式是</p>
    <p style="text-align:center"><Katex tex="\frac{1}{2}v^2=gh" display /></p>
    <p>左边是单位质量上的动能，右边是单位质量上减少的重力势能，量纲都是焦耳每千克。这样写的好处是不必测量质量，重物的质量取多少都不影响结论，质量只决定各项的绝对数值。</p>
    <p>若以某个计数点 <Katex tex="n" /> 为研究对象，速度由它前后相邻的两个点求出。设这三点到起始点的距离依次为 <Katex tex="h_{n-1}" />、<Katex tex="h_n" />、<Katex tex="h_{n+1}" />，则</p>
    <p style="text-align:center"><Katex tex="v_n=\frac{h_{n+1}-h_{n-1}}{2T_0}" display /></p>
    <p>这仍然是「平均速度等于中间时刻瞬时速度」那条性质。若纸带的第一个点就是释放点（速度为零），也可以只取起点与某点两处，用 <Katex tex="\tfrac{1}{2}v_n^2=gh_n" /> 验算，此时 h 直接读该点到第一个点的距离。</p>
    <p>实际纸带的第一个点往往不是严格的释放点。振针打下第一个点时重物已有微小速度，因此更稳妥的做法是任取两个计数点 A、B 作比较：</p>
    <p style="text-align:center"><Katex tex="\frac{1}{2}v_B^2-\frac{1}{2}v_A^2=g\,(h_B-h_A)" display /></p>
    <p>这样就不依赖起点是否严格静止，验证的仍是「动能的增量等于势能的减少量」。</p>

    <h3 class="sec" id="e3-step">器材与操作步骤</h3>
    <p>器材：铁架台、打点计时器、学生电源、纸带、重物（带纸带夹）、复写纸、毫米刻度尺。</p>
    <p>组装时把打点计时器竖直固定在铁架台上，限位孔朝下，纸带从下往上穿过限位孔并压在复写纸下面，纸带下端夹住重物。用手捏住纸带上端把重物提到靠近计时器的位置，先接通电源，待打点稳定后松手，重物带着纸带自由下落，纸带上留下一串点距递增的点。</p>
    <p>计时器必须竖直。若倾斜安装，纸带与限位孔之间产生额外摩擦，重物还受到侧向的挤压，实测的动能会系统性地偏小。同理，纸带要保持平直，不能有折痕，否则它在限位孔里的阻力时大时小。</p>
    <p>纸带的选取标准是点迹清晰、第一、二两点间距接近 2 mm。间距约 2 mm 说明第一个点附近重物的速度确实接近零，因为它对应的时间只有一个打点周期，而 0.02 s 内自由落体的位移是 <Katex tex="\tfrac{1}{2}\times9.8\times0.02^2\approx2\,\mathrm{mm}" />。若开头几个点挤成一片，说明松手时已有初速度，这样的纸带应换掉。</p>

    <h3 class="sec" id="e3-data">数据处理：以 h 为横轴</h3>
    <p>在纸带上取若干计数点，用刻度尺量出各点到起始点的距离 <Katex tex="h_n" />，按上一节的式子求出各点速度 <Katex tex="v_n" />，再算出 <Katex tex="\tfrac{1}{2}v_n^2" />。把这两个量并排列成表，逐行比较；若每行的差都在测量误差允许的范围内，就说明两者相等。</p>
    <p>作图的做法更直观。以 <Katex tex="h" /> 为横轴、<Katex tex="\tfrac{1}{2}v^2" /> 为纵轴描点：理论关系是过原点、斜率为 <Katex tex="g" /> 的直线，实测点应落在这条线附近。斜率一旦偏离 9.8 m/s² 较多，就意味着系统误差明显；若各点整体在直线下方，那是阻力在起作用。</p>

    <PhysicsDemo :def="DEMO" />
    <p class="cap">图 实3 · <b>纸带与 ½v²–h 图</b>：左侧一根竖直标尺，重物的位置由下落高度 h 决定，纸带上每隔 0.05 m 有一个点；右栏橙点是逐点算出的 ½v²，绿虚线是理论上的 gh。看点一：默认 h = 0.60 m，读数栏给出 t = 0.35 s、v = 3.43 m/s，½v² 与 gh 都是 5.88 J/kg，两行数字完全相同。看点二：两条线在整个区间上贴着走，说明动能与势能的转化是按比例发生的，不是只在终点凑巧相等。看点三：把 h 拖小，两条线一起缩短，斜率不变——斜率就是 g，与下落多高无关。看点四：任意把水平虚线往上提，交点处 ½v² 与 gh 仍然相等，这正是「任一位置机械能都守恒」的意思。</p>

    <h3 class="sec" id="e3-err">误差：实测值为何略小</h3>
    <p>最要紧的一项系统误差是阻力。纸带与限位孔之间有摩擦，重物还受到空气阻力，这些力做负功，一部分重力势能变成了内能而没有全部转成动能，所以实测的 <Katex tex="\tfrac{1}{2}v^2" /> 总是略小于 <Katex tex="gh" />，且下落越远、差距越大。</p>
    <p>另一项系统误差来自「用平均速度代替瞬时速度」。严格地说，<Katex tex="(h_{n+1}-h_{n-1})/(2T_0)" /> 给出的是区间中点的瞬时速度；因为该中点在时间上恰好与计数点 n 重合，这一近似在匀加速情形下是精确的，不引入误差。真正需要注意的是判读：纸带上的点有大小，点的中心位置估计不准，会给每个 h 带来零点几毫米的误差，求差时又可能被放大。</p>
    <p>还有一项容易被忽略：若起始点不是严格的静止点，<Katex tex="\tfrac{1}{2}v^2" /> 与 <Katex tex="gh" /> 的绝对值都会偏大，两条线整体平行上移，差值反而看不太出来。所以判读时更该看两点之间的增量关系，而不是只看绝对值是否相等。</p>

