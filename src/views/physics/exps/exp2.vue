    <h3 class="sec" id="e2-prin">原理：控制变量与两条关系</h3>
    <p>小车在长木板上由跨过定滑轮的细线拉着，另一端挂砂桶。忽略绳与滑轮的质量、忽略摩擦，把小车与砂桶看成一个整体，整体受到的合外力就是砂桶的重力，于是</p>
    <p style="text-align:center"><Katex tex="a=\frac{mg}{M+m}" display /></p>
    <p>其中 <Katex tex="m" /> 是砂桶与砂的总质量，<Katex tex="M" /> 是小车的质量。绳对小车的拉力则由小车一侧单独写出：</p>
    <p style="text-align:center"><Katex tex="F_T=Ma=mg\cdot\frac{M}{M+m}" display /></p>
    <p>可见拉力总比砂桶的重力小一点，两者的相对差距是 <Katex tex="m/(M+m)" />。当 <Katex tex="m\ll M" /> 时，这个差距可以忽略，绳的拉力近似等于砂桶的重力。实验中通常要求砂桶与砂的总质量不超过小车的十分之一，这就是「砂桶质量远小于小车」这条要求的来历。</p>
    <p>把砂桶重力当作拉力 <Katex tex="F" /> 之后，两条待检验的关系都在同一式子里：</p>
    <p style="text-align:center"><Katex tex="a=\frac{F}{M}=\frac{1}{M}\,F=F\cdot\frac{1}{M}" display /></p>
    <p>固定 <Katex tex="M" /> 改变 <Katex tex="F" />，a 与 F 成正比，比例系数为 <Katex tex="1/M" />；固定 <Katex tex="F" /> 改变 <Katex tex="M" />，a 与 <Katex tex="1/M" /> 成正比，比例系数为 <Katex tex="F" />。两个比例系数都由另一条图线的斜率互相印证。</p>
    <p>还有一项必须处理：木板与小车之间有摩擦。若存在大小为 <Katex tex="f" /> 的阻力，则 <Katex tex="F-f=Ma" />，a–F 图线不经过原点，而是在横轴上截出一段。把木板在不挂滑轮的一端垫高，让重力沿斜面的分量恰好抵消摩擦，图线才回到过原点的位置。这一操作叫平衡摩擦，判断标准是：不挂砂桶时轻推小车，小车能沿木板匀速下滑。</p>

    <h3 class="sec" id="e2-step">器材与操作步骤</h3>
    <p>器材：长木板、小车、打点计时器、纸带、学生电源、砂桶与砂、细线、定滑轮、天平、毫米刻度尺。</p>
    <p>步骤依次是：用天平称出小车的质量；把长木板一端垫高，平衡摩擦并检验；按图组装装置，细线跨过定滑轮、与木板平行；把纸带接在小车后面并穿过限位孔；先接通电源，再释放小车，打出一条纸带；保持小车质量不变，逐次增加砂桶中的砂，打出若干条纸带；再保持砂桶质量不变，逐次在小车上加砝码改变总质量，同样打出若干条纸带。</p>
    <p>每换一个质量组合都要重新跑一次，纸带与工况一一对应，记录时把砂桶质量、小车总质量一并写在同一行，否则事后数据无法归位。砂桶的质量要连着砂一起称，加砂时把砂桶从线上取下称好再挂回，不要凭估计。</p>
    <p>平衡摩擦是一项容易被敷衍的步骤。垫高的角度要反复调：轻推小车，小车若加速下滑说明垫得过高，若很快停下说明垫得不够；调到小车能连续、平稳地滑完整块木板，才算平衡好了。改变小车质量之后，若在小车上加的是较重的砝码，重心变化可能影响摩擦，必要时重新检验一次。</p>

    <h3 class="sec" id="e2-data">数据处理：a–F 图与 a–1/m 图</h3>
    <p>每条纸带都用打点计时器那一章的逐差法求出加速度：</p>
    <p style="text-align:center"><Katex tex="a=\frac{(s_4+s_5+s_6)-(s_1+s_2+s_3)}{9T_0^2}" display /></p>
    <p>用天平称出的砂桶总质量乘以 <Katex tex="g" /> 得到拉力 <Katex tex="F" />；小车总质量取小车质量加砝码质量。第一组数据画 a–F 图：横轴是 F、纵轴是 a，各点应落在一条过原点的直线上，斜率是 <Katex tex="1/M" />。第二组数据画 a–1/M 图：横轴是质量的倒数，各点同样落在过原点的直线上，斜率是 <Katex tex="F" />。</p>
    <p>作图时用一条直线拟合全部点，不要逐段连线。若某条图线在 F 较大的一端向下弯曲，说明砂桶的质量已经不再远小于小车，拉力与砂桶重力的差距变得明显；这时应减少砂的质量重新测，而不是把弯的那几个点舍掉。若图线不过原点而与横轴有交点，那是摩擦没有平衡干净，交点对应的横坐标正是摩擦力的大小。</p>

