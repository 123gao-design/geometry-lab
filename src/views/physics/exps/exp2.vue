    <h3 class="sec" id="e2-err">误差来源：砂桶质量与摩擦</h3>
    <p>第一项系统误差来自「用砂桶重力代替绳的拉力」。前面已经算出真实拉力是 <Katex tex="mgM/(M+m)" />，比砂桶重力小。砂的质量越大、小车越轻，这一项偏差越大，所以 a–F 图线在大 F 一端向下弯。控制的方法是把砂桶质量压在小车质量的十分之一以内，或者改用力的传感器直接测量绳的拉力。</p>
    <p>第二项系统误差来自摩擦。平衡摩擦做得不彻底，图线会与横轴相交；垫得过高，图线则会与纵轴相交，甚至出现不挂砂桶小车也加速的情形。这两种偏差方向相反，都说明平衡这一步没有做对。</p>
    <p>偶然误差来自纸带的测量与判读。点迹不清、刻度尺估读不准、计数点选错，都会让个别 a 值偏离。多打几条纸带、每条都认真取点，可以把这一项压下去；同一条工况重复测得几个 a 再取平均，效果更直接。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把砂桶的重力直接当成绳的拉力。</strong>只有当砂桶质量远小于小车质量时这一近似才成立。严格算下来拉力是 mg·M/(M+m)，永远小于 mg；F 越大、M 越小，偏差越明显，图线末端会向下弯。</li>
        <li><strong>提示二：忘记平衡摩擦，或以为可以靠计算删掉。</strong>摩擦若不抵消，F − f = Ma 中的 f 是个未知量，图线既不过原点、斜率也不干净，无法同时交代两条关系的比例系数。</li>
        <li><strong>提示三：改变小车质量后仍沿用原来的平衡角。</strong>加砝码后小车对木板的压力变大，摩擦随之变大，原先垫好的角度可能不再合适。加的质量较大时要重新检验一次匀速下滑。</li>
        <li><strong>提示四：把 a–m 图当成反比曲线来验证。</strong>a 与 m 的关系是双曲线，光看图很难判断是不是反比；改成以 1/m 为横轴，关系才化为过原点的直线，直线是最好判读的形式。同类处理在气体的等温变化、单摆的 T²–L 中反复出现。</li>
        <li><strong>提示五：细线没有与木板平行。</strong>细线若向上或向下倾斜，拉力会产生垂直于木板的分量，改变小车受到的约束力，测出的加速度既不是 F/M、也不是装置示意图上那个理想的 a。组装时应目测细线与木板平行。</li>
      </ul>
