    <p>回收与预告：本章与测折射率、测电动势同属一类实验——把一个测不到的量，换成几个能量得的量的组合。区别在于这一次被换掉的是「光的波长」这件东西本身：它既不是长度也不是时间，而是一列波的空间周期，只有让它自己与自己干涉才有办法读出来。下一章暂时离开具体的仪器，讲这些读数最终要怎么记录：误差从哪里来、有效数字该留几位、什么时候多留一位是假精确。</p>
