    <p class="cap">图 实11 · <b>用双缝干涉测波长</b>：左栏是俯视的光路——紫色圆点是单色光源，中间画着两条缝的竖直挡板是双缝、缝距标为 d，右端是屏，屏上橙色的明暗条带就是干涉条纹，颜色越浓处光强越大；橙色细线从两条缝连到屏上的 P 点，紫色短杠量出该处相邻两条亮纹的距离 Δx，底部双箭头量屏距 L。右栏是屏上的光强分布，纵轴是屏上位置（以中线为零，单位 mm，视场取 ±12 mm），横轴是相对光强 I/I₀；曲线是一串等宽的峰，绿色小点标出每条亮纹的位置。看点一：默认 λ = 550 nm、d = 0.20 mm、L = 1.00 m，读数栏给 Δx = 2.75 mm，±12 mm 内共 9 条亮纹，反算波长仍是 550 nm。看点二：把 λ 拖到 700 nm（红光），Δx 增到 3.50 mm，条纹变稀、变宽；拖到 400 nm（紫光）则降到 2.00 mm，条纹变密。看点三：把 d 拖到 0.40 mm，Δx 降为 1.38 mm，条纹成倍变密——缝距越大，两束光的相位差随位置变化越快。看点四：把 L 拖到 2.0 m，Δx 增到 5.50 mm；右栏的峰仍然等间距，只是变稀，证实间距只由 λL/d 决定、与级数无关。</p>

    <p>顺带说明一件事：白光做这个实验时，屏中央是白色亮纹，两侧出现由紫到红的彩色条纹，而第二级以后各色互相重叠，整片就成了白色。原因就在 <Katex tex="\Delta x = \lambda L/d" />：同一级条纹中紫光的间距最小、红光最大，条纹越往外错开越多，最终彼此交叠。所以测波长必须用单色光。</p>

    <h3 class="sec" id="e11-err">误差：条纹读数与三个量的精度</h3>
    <p>三个量里，<Katex tex="\Delta x" /> 的测量是主要误差来源，但它也是三者中唯一能通过「多数几条」来改进的量。</p>
    <p>条纹中心的判定靠分划板的十字线对准，人眼判断亮纹中心有一定的不确定度。<Katex tex="\Delta x" /> 只有一两毫米，若只测相邻两条，这个不确定度在结果里占的比重相当大；测 <Katex tex="n" /> 条后除以 <Katex tex="n" />，绝对误差被缩小 <Katex tex="n" /> 倍。但这只对「对准同一条纹时的随机误差」有效，若第一个读数的条纹数就数错了一条，误差会成倍地带进结果——所以计数的准确性比重复次数更重要，测完应回测一次核对。</p>
    <p><Katex tex="L" /> 的测量误差来自「双缝到光屏」这一段的认定。装遮光筒之后再量，两端要对准双缝所在的平面与光屏所在的平面，不要量到遮光筒的外壳或目镜的位置上。<Katex tex="d" /> 用标称值，其误差由仪器的加工精度决定，通常远小于 <Katex tex="\Delta x" /> 与 <Katex tex="L" /> 的相对误差，可以不计。</p>
    <p>按相对误差的传递，<Katex tex="\lambda" /> 的相对误差约等于三项相对误差之和：<Katex tex="\dfrac{\Delta\lambda}{\lambda} = \dfrac{\Delta d}{d}+\dfrac{\Delta(\Delta x)}{\Delta x}+\dfrac{\Delta L}{L}" />。三项中哪一项的影响最大，就看哪一项的相对误差最大——多数情况下是参量 <Katex tex="\Delta x" />。</p>
    <p>还有几条系统性因素：单缝与双缝不平行、各件不共轴时，条纹本身就已经变形，读数再准也没有意义；单缝过宽时条纹对比度下降，峰变得平缓，中心反而更难对准；测量过程中若碰动了仪器，<Katex tex="L" /> 与条纹的位置都会变，必须重新调共轴。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：只量相邻两条亮纹的间距。</strong>一两毫米的间距配上游标尺的读数误差，相对误差可达百分之几甚至更高。应当让十字线跨过十条以上亮纹，用总距离除以跨越的间隔数，误差被同一比例缩小。</li>
        <li><strong>提示二：把跨越的条纹数当成间隔数。</strong>从第一条亮纹移到第 <Katex tex="n" /> 条亮纹，跨越的是 <Katex tex="n-1" /> 个间距；多数一条或少除一个，结果就偏出 <Katex tex="1/(n-1)" />。计数时把第一条数作零，一条一条数「跨过了几个间距」。</li>
        <li><strong>提示三：用白光做实验去测波长。</strong>白光的各色条纹间距不同，中央亮纹之外各色立刻错开重叠，很少能看到清晰的彩色以外的条纹，更没有单一条纹中心可对准。测波长必须加单色滤光片。</li>
        <li><strong>提示四：单缝与双缝不平行、或各件不共轴。</strong>条纹会变得模糊、歪斜甚至消失。装上双缝后要先调共轴再调平行，确认视野中央有一组清晰的等间距条纹，之后才开始读数。</li>
        <li><strong>提示五：把 <Katex tex="L" /> 量成双缝到目镜的距离。</strong>公式里的 <Katex tex="L" /> 是双缝到光屏的距离。遮光筒内部有透镜与光屏，量尺要量到光屏所在的位置，不能拿筒长或到目镜的距离顶替。</li>
      </ul>
