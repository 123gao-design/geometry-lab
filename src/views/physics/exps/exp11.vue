    <h3 class="sec" id="e11-prin">原理：路程差与明暗条纹的位置</h3>
    <p>相干光源在实验室里不容易直接得到，双缝解决了这一点。让一束单色光先照到一条单缝上，单缝成为点状光源；它发出的光再照到两条靠得很近的狭缝，这两条缝就相当于两个光源——它们由同一束光分出，频率相同，相位差始终不变，是相干光源。</p>
    <p>设两条缝的距离为 <Katex tex="d" />，屏到双缝的距离为 <Katex tex="L" />，屏上一点 <Katex tex="P" /> 到屏中央（中线）的距离为 <Katex tex="y" />。从两条缝到 <Katex tex="P" /> 的两条光线长度不等，差值记为 <Katex tex="\Delta r" />。实验中 <Katex tex="L" /> 远大于 <Katex tex="d" /> 与 <Katex tex="y" />，两条光线几乎平行，与中线的夹角记作 <Katex tex="\theta" />，则</p>
    <p style="text-align:center"><Katex tex="\Delta r = d\sin\theta \approx d\tan\theta = d\,\frac{y}{L}" display /></p>
    <p>叠加的结果只由路程差决定：<Katex tex="\Delta r = k\lambda" />（<Katex tex="k=0,\pm1,\pm2,\dots" />）处两束光同相，光强最大，屏上是亮纹；<Katex tex="\Delta r = (k+\tfrac12)\lambda" /> 处相差半个波长，光强最小，是暗纹。把亮纹条件代回上式，得到亮纹的位置</p>
    <p style="text-align:center"><Katex tex="y_k=k\frac{\lambda L}{d}" display /></p>
    <p>各条亮纹的位置与级数 <Katex tex="k" /> 成正比，相邻两条相隔 <Katex tex="\Delta x = y_{k+1}-y_k = \lambda L/d" />，与 <Katex tex="k" /> 无关——这正是屏上看到的那一排等间距的条纹。条纹关于中线对称，正中的 <Katex tex="k=0" /> 处路程差为零，是最亮的中央亮纹。</p>
    <p>把公式反过来读，就是这台实验的全部意义：<Katex tex="\lambda = d\,\Delta x/L" />。波长在 <Katex tex="10^{-7}" /> m 量级，任何尺子都直接量不到；而 <Katex tex="\Delta x" /> 在毫米量级、<Katex tex="d" /> 与 <Katex tex="L" /> 也各有现成的量法，于是波长变成了一次厘米尺与游标卡尺的读数。双缝干涉因此第一次给出光的波长的实测值，也是光具有波动性的直接证据。</p>

    <h3 class="sec" id="e11-step">器材与步骤：调共轴、找条纹、量间距</h3>
    <p>器材：双缝干涉实验仪（光源、滤光片、单缝、双缝、遮光筒、测量头）、米尺。光源装在最前，其后依次是滤光片、单缝、双缝，最后是遮光筒与光屏；测量头装在遮光筒的观察端，可以沿垂直于光轴的方向平移，并带刻度读出移动的距离。</p>
    <p>第一步，调共轴。让光源、单缝、双缝与遮光筒的中心在同一条直线上，视线从目镜里看过去各件应当同轴。各件的高度与水平位置都要调，偏了以后条纹不在视野中央，甚至看不到。</p>
    <p>第二步，调单缝与双缝平行。单缝的缝宽可以调，调得太宽条纹对比度变差、太窄则亮度不足；转动单缝的调节螺钉使它与双缝严格平行，否则两条缝照到光的相位关系不再对应同一时刻，条纹会模糊成一片。</p>
    <p>第三步，装上双缝、透过目镜观察。先不装滤光片时看到的是彩色条纹，各色条纹互相错开叠在一起，测不出间距；换上单色滤光片，屏上就出现一组等间距的明暗条纹，中央最亮，向两侧逐渐变暗而间距不变。</p>
    <p>第四步，量条纹间距。旋动测量头的手轮，让分划板的十字线对准某一条亮纹的中心，记下读数；再让十字线依次移过若干条亮纹，数出移动过的条纹数 <Katex tex="n" />，记下总读数。两读数之差 <Katex tex="a" /> 是 <Katex tex="n" /> 个条纹间距，于是</p>
    <p style="text-align:center"><Katex tex="\Delta x=\frac{a}{n}" display /></p>
    <p>这一步是整台实验的关键。只测相邻两条亮纹的间距时，间距本身只有一两毫米，读数误差在结果里的比重很大；改成测十条、二十条再除，同样的读数误差被摊薄到十分之一、二十分之一。注意数条纹时要数「间隔数」而不是「条纹数」：从第一条亮纹移到第十一条亮纹，跨越的是十个间距。</p>
    <p>第五步，量 <Katex tex="d" /> 与 <Katex tex="L" />。双缝间距 <Katex tex="d" /> 是仪器的标称值，一般印在双缝的支架上；<Katex tex="L" /> 用米尺量双缝到光屏的距离，且要在装上遮光筒之后再量。</p>
    <p>为了检验结果，可以换一块不同 <Katex tex="d" /> 的双缝重做，或者改变 <Katex tex="L" /> 再测一次。多组数据既可以取平均，也可以作 <Katex tex="\Delta x" />–<Katex tex="L" /> 图：由 <Katex tex="\Delta x = (\lambda/d)L" />，各点落在一条过原点的直线上，斜率是 <Katex tex="\lambda/d" />，由此求出的波长不受单次 <Katex tex="L" /> 读数误差的影响。</p>

    <h3 class="sec" id="e11-data">数据处理：Δx = λL/d 与反算波长</h3>
    <p>把每组数据先算出条纹间距 <Katex tex="\Delta x = a/n" />，再由</p>
    <p style="text-align:center"><Katex tex="\lambda=\frac{d\,\Delta x}{L}" display /></p>
    <p>求出波长。若换用不同 <Katex tex="d" /> 或不同 <Katex tex="L" /> 做了几组，波长应当基本一致，取其平均值作为结果。</p>
    <p>作图的版本是：横轴取 <Katex tex="L" />，纵轴取 <Katex tex="\Delta x" />，各点应落在一条过原点的直线上，斜率 <Katex tex="k = \Delta x/L = \lambda/d" />，于是 <Katex tex="\lambda = k d" />。作图的好处与前面几章相同：单点的误差被整条直线平摊，偏离直线的点也容易发现——若某组点整体偏高，先回查那一组的条纹计数是否多数或少数了一条。</p>
    <p>结果的量级值得记住。红光波长约 700 nm，紫光约 400 nm，可见光落在 400 到 700 nm 之间；实验中 <Katex tex="\Delta x" /> 通常是一两毫米，<Katex tex="d" /> 是零点几毫米，<Katex tex="L" /> 是 1 m 上下，代进公式算出的正是几百纳米。</p>

