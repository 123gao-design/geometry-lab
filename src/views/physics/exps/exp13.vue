    <h3 class="sec" id="e13-prin">原理：游标把 1 mm 再细分</h3>
    <p>主尺的量法是固定的：被测物两端各落在一个刻度上，两端之间的毫米数由刻线数出来，剩下不足一格的部分靠眼睛估。估读的可靠程度受限于人眼，通常到十分之一格。游标卡尺要做的，就是把「不足一格的那部分」交给刻线自己去比。</p>
    <p>设游标有 <Katex tex="n" /> 个格子、总长 <Katex tex="n-1" /> mm，相邻两格间距为 <Katex tex="\frac{n-1}{n}" /> mm。把它贴着主尺放置时，游标第 <Katex tex="j" /> 格的位置比主尺第 <Katex tex="j" /> 条毫米线少 <Katex tex="\frac{j}{n}" /> mm。也就是说，游标相对主尺每往右挪 <Katex tex="\frac{1}{n}" /> mm，就往下换一格与主尺对齐。若游标零线落在主尺 <Katex tex="m" /> 与 <Katex tex="m+1" /> 之间、距 <Katex tex="m" /> 为 <Katex tex="f" />（<Katex tex="0\le f<1" /> mm），那么第 <Katex tex="k" /> 格恰好压在主尺刻线上的条件是</p>
    <p style="text-align:center"><Katex tex="f=\frac{k}{n}\quad\Longrightarrow\quad L=m+\frac{k}{n}" display /></p>
    <p>对齐的那一格把 <Katex tex="f" /> 直接写成了 <Katex tex="\frac{k}{n}" />：格数乘以 <Katex tex="\frac{1}{n}" /> mm 就是小数部分。这就是游标卡尺读数的全部来历，也是它不必估读的原因——小数部分由「哪一格对齐」这个确定的事实给出，不靠眼睛分格。</p>
    <p>反过来说，若 <Katex tex="f" /> 不是一个格点的值，就没有任何一格完全对齐，最近的两格会一左一右各偏一点。实际读数时取偏得最少的那一格，偏差不超过半个精度格，这正是卡尺的示值误差。</p>

    <h3 class="sec" id="e13-read">读数：整毫米加对齐格数乘精度</h3>
    <p>读数按三步走。第一步，看游标的零线落在主尺的哪两条毫米线之间，取左边那条的数值 <Katex tex="m" />；它不必是整十数，主尺上每一条毫米线都算。第二步，沿游标从头往后找，看第几格与主尺的某条刻线重合得最好，记下格数 <Katex tex="k" />。第三步，代入</p>
    <p style="text-align:center"><Katex tex="L=m+k\cdot\frac{1}{n}\ \text{mm}" display /></p>
    <p>精度 <Katex tex="\frac{1}{n}" /> mm 印在卡尺的游标上，常见写法是「0.02 mm」「0.05 mm」或「0.1 mm」，直接按印的数值乘即可。以 20 分度、精度 0.05 mm 的卡尺为例：游标零线在 12 mm 与 13 mm 之间，游标上第 9 格与主尺刻线重合，则 <Katex tex="L = 12 + 9\times0.05 = 12.45" /> mm。结果的末位在百分位，与精度同一档。</p>
    <p>这里没有估读这一步。若硬要在 12.45 mm 后面再写一位，例如 12.452 mm，那一位是没有依据的：卡尺上没有比 0.05 mm 更细的刻线，仪器的分辨极限就到这里。</p>

    <h3 class="sec" id="e13-kinds">三种分度：0.1、0.05、0.02 mm</h3>
    <p>游标分多少格，精度就是多少分之一毫米。常见的三种如下。</p>
    <p>10 分度：游标 10 格总长 9 mm，每格 0.9 mm，精度 <Katex tex="\frac{1}{10}=0.1" /> mm。结果读到小数点后一位（以 mm 计），以 cm 计时读到两位。</p>
    <p>20 分度：游标 20 格总长 19 mm，每格 0.95 mm，精度 <Katex tex="\frac{1}{20}=0.05" /> mm。结果读到 0.05 mm 的整数倍，末位是 0 或 5。</p>
    <p>50 分度：游标 50 格总长 49 mm，每格 0.98 mm，精度 <Katex tex="\frac{1}{50}=0.02" /> mm。结果读到 0.02 mm 的整数倍，末位是偶数。这种卡尺最常见，尺面上的字也很密，读数时要对着放大镜或凑近看。</p>
    <p>三种卡尺的格数不同，读数的方法却完全一样：整毫米加对齐格数乘精度。判断精度只需看游标上的标数——0.02 mm 的卡尺，游标上会印到 50。分度越细，游标越长、刻线越密，读数越费眼，这是精度换来的代价。</p>

    <h3 class="sec" id="e13-use">使用：校零、夹持与零点误差</h3>
    <p>用之前先校零：把两个量爪合拢，看游标的零线与主尺的零线是否重合。若两爪合拢时游标零线并不在主尺零处，说明卡尺有<strong>零点误差</strong>，记下这个读数 <Katex tex="L_0" />；此后每次测量都按 <Katex tex="L = L' - L_0" /> 修正（<Katex tex="L'" /> 为这次测得的读数）。零点误差是系统误差，多测几次取平均也消不掉，只能这样扣除。</p>
    <p>测外径用下面那对量爪，测内径用上面那对，测深度把尺尾的深度尺伸进去。夹持时力度以量爪刚好贴住工件为准，不能用力挤压——工件被压出弹性形变，读数就偏小；松开后又弹回来，看着像是「卡尺不准」。读数时视线要与刻线垂直，斜着看会把重合的那一格看成相邻的一格。</p>
    <p>卡尺是精密量具，不能量粗糙面、运动中的工件或高温件；用完擦净、松开量爪再放进盒里，长期夹着会让量爪变形。同一段长度沿轴向多量几处，能看出工件有没有锥度——这也是卡尺比直尺有用的地方：它量的是「点到点」，不是「大概多长」。</p>
    <p>与刻度尺相比，卡尺把 1 mm 的估读换成了刻线的对齐，精度提高一个量级；与螺旋测微器相比，它量程大、可以测内径与深度，但精度只到 0.02 mm。选哪一种，取决于被测长度与要求的位数，这也是下一章要接着讲的事。</p>

