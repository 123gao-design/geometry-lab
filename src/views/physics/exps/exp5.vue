    <h3 class="sec" id="e5-prin">原理：总动量在碰撞中不变</h3>
    <p>设滑块 A 的质量为 <Katex tex="m_1" />、初速度为 <Katex tex="v_1" />，滑块 B 的质量为 <Katex tex="m_2" />、静止，碰撞后的速度分别为 <Katex tex="v_1'" /> 与 <Katex tex="v_2'" />。动量守恒给出</p>
    <p style="text-align:center"><Katex tex="m_1v_1=m_1v_1'+m_2v_2'" display /></p>
    <p>这条式子只要求碰撞期间系统所受的合外力为零，不要求碰撞过程是怎样的。碰撞时间短、内部作用力大、外部摩擦与空气阻力小，这些条件在气垫导轨上都近似满足。</p>
    <p>碰后的速度由碰撞的类型决定。若是弹性碰撞，动量与动能同时守恒，解得</p>
    <p style="text-align:center"><Katex tex="v_1'=\frac{m_1-m_2}{m_1+m_2}v_1,\qquad v_2'=\frac{2m_1}{m_1+m_2}v_1" display /></p>
    <p>两式合起来看，碰后两滑块的相对速度与碰前大小相等、方向相反（等质量时速度互换）。若是完全非弹性碰撞，两滑块粘在一起同速运动，由动量守恒立刻得到</p>
    <p style="text-align:center"><Katex tex="v'=\frac{m_1}{m_1+m_2}v_1" display /></p>
    <p>此时的动能损失可以由两式相减算出：</p>
    <p style="text-align:center"><Katex tex="\Delta E_k=\frac{1}{2}\cdot\frac{m_1m_2}{m_1+m_2}v_1^2" display /></p>
    <p>损失全部转化为内能与声能。等质量的两滑块完全非弹性碰撞时，动能恰好损失一半，这一点在后面核对数据时很有用。</p>
    <p>速度的测量靠光电门。滑块上装一片宽度为 d 的遮光条，它通过光电门时挡住光路，计时器记下挡光时间 Δt。由于 d 很小，这段时间内的速度近似不变，于是</p>
    <p style="text-align:center"><Katex tex="v=\frac{d}{\Delta t}" display /></p>
    <p>d 越小、测得越准，但 d 太小会使挡光信号变弱、计时分辨力不够。实验用的遮光条通常在 1 cm 量级。</p>

    <h3 class="sec" id="e5-step">器材与步骤：光电门测速</h3>
    <p>器材：气垫导轨、两个滑块（带遮光条与缓冲器）、两个光电门、数字计时器、天平、水平仪。</p>
    <p>先调平导轨。把水平仪放在导轨上，调节地脚螺丝使气泡居中；也可以用「滑块放在导轨任意位置都不自行滑动」来检验。导轨不平会让滑块沿导轨方向受力，破坏合外力为零的条件，动量在碰撞之外还会无声地改变。</p>
    <p>用天平称出两个滑块的质量，连遮光条与缓冲器一起称。遮光条的宽度用游标卡尺测量，读数记到 0.01 mm。</p>
    <p>把两个光电门分置导轨两侧，位置使碰撞发生在两门之间、且碰前碰后滑块都能完整通过某道门。接通气源，让滑块悬浮，先测 A 通过第一道光门的时间，再让 A 与静止的 B 相碰，测出碰后 A、B 各自通过光门的时间。</p>
    <p>弹性碰撞用装有弹簧缓冲器的滑块，碰撞后两者分开；完全非弹性碰撞用装有黏性搭扣或橡皮泥的滑块，碰后粘在一起。两种情形的数据分开记录，不要在一条纸面上混写。</p>
    <p>每次实验要让 A 从同一侧推出，避免手推时带入侧向速度。放手后不要碰导轨，气流未稳定时不要开始测量。</p>

    <h3 class="sec" id="e5-data">数据处理：两种碰撞的碰后速度</h3>
    <p>每一道光电门的记录给出遮光时间 Δt，按 v = d/Δt 换算成速度，注意方向：A 向右为正，B 若被推向左则取负。把质量与速度逐个相乘、相加，得到碰前总动量 <Katex tex="p" /> 与碰后总动量 <Katex tex="p'" />。</p>
    <p>弹性碰撞的检验有两层。第一层是动量：<Katex tex="p'" /> 与 <Katex tex="p" /> 相等。第二层是动能：<Katex tex="\tfrac{1}{2}m_1v_1^2" /> 应当等于 <Katex tex="\tfrac{1}{2}m_1v_1'^2+\tfrac{1}{2}m_2v_2'^2" />。两层都过关，说明缓冲器确实把碰撞做到接近完全弹性。</p>
    <p>完全非弹性碰撞时，碰后只有一组速度，检验的是 <Katex tex="m_1v_1=(m_1+m_2)v'" />。此时再算动能，会发现碰后小于碰前，差值应与 <Katex tex="\tfrac{1}{2}\cdot m_1m_2/(m_1+m_2)\cdot v_1^2" /> 相符。动量守恒而动能不守恒，这正是这类碰撞的标志。</p>
    <p>把同一次实验重复几遍，取总动量的平均值，并算出碰前碰后之差的相对大小。相对偏差在百分之几以内，通常就认为守恒成立。</p>

