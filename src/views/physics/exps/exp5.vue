    <h3 class="sec" id="e5-err">误差与判定标准</h3>
    <p>导轨不水平是最主要的系统误差。滑块在导轨上受到的沿轨分力虽然不大，但在两道光门之间的长距离上会持续改变速度，使碰前、碰后测得的速度都不是碰撞瞬间的值。调平导轨应在实验的第一步完成。</p>
    <p>气流不足也会破坏条件。滑块若没有完全悬浮、局部与导轨接触，摩擦就会进入碰撞前后的整个过程，总动量会单调减少。气源压力要调到能让滑块顺畅滑动且不飘起的状态。</p>
    <p>测量遮光时间时，遮光条必须垂直通过光路。若遮光条与导轨不垂直，实际遮挡的有效长度大于 d，算出的速度偏小，且偏小的程度与装配角度有关。安装遮光条时用直角尺校正。</p>
    <p>碰撞是否发生在两门之间、碰撞后滑块是否在通过光门前又撞到导轨端头的缓冲器，这些操作细节都会让数据对应错位。实验前先空跑一次，确认行程充裕。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把「动量守恒」理解成「速度守恒」。</strong>守恒的是质量与速度的乘积之和，不是速度本身。等质量弹性碰撞时速度互换、非弹性碰撞时同速，这些结论都是动量守恒加工碰撞类型推导出来的，不能反过来说。</li>
        <li><strong>提示二：忽略了速度的方向。</strong>B 若碰后向左运动，速度要取负号填进式子。只代大小会让总动量凭空变大，看上去像「守恒不成立」。</li>
        <li><strong>提示三：用遮光条的宽度直接乘以挡光时间。</strong>两者是相除的关系：v = d/Δt。挡光时间越长说明速度越小，这个直觉可以帮助检查算错没有。</li>
        <li><strong>提示四：把完全非弹性碰撞的动能损失当成守恒被破坏。</strong>动量守恒与动能守恒是两件事。有内能产生时动能必然减少，动量却仍然守恒；要看出这一点，必须把两个量分开算。</li>
        <li><strong>提示五：忽略导轨未调平。</strong>调平应在装光电门之前完成，并且用「滑块不自行滑动」实际检验。导轨倾斜几度，两道光门之间的速度就会差出百分之几，足以掩盖真实的守恒关系。</li>
