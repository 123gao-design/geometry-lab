    <h3 class="sec" id="e15-rule">通则：分度值决定读到哪一位</h3>
    <p>分度值是相邻两条刻线之间代表的量。读数的第一步是数整格，得到一个分度值的整数倍；第二步是估读，把一格分成十份或五份，读出剩余那一小段占一格的几分之几。所以读数的末位，总在分度值的下一位。</p>
    <p>这条规则可以写成一句话：<strong>读数位数比刻度多一位</strong>。刻度只到 0.1 的量具，读数写到 0.01；刻度只到 1 的量具，读数写到 0.1。位数不是随手多写，它有刻线做依据——多出来的那一位虽然估出来，但它代表的是「介于两条刻线之间」的位置信息。</p>
    <p>分度值不是 1、0.1、0.01 这类整齐的数时，估读的份数要看惯常规定：分度 0.02 A 的表，每小格再分两份，读到 0.01 A；分度 0.5 V 的电压表，每小格分五份，读到 0.1 V。分度 0.2 g 的游码标尺，读数取 0.2 g 的整数倍或读到 0.1 g，两种写法在不同教材里都能见到，考试时按题给仪器的刻度来定。</p>
    <p>这条通则也是上一章两件精密量具的底子：卡尺的分度是精度本身，所以读数末位就在精度这一位、不必再往后；测微器的分度是 0.01 mm，所以读数末位在 0.001 mm。量具越精密，分度越细，能写出的位数越多。</p>

    <h3 class="sec" id="e15-ruler">刻度尺：分度 1 mm，估读到 0.1 mm</h3>
    <p>刻度尺是最基本的长度量具。最小分度通常是 1 mm：每毫米一道线，逢五稍长、逢厘米标数。读数先看被测物两端落在哪两条刻线之间，左边那条给出整毫米，右边那一段不足 1 mm 的部分再分成十份估读，所以读数的末位在 0.1 mm，也就是 0.01 cm。</p>
    <p>写成什么单位就要给到相应位数。以 cm 为单位时读两位小数（4.87 cm），以 mm 为单位时读一位小数（48.7 mm）。两种写法是同一个数，只是单位的换算；若写成 4.9 cm，等于把估读位舍掉了，读数反而比仪器能做到的粗。</p>
    <p>用刻度尺有两个细节。其一，零刻度线若已磨损，不要从零量起，改从某一整刻度线量到终点、两读数相减——这与卡尺的零点校正是同一个道理。其二，视线要垂直于刻面，斜着看会把刻线看偏，读数偏向一侧；量圆柱直径这类「端点不在同一条线上」的情况，还要确认尺身与被测方向平行。</p>
    <p>刻度尺的分度决定了它的极限：1 mm 以下的部分全是估的，多写一位没有依据。这与实12 讲的有效数字一致——仪器的分度值决定了结果该保留几位。</p>

    <h3 class="sec" id="e15-balance">托盘天平：砝码试放与游码</h3>
    <p>托盘天平称的是质量。右盘放砝码，左盘放被测物，<strong>读数 = 砝码总质量 + 游码读数</strong>。操作时砝码要由大到小试放：先取最大的一只，太重就换小一号，直到放上去之后总质量仍不超过被测质量为止。这样一只只用下来，砝码的数量最少、试放次数也最少；若从小到大往上加，往往加到最后还得来回换。</p>
    <p>砝码凑不出的余数由游码补足。游码标尺是一根 0 到 5 g 的短尺，上面每小格 0.2 g。把游码拨到使横梁重新平衡的位置，它所指的刻度就是余数。所以总读数往往是这样：砝码 60 g 加游码 3.4 g，得 63.4 g。砝码是离散的（100、50、20、20、10、5 g 一套），游码是连续的，两者合起来才能读出任意质量。</p>
    <p>使用顺序不能颠倒：先把天平放平、游码归零，再调平衡螺母使指针指在分度盘中央；称量时左物右码，用镊子夹砝码（手直接拿会沾油污、改变质量）；称完把砝码放回盒中、游码归零。称量不能超过量程，被测物要放在盘中央。</p>
    <p>天平的灵敏度也有限度：游码标尺每格 0.2 g，读数一般取 0.2 g 的整数倍，比它更细的部分天平分辨不出来。这与刻度尺的 1 mm 是同一回事——分度值就是这台仪器的分辨极限。</p>

    <h3 class="sec" id="e15-meter">电表：量程、分度与估读</h3>
    <p>电流表与电压表是双量程的：同一个表盘上有两套刻度，接线柱选哪一对就对应哪一个量程。读数前先确认量程，再数这一量程下每小格代表多少，最后按分度值估读。0.6 A 档的刻度盘上，0 到 0.6 之间有 30 个小格，每格 0.02 A，读数估读到 0.01 A，写成两位小数（如 0.37 A）；3 A 档每小格 0.1 A，读数估读到 0.01 A。电压表同理：3 V 档每格 0.1 V、读到 0.01 V，15 V 档每格 0.5 V、读到 0.1 V。</p>
    <p>量程的选择有讲究：先估计被测电流的大致范围，选略大于它的量程；量程选大了，指针偏转太小，相对误差变大；选小了，指针打满甚至烧表。若事先无法估计，先用大量程试触一下，看指针偏转是否超过满刻度的一半，再决定换不换小量程。</p>
    <p>用前还要校零：断开电路时指针应指在零刻度，若不在，用表盘下方的小螺丝调回零。读数时视线要与表盘垂直，指针在镜面刻度盘上的像与指针重合时读数最准——这类表盘专门在刻度后装了一面小镜子。</p>
    <p>其他常见量具遵循同一条规矩：机械秒表分度 0.1 s、读到 0.1 s（电子秒表分度 0.01 s、读到 0.01 s）；温度计的分度常见 1 ℃ 或 0.1 ℃，读数按分度估读一位。分度值多少，读数就写到它的下一位，这条通则贯穿所有量具。</p>

