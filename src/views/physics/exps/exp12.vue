    <p class="cap">图 实12 · <b>误差与有效数字</b>：左栏是一把 0–4 cm 的刻度尺，最小分度 1 mm，每毫米一道线、逢半厘米加长、逢厘米标数；铅笔横在尺的上方，两端各有一条紫色投影线落向尺面，读数写在下面。默认左端 a = 0.87 cm、右端 b = 3.42 cm，两者都读到了分度值的下一位（0.1 mm），长度 L = b − a = 2.55 cm，也写到小数点后两位。右栏把同一根铅笔反复量若干次，横轴是第几次，纵轴是读到的长度：橙点是各次读数，绿虚线是真值 2.55 cm，蓝实线是当前的平均值，橙色带是 ±u。看点一：n 从 5 加到 20 再加到 40，橙点的散布几乎不变——单次读数的分散由仪器与估读方式决定；橙带却按 √n 收窄，读数栏的 σ 停在 0.02–0.03 cm 这一档，u 从约 0.009 cm 降到 0.004 cm 上下，结果仍写在千分位，只是那一位上的数在变小。看点二：n = 20 时平均值约 2.556 cm，按「不确定度取一位、数值末位与它对齐」记作 (2.556 ± 0.006) cm。看点三：拖动「铅笔左端的位置」，两端读数一起变，差值仍是 2.55 cm——长度只由差值决定，与尺子从哪里起量无关。看点四：把铅笔的长度拖到 1.50 cm，两端读数都变小，可各次读数的分散程度并不改变，说明估计误差由分度与眼睛的分辨决定，与量什么无关。</p>

    <p>把演示里的两个读数单独看一遍，就能看到估计误差的样子：同一次量的读数可以是 2.56 cm，也可以是 2.53 cm，差别全在百分位那一位上。这一点不值得纠正，它本来就是尺子与眼睛的极限；要做的是承认它，再按它决定结果该写到哪一位。</p>

    <h3 class="sec" id="e12-rule">记录规则：结果按不确定度定位数</h3>
    <p>数值与不确定度写几位，有一套通行的约定，与上面各节的理由一一对应。</p>
    <p>其一，<strong>不确定度取一位有效数字</strong>：<Katex tex="u" /> 本身也只是估计，第二位没有信息量。若首位是 1 或 2，为了不把不确定度估得过粗，允许取两位。其二，<strong>数值的末位与不确定度的末位对齐</strong>，两者同到千分位或同到百分位，不能一深一浅。其三，最终结果写成</p>
    <p style="text-align:center"><Katex tex="L=(2.556\pm0.006)\ \text{cm},\qquad \frac{u}{\bar L}\approx0.24\%" display /></p>
    <p>平均值的第四位之所以能写出来，是因为不确定度落在千分位；若不确定度大到 0.01 cm 这一档，结果就只能写到 <Katex tex="(2.56\pm0.01)" /> cm。同一个平均值，不确定度压得越小，可以诚实地多写一位——多写的那一位是有依据的，不是凑出来的。</p>
    <p>运算过程中的位数另有规定。加减法的结果，末位与参与运算的各项中<strong>末位最高</strong>的那一项对齐：<Katex tex="2.55+0.1=2.65" /> cm，不能写 2.650，因为 0.1 那一位本身就没有更细的信息。乘除法看<strong>有效数字位数最少</strong>的参与者，结果保留同样多的位数。中间步骤宜多留一位，避免连续舍入把误差累积起来，只在最后一步定稿。</p>
    <p>作图的数据处理还有一条相应的要求：图上一点所代表的那组数只到某一位，画出的直线也只到某一位，所以由斜率反算的物理量不能写到超出原始数据精度的位数。<Katex tex="v-t" /> 图斜率给出的加速度、<Katex tex="U-I" /> 图截距给出的电动势，写出的位数都应当与前几步的读数相称。</p>

