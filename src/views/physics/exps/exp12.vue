      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把有效数字多写了一位。</strong>分度 1 mm 的尺子只有估读的那一位靠得住，写成 2.550 cm 的第四位是凭空添的。写完回头核对三件事：分度值是多少、该估读到哪一位、结果的末位是否正好落在那里。</li>
        <li><strong>提示二：零刻度已磨损，仍从零端量起。</strong>磨损量与长度一并进入读数，这是系统误差，多测取平均消不掉。改从某个整刻度量起、再相减，或换用未磨损的那一端做起点。</li>
        <li><strong>提示三：只报平均值，不报不确定度。</strong>平均值只是最好的估计，配上不确定度才是完整的结果。两者末位对齐，不确定度取一位有效数字；只把平均值写出来，读者无法判断前几位是可靠的。</li>
        <li><strong>提示四：以为多测就一定能提高精度。</strong>不确定度按 <Katex tex="1/\sqrt n" /> 收窄，测 4 次精一倍、要精十倍得测 100 次。降到仪器误差限以下之后，再测也不会变小，此时应当更换仪器。</li>
        <li><strong>提示五：加减乘除一律保留全部位数。</strong>加减看末位最高的那一项，乘除看有效数字最少的那个量。中间步骤多留一位，最终结果再按不确定度定稿，不要每一步都舍入。</li>
