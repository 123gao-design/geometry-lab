      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把斜槽末端的使用位置当成坐标原点。</strong>原点应取末端的球心位置，不是边缘、也不是小球离开后下落一段的位置。原点偏了，图线截距不为零，斜率也会跟着错。</li>
        <li><strong>提示二：每次释放位置不固定。</strong>初速度不同，轨迹就不同，把不同轨迹上的点混在一起画图，散点会散得很开，看上去像「实验失败」。每次都从斜槽同一位置由静止释放是硬性要求。</li>
        <li><strong>提示三：末端没有调水平。</strong>用「小球能停在末端不滚落」或「轻推小球能水平飞出」来检验。末端不水平时小球带竖直初速度，已经不是平抛，后续所有公式都不适用。</li>
        <li><strong>提示四：误把 y 与 x 成正比的结论套到本实验。</strong>平抛的轨迹是抛物线，y 与 x 不是线性关系；与 x² 才是线性关系。作图时若以 x 为横轴，会得到一条弯曲的线，那是正常的。</li>
        <li><strong>提示五：只用一两个点就断言曲线是抛物线。</strong>两个点总能连成直线，判读抛物线至少需要四五个分散的点，最好让 x 的覆盖范围拉开，使图线的弯曲或挺直一眼可辨。</li>
