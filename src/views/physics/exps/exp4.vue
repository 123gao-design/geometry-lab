    <p class="cap">图 实4 · <b>平抛轨迹与 y–x² 图</b>：左栏是斜槽末端、地面与整条轨迹，小球按等时间间隔留下的点越往下越密，粉点是落点，青色标注给出射程 x；右栏以 x² 为横轴、y 为纵轴，橙点是实测散点，绿虚线是过原点的理论直线。看点一：默认 H = 0.80 m、v₀ = 1.5 m/s，读数栏给出飞行时间 0.40 s、射程 0.61 m，落地竖直速度 3.96 m/s，三者互相对得上。看点二：把 v₀ 拖大，射程变大、轨迹更平，右栏直线的斜率随之变小，反推的 v₀ 仍然回到设定值。看点三：把 H 拖小，飞行时间缩短、射程也缩短，但轨迹仍然是同一条抛物线，说明顶点始终在抛出点。看点四：右栏所有点几乎落在一条线上过原点，这就是「y 与 x² 成正比」的直接证据。</p>

    <h3 class="sec" id='e4-err'>误差：末端是否水平、原点在哪</h3>
    <p>斜槽末端不水平是最常见的问题。末端若向上翘，小球带着竖直分速度飞出，轨迹比平抛更陡；末端若向下压，小球会先沿末端滚出一小段再离开，起点不在末端球心处。两种情形下算出的 v₀ 都不是真实值，而且图线可能不过原点。</p>
    <p>坐标原点的定位误差同样不可忽略。原点应取斜槽末端球心的投影，而非末端边缘。球心与末端边缘差半个球径，在几十厘米的纵向尺度上，这一项会让所有 y 值整体平移，进而改变斜率。</p>
    <p>阻力与空气阻力使轨迹略低于理想抛物线：竖直方向实际加速度略小于 g，水平速度也略有衰减。小球越小、射出速度越大，这一项越明显；小球若质量太小，甚至会被气流带偏。</p>
    <p>取点误差来自白纸上点迹的判读。点迹有大小，中心位置靠估计，而且小球与纸面接触时的形变会让墨点不对称。多取几个点、把拟合直线画得平滑，可以削弱这类随机偏差。</p>

