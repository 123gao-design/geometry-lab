    <h3 class="sec" id="e4-prin">原理：把平抛分解成两个方向</h3>
    <p>小球从水平末端飞出后只受重力。水平方向不受力，速度保持不变；竖直方向初速度为零、加速度为 g。以抛出点为原点、水平方向为 x 轴、竖直向下为 y 轴，两个分运动的方程是</p>
    <p style="text-align:center"><Katex tex="x=v_0t,\qquad y=\frac{1}{2}gt^2" display /></p>
    <p>第一式给出时间，代入第二式即得轨迹方程</p>
    <p style="text-align:center"><Katex tex="y=\frac{g}{2v_0^2}x^2" display /></p>
    <p>这是一条过原点、开口向下的抛物线。它与一般二次函数的区别在于只有平方项、没有一次项与常数项：顶点就在抛出点，对称轴是竖直方向。</p>
    <p>由此有两条可以分别检验的结论。其一是形状：把 y 当作 x² 的函数，关系是线性的，图线过原点、是直线。其二是数值：直线的斜率</p>
    <p style="text-align:center"><Katex tex="k=\frac{g}{2v_0^2}\;\Longrightarrow\;v_0=\sqrt{\frac{g}{2k}}" display /></p>
    <p>只要量出斜率，初速度就能算出来。此外，若只测了某个落点，把它的坐标代回轨迹方程也能求初速度：<Katex tex="v_0=x\sqrt{g/(2y)}" />，多测几个点再取平均，结果更可靠。</p>
    <p>飞行时间只由抛出高度决定，与初速度无关：</p>
    <p style="text-align:center"><Katex tex="t=\sqrt{\frac{2H}{g}}" display /></p>
    <p>同一装置把小球从同一高度水平弹出、只是改变了弹出速度时，落地时间不变，射程却按 v₀ 成比例变化。这一条在数据里也看得见：v₀ 变大，整条轨迹横向拉长，竖直方向并不跟着变。</p>

    <h3 class="sec" id='e4-step'>器材与操作步骤</h3>
    <p>器材：斜槽轨道、小球、木板与坐标纸、重锤线、铅笔、刻度尺、铁架台。</p>
    <p>安装时把斜槽固定在铁架台上，末端调成水平——这一步决定了小球是否真的做平抛。检验的办法是把小球放在末端，若它能在原处静止而不滚落，末端就是水平的；也可以在末端附近放一粒小钢球，看它是否被水平推出。</p>
    <p>坐标纸钉在竖直的木板上，位于斜槽外侧。用重锤线确定竖直方向，在坐标纸上画出 y 轴；再用铅垂线定出斜槽末端球心的投影位置，作为坐标原点 O。坐标原点是抛物线的顶点，位置一旦错了，整条曲线都会平移，斜率与初速度都会跟着出错。</p>
    <p>每次让小球从斜槽上的同一位置由静止滚下，保证初速度相同。小球飞出后落在复写纸与白纸之间，在白纸上留下一个点；改变接收板的高度，重复多次，得到轨迹上的一串点。取点时不要只取一个方向，横向也要铺开，覆盖尽量宽的 x 范围，斜率才定得准。</p>
    <p>如果不用落点法，也可以让小球每次都从同一高度水平飞出，同时用带小孔的卡片在其飞行路径上截取位置。无论用哪种方式，都要保证小球每次都从同一位置释放，这是把多个点归到同一条轨迹上的前提。</p>

    <h3 class="sec" id='e4-data'>数据处理：以 x² 为横轴</h3>
    <p>量出各点的坐标 <Katex tex="(x_1,y_1)" />、<Katex tex="(x_2,y_2)" />……，算出每一个 <Katex tex="x^2" />，以 <Katex tex="x^2" /> 为横轴、<Katex tex="y" /> 为纵轴描点。若各点落在一条过原点的直线上，说明轨迹确为抛物线、且顶点在原点。</p>
    <p>用直线拟合后取直线上相距较远的两点求斜率：<Katex tex="k=\Delta y/\Delta x^2" />，再代进 <Katex tex="v_0=\sqrt{g/(2k)}" />。也可以对每个点单独算 <Katex tex="v_0^{(i)}" />，再取算术平均；两种做法结果应当接近，前者受个别坏点影响更小。</p>
    <p>若图线的截距不为零，通常有两类原因：一是坐标原点没有定在抛出点，整条线平移；二是小球在飞出之前已经有一段很小的水平或竖直位移。前者可以通过重新确定原点解决，后者需要检查末端是否真的水平、小球离开末端时是否已经脱离轨道。</p>

