    <h3 class="sec" id="e14-prin">原理：螺距与微分筒的 50 格</h3>
    <p>螺旋副把转动的角度换成沿轴的位移。设螺距为 <Katex tex="h" />，微分筒转过角度 <Katex tex="\theta" />，螺杆前进的距离为</p>
    <p style="text-align:center"><Katex tex="s=\frac{\theta}{2\pi}\,h" display /></p>
    <p>测微器的螺距取 <Katex tex="h = 0.5" /> mm。微分筒转一整圈（<Katex tex="\theta = 2\pi" />），<Katex tex="s = 0.5" /> mm；这一圈在筒的圆周上分成 50 等份，每转一格 <Katex tex="\theta = 2\pi/50" />，代入上式得 <Katex tex="s = 0.01" /> mm。这就是「每格 0.01 mm」的来历，也是它被叫作千分尺的原因——量程内的读数可以给到千分之一毫米。</p>
    <p>固定刻度上有两排刻线：一排是毫米线，另一排错开半格、标出 0.5 mm 的位置。为什么要半毫米线？因为螺距只有 0.5 mm，转一圈螺杆才走半毫米；若不把半毫米单独标出来，微分筒转过一圈回到原处，固定刻度上的读数不变，就无法区分「走了 0.5 mm」与「没走」。上下两排刻线合起来，才把螺杆的一个螺距走完这件事在尺面上记下来。</p>
    <p>由此也能看出量程的由来：常见测微器的螺杆行程是 25 mm，超过这个长度要换量程更大的尺或分段测量。它的精度高，代价是量程小、测力要格外小心——这一点在第三节还会讲到。</p>

    <h3 class="sec" id="e14-read">读数：固定刻度加微分筒格数</h3>
    <p>读数同样分三段。第一步看固定刻度：微分筒的边缘左侧露出的毫米线有几条，就是几毫米；再看毫米线之间那条半毫米线露没露出来，露了就再加 0.5 mm，得到 <Katex tex="a" />。第二步看微分筒：找与基准线（固定刻度上那条水平线）对齐的那一格，读出格数 <Katex tex="t" />。第三步相加：</p>
    <p style="text-align:center"><Katex tex="L=a+t\times0.01\ \text{mm}" display /></p>
    <p>以 <Katex tex="a = 2.0" /> mm（半毫米线未露出）、<Katex tex="t = 47" /> 为例：<Katex tex="L = 2 + 47 \times 0.01 = 2.47" /> mm。若半毫米线也露了出来，则 <Katex tex="a = 2.5" />，同样的格数给出 2.97 mm。<strong>半毫米线露没露，是这一类题最容易漏的一步</strong>：两排刻线一上一下交错，凑近看勉强能分辨，稍一疏忽就会把 2.97 读成 2.47，差出整整 0.5 mm。</p>
    <p>最后一位估读：微分筒每格 0.01 mm，格与格之间的空隙用眼睛再分成十份，估到 0.001 mm。所以完整的结果写成三位小数，如 <Katex tex="2.473" /> mm；末位是估计出来的，不能随意增删。若对齐的格线恰好压在基准线上，估读位记 0，写成 2.470 mm 而不是 2.47 mm——位数本身说明了用的是什么仪器。</p>
    <p>反向核对走的是同一把尺。若一个读数记作 2.473 mm，先看半毫米线露没露：露出则 <Katex tex="a = 2.5" />，格数就须取负数才凑得出 2.473，与「格数在 0 到 50 之间」矛盾；所以那半毫米线其实没露，<Katex tex="a = 2.0" />、<Katex tex="t = 47.3" />。检验的办法只有一个：看那半毫米线到底有没有露出来。</p>

    <h3 class="sec" id="e14-use">使用：校零、测力与放置</h3>
    <p>用前校零：两测量面合拢（或用标准量杆），看微分筒的零线是否与基准线对齐、固定刻度的零线是否正好被微分筒边缘压住。若不对齐，说明有<strong>零点误差</strong>，记下这个读数 <Katex tex="L_0" />，之后每次测量按 <Katex tex="L = L' - L_0" /> 修正（<Katex tex="L'" /> 为这次测得的读数）。零点误差通常是测量面磨损或螺杆间隙造成的，属于系统误差，取平均也消不掉。</p>
    <p>夹持要靠棘轮（测力装置）：旋转尾部的棘轮旋钮，听到三声「咔咔」就停，这时的夹紧力由棘轮内的弹簧限定，被测件不会被压变形。直接转微分筒、凭手感夹紧是不对的——力稍大一点，金属件被压出弹性形变，读数就偏小；测薄片、细丝时这个偏差尤其明显。测完先把锁紧装置松开再取件，不要硬抽。</p>
    <p>放置也有讲究：测量面要垂直于被测尺寸的方向，斜着夹会把圆柱夹成椭圆截面、读数偏大；量圆柱的直径时沿轴向多量几处，能看出有没有锥度；量细丝、薄纸这类软而薄的东西，更要靠棘轮限力，不能压扁。测微器怕磕碰、怕油污，用完擦净测量面、让两测量面留一道缝再收进盒里，长期合紧会让螺纹副产生应力。</p>
    <p>刻度细，读数要凑近看，必要时用放大镜辅助——短短几个毫米的刻度上挤着两排刻线加一条基准线，凑近看才分得清半毫米线露没露。</p>

    <h3 class="sec" id="e14-cmp">与游标卡尺的分工</h3>
    <p>两种量具解决的是同一个问题——把一毫米以下的部分读出来——但手段不同。卡尺靠游标格线与主尺刻线的重合，格数直接给出小数部分，<strong>不估读</strong>，精度由分度决定（0.1、0.05、0.02 mm）；测微器靠螺旋副把转动摊成前进，格数乘以 0.01 mm 给小数部分，<strong>再估读一位</strong>，读数写到 0.001 mm（仪器本身的分度是 0.01 mm，0.001 是估出来的）。</p>
    <p>选哪一种看三件事：被测长度、要求的位数、能不能夹住。量程大（几十毫米到一米）、要测内径与深度、精度要求到 0.02 mm，用卡尺；量程小（25 mm 以内）、要读到千分位、被测件是细丝薄片这类软而薄的，用测微器。精度更高的场合还有千分尺的变体（深度千分尺、内径千分尺、螺纹千分尺），读法与本器的固定刻度加微分筒完全一致。</p>
    <p>两种仪器的读数最后都要落到有效数字上：卡尺的末位就是精度这一位，测微器的末位是估读位。这一条在实12「误差与有效数字」里已经讲过，这里只是把它挂到了具体的尺面上。</p>

