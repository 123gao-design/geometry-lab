    <h3 class="sec" id="e9-meter">表头、选择开关与表笔</h3>
    <p>表头是一只小量程电流表，标着满偏电流 <Katex tex="I_g" /> 与内阻 <Katex tex="R_g" />。指针的偏转角与流过它的电流成正比，指针满偏时对应的就是 <Katex tex="I_g" />。多用电表的所有挡位都建立在这一点上：让被测的量最终变成一股不超过满偏的电流。</p>
    <p>用选择开关切换量程与挡位。转盘上通常有直流电流、直流电压、交流电压、欧姆四类，每类再分几档。量程表的是「满偏时测量端对应的值」，指针指到满刻度就是该量程的上限。</p>
    <p>表盘上印着几排刻度，欧姆挡那一排与其余几排的疏密不同，读数时要看与当前挡位对应的那一排。数字下方标着该排的倍率或量程，认错排读数会差出十倍。</p>
    <p>表笔有红黑两支。测电流、测电压时，电流从红表笔流入、从黑表笔流出，红表笔接靠近电源正极的一端；表笔接反时指针会反打，机械式表头的反打容易碰弯指针。测电阻时表笔不分正负，此时红表笔接的是表内电池的负极、黑表笔接正极。</p>

    <h3 class="sec" id="e9-ohm">欧姆挡：调零、倍率与读数</h3>
    <p>欧姆挡把内部电池、调零电阻与表头串成一个回路，再把待测电阻接进这个回路。回路的总电阻是 <Katex tex="R_{\mathrm{m}}+R_x" />，其中 <Katex tex="R_{\mathrm{m}}" /> 是表内全部电阻之和，流过的电流为</p>
    <p style="text-align:center"><Katex tex="I=\frac{\varepsilon}{R_{\mathrm{m}}+R_x}" display /></p>
    <p>待测电阻为零时电流最大、指针满偏，所以<strong>欧姆挡的 0 在刻度盘右端</strong>；待测电阻无穷大时电流为零，指针停在左端，那里标着 ∞。中间各点的刻度由 <Katex tex="I" /> 与 <Katex tex="R_x" /> 的反比关系决定：电阻越大，同样的电阻增量引起的电流变化越小，刻度就越挤。这就是欧姆挡刻度左密右疏的原因。</p>
    <p>指针指在刻度正中时，回路电流正好是满偏的一半，此时 <Katex tex="R_x=R_{\mathrm{m}}" />。这个电阻叫中值电阻，是这一挡的「代表性」数值：指针落在中值附近时，刻度较疏、读数最可靠；指针贴在两端时，很小的电阻变化也挤在几个刻度里，读数误差很大。所以测量时通过换挡，让指针尽量落在中值附近。</p>
    <p>读数 = 指针示数 × 倍率。倍率 ×1 表示指针示数就是电阻值，×100 表示要把示数乘一百。换挡之后 <Katex tex="R_{\mathrm{m}}" /> 随之改变，指针位置也变，所以<strong>每换一次挡都要重新短接表笔调零</strong>：把两支表笔碰在一起，转动调零旋钮，使指针指到右端的 0 Ω。调零时表内电池被短接，电流最大，指针才可能回到满偏位置。</p>
    <p>欧姆挡内部有电池，测电阻时电路本身必须断电。带电测电阻，外部电压会叠在表内电池上，指针偏转失去意义，还可能损坏表头。测量时手只能捏表笔的绝缘柄，不能同时接触两支表笔的金属部分——人体电阻与待测电阻并联，读数会偏小。</p>

    <h3 class="sec" id="e9-use">电压挡、电流挡与二极管的判定</h3>
    <p>测电流时把多用电表串进电路，测电压时并在被测元件的两端。两种接法与单个电表完全一样，量程的选择原则也一样：先选大量程试测，再换到指针偏转超过满刻度三分之一的那一挡，读数最准；指针超过满刻度的三分之二就要立即换大的一挡。</p>
    <p>用欧姆挡判断二极管的正负极。二极管正向电阻小、反向电阻大，两次对调表笔测量，读数小的一次里，黑表笔接的是二极管的正极——因为欧姆挡内部电池的正极接的是黑表笔。判向时用 ×100 或 ×1k 挡，不要用 ×1 或 ×10k 挡：前者电流过大可能烧坏二极管，后者表内电池电压较高可能击穿。</p>
    <p>欧姆挡读数是粗略值，误差可达百分之几到十几，只用来估量与判断通断，不作为定量测量。需要精确阻值时仍用伏安法。</p>

