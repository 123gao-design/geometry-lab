      <ul class="tip-list">
        <li><strong>提示一：换倍率后忘了重新调零。</strong>各挡的中值电阻不同，表内电池的内阻也随使用改变，不调零的读数带一个固定的零点偏移。每换一挡先短接表笔、转调零旋钮到右端 0 Ω，再测。</li>
        <li><strong>提示二：带电测量电阻，或手同时捏住两表笔的金属部分。</strong>前者把外部电压叠进回路，后者让人体电阻与被测电阻并联，两者都会让读数失真，前者还可能损坏表头。断电测、只捏绝缘柄。</li>
        <li><strong>提示三：把欧姆挡刻度当均匀刻度读。</strong>欧姆挡读的是电流的倒数关系，刻度左密右疏。估读时示数靠左端要格外小心，宁可换挡让指针回到中值附近再读。</li>
        <li><strong>提示四：测电压、电流时量程选得过大或指针超过满偏。</strong>量程过大时指针只偏一小格，读数相对误差很大；超过满偏则可能打弯指针。先大后小，停在偏转超过满刻度过三分之一的位置。</li>
        <li><strong>提示五：不判方向就接传感器电路。</strong>NTC 与 PTC 的阻值随温度的变化方向相反，光敏电阻与霍尔元件的输出方向也各不相同。先写出阻值随被测量的变化方向，再定它接在上臂还是下臂。</li>
