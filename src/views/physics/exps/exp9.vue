    <h3 class="sec" id="e9-sensor">传感器：热敏电阻与光敏电阻</h3>
    <p>传感器是把非电学量（温度、光照、压力、磁场）按确定规律转成电学量（电阻、电压、电流）的元件，输出再交给电表或控制电路。高中阶段常考的三类：热敏电阻、光敏电阻、霍尔元件。</p>
    <p>热敏电阻分两种。负温度系数（NTC）的阻值随温度升高而减小，常用的半导体热敏电阻属于这一类；正温度系数（PTC）的阻值随温度升高而增大，金属丝绕制的属于这一类。半导体热敏电阻的阻值与热力学温度的关系近似为</p>
    <p style="text-align:center"><Katex tex="R=R_0\,e^{B\left(\frac{1}{T}-\frac{1}{T_0}\right)}" display /></p>
    <p>其中 <Katex tex="R_0" /> 是温度 <Katex tex="T_0" /> 时的阻值，<Katex tex="B" /> 是由材料决定的常数，几百到几千开尔文。温度升高时指数为负，阻值呈指数下降。把热敏电阻与定值电阻串联接到恒压电源上，就把温度的变化变成了电压的分压变化：</p>
    <p style="text-align:center"><Katex tex="U_R=\frac{R_s}{R_s+R_\theta}E" display /></p>
    <p>其中 <Katex tex="R_s" /> 是串联的定值电阻。温度升高、<Katex tex="R_\theta" /> 变小，<Katex tex="U_R" /> 增大。这样的电路就是一只温度计，把输出的电压接到电压表或比较器上，还能做成温度报警器与恒温箱的开关。</p>
    <p>光敏电阻用半导体材料制成，光照增强时载流子增多，阻值减小，同样串进分压电路就把光的强弱变成电压的高低，用于路灯的自动开关与照相机的测光。霍尔元件放在磁场中，通以电流，会在垂直于电流与磁场的方向上产生霍尔电压 <Katex tex="U_H=k\dfrac{IB}{d}" />，与磁感应强度成正比，用来测磁场或做成无触点开关。</p>
    <p>设计这类电路时，要先弄清传感器的阻值随被测量向哪个方向变，再确定它接在分压的上臂还是下臂、输出取在哪两点之间。方向搞反，报警器就会在应当报警时不响、不应当报警时乱响。</p>

