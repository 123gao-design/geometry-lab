    <p class="cap">图 实8 · <b>测电源电动势与内阻</b>：左栏是测量电路，青色圆框是电压表，它的两个接点（青点）跨在电源两端，读的是路端电压；橙色箭头标干路电流方向。右栏是 U–I 图，绿色虚线与各测点的趋势重合，纵截距（绿点）给电动势 ε、直线的斜率给 −r、与横轴的交点标短路电流。看点一：默认 ε = 3.00 V、r = 1.50 Ω、R = 4.0 Ω，电流 0.545 A、路端电压 2.18 V，读数栏的 U/I 是 4.00 Ω、(ε−U)/I 是 1.50 Ω，两行正好还原外电阻与内阻。看点二：拖「外电阻 R」，橙点沿直线滑动而不离开它——R 越大点越靠左上，R 与内阻同量级时落到中段，R 很小时逼近右下的短路电流。看点三：拖「内阻 r」，整条直线绕纵截距转动，r 越大越陡、横截距 ε/r 越靠左；拖「电动势 ε」，直线整体平移、与纵轴的交点跟着升降。看点四：把 r 拖到 5 Ω，短路电流降到 0.6 A，横轴随之收紧，各测点按新坐标重新铺开——图线的读数与读数栏给出的 ε、r 始终对得上。</p>

    <h3 class="sec" id="e8-err">误差：电压表分流的影响</h3>
    <p>接入电压表之后，电源的输出电流被分成两路：一路经电流表与变阻器，一路经电压表。电流表读到的是前者，而 <Katex tex="U=\varepsilon-Ir" /> 里的 I 应当是干路电流——也就是两路之和。于是同一组读数并不严格满足断路方程，偏差的方向可以推出来。</p>
    <p>设电压表内阻 <Katex tex="R_V" />，真实干路电流是 <Katex tex="I_{\text{true}}=I+U/R_V" />。把它代回真实的闭合电路方程 <Katex tex="U=\varepsilon-I_{\text{true}}r" />，整理成用读数 I 表示的形式：</p>
    <p style="text-align:center"><Katex tex="U=\frac{R_V}{R_V+r}\varepsilon-\frac{rR_V}{R_V+r}I" display /></p>
    <p>所以从图线上解出的两个量都偏小：</p>
    <p style="text-align:center"><Katex tex="\varepsilon'=\frac{R_V}{R_V+r}\varepsilon<\varepsilon,\qquad r'=\frac{rR_V}{R_V+r}<r" display /></p>
    <p>电压表内阻比内阻大得越多，这两个偏差越小。几 kΩ 量级的电压表配零点几欧的内阻，偏差在百分之一以内，通常在题目的误差要求之下。若电压表内阻不够大，可以改用更大量程（内阻随量程增大）或换用电桥一类的接法。</p>
    <p>另一项偏差来自电流表：它的内阻在干路上，压降与内阻本身的压降不可分，等效地把电流表内阻并进了内阻，使测得的 r 偏大。这与电压表分流的方向相反，两项相互抵消一部分。接线的接触电阻同理，也记在内阻里。</p>

