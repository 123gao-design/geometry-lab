        <li><strong>提示二：用两组测点直接联立解 ε 与 r。</strong>两个点各自的读数误差会原样传进结果，也没有任何冗余可供判断。至少六组点作图，让直线由全部数据共同确定，斜率与截距才稳。</li>
        <li><strong>提示三：把 U/I 当成内阻。</strong>U/I 是工作点对应的外电阻 R；内阻要看图线的斜率，那是电压随电流变化的比值，两个量纲相同、含义完全不同。读数栏把这两行并排列出，就为区分它们。</li>
        <li><strong>提示四：闭合开关前变阻器没有调到最大。</strong>刚接通就接近短路，电池迅速发热、电动势下降，还可能烧坏电流表。先取最大阻值，再逐级减小，全程让电流不超过短路电流的一半。</li>
        <li><strong>提示五：忽略电压表分流，把误差方向说反。</strong>电压表并在电源两端会偷走一部分干路电流，使测得的 ε 与 r 同时偏小；电流表内阻则让 r 偏大。判定方向要按接法现推，不能凭记忆套一句「测量值偏小」。</li>
