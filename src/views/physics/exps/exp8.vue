    <h3 class="sec" id="e8-prin">原理：U = ε − Ir 是一条直线</h3>
    <p>电源的电动势 ε 与内阻 r 是电源自身的两个参数，与接多大的外电阻无关。电路闭合后，电流流过内阻时产生压降 Ir，于是加在外部电路上的路端电压只剩</p>
    <p style="text-align:center"><Katex tex="U=\varepsilon-Ir" display /></p>
    <p>改外电阻 R 会同时改变 I 与 U，两者的变化被这条式子锁在一起：R 减小、I 增大，U 跟着减小，电源的「输出能力」被内耗分走一部分。</p>
    <p>在 U–I 图里，这条式子的读法是三条：</p>
    <p>其一，令 I = 0（外电路断开），得 <Katex tex="U=\varepsilon" />，所以直线与纵轴的交点就是电动势。</p>
    <p>其二，取两点相减消去 ε，得</p>
    <p style="text-align:center"><Katex tex="r=\left|\frac{\Delta U}{\Delta I}\right|" display /></p>
    <p>所以图线越陡，内阻越大。其三，令 U = 0（外电路短接），得 <Katex tex="I=\varepsilon/r" />，这是电源能输出的最大电流，也是实验时刻要避开的量。</p>
    <p>由这两条还能写出一组分压关系：<Katex tex="U=\dfrac{R}{R+r}\varepsilon" />。当 <Katex tex="R\gg r" /> 时 U 接近 ε，图上的工作点往左上角跑；当 R 与 r 同量级时，工作点落到直线的中段。实验选外电阻时要让工作点散开，全都挤在一端画不出斜率。</p>

    <h3 class="sec" id="e8-step">器材与步骤：限流接法与读数</h3>
    <p>器材：待测电源（干电池或学生电源）、电压表、电流表、滑动变阻器、开关、导线。</p>
    <p>接线：电流表串在干路上、与滑动变阻器组成限流电路；电压表并在电源两端，量的就是路端电压。电流表要选内阻小的量程，电压表选内阻大的量程——原因在误差一节。</p>
    <p>操作：先把滑动变阻器调到阻值最大处再闭合开关，此时电流最小、电压最大；然后逐步减小阻值，让电流单调增大，每变一次读一组 (I, U)，取六到八组。读数一律从表盘的正中间偏右侧取，指针贴着刻度线且避开零点附近，相对误差才小。</p>
    <p>读数范围控制在短路电流的一半以内。电池内阻通常只有零点几欧，短路电流可以达到几安，长时间大电流放电会让电动势下降、内阻上升，数据前后不可比。读数要快，读完立刻断开。</p>

    <h3 class="sec" id="e8-data">数据处理：截距、斜率与两点法</h3>
    <p>把各组 (I, U) 描在坐标纸上，一条直线穿过点群，让两侧的点数相仿、点到直线的距离之和最小。直线画出后：</p>
    <p>纵截距读电动势 ε。取图线与纵轴的交点，别去取某个测量点——测量点都带着读数误差，图线是全部点的共同结果。</p>
    <p>斜率读内阻 r。在直线上取相距较远的两点算 <Katex tex="\left|\Delta U/\Delta I\right|" />，两点越远，由坐标读数带来的相对误差越小。不要用两个原始测点，那两个点未必正好压在直线上。</p>
    <p>有一处常见的形式要求：如果纵轴起点不是零（比如从 1.0 V 起画），图线与纵轴的交点读数就不再是 ε。此时取直线上的任意两点坐标代入 <Katex tex="U_2-U_1=-r(I_2-I_1)" /> 先求 r，再把 r 与某一点坐标一起代回 <Katex tex="\varepsilon=U+rI" /> 求 ε。直接在图上量截距会把轴起点的偏移一并算进去。</p>
    <p>也可以用 <Katex tex="\frac{U}{I}-\frac{1}{I}" /> 图：由 <Katex tex="U=\varepsilon-Ir" /> 两边除以 I 得 <Katex tex="\frac{U}{I}=\varepsilon\cdot\frac{1}{I}-r" />，以 <Katex tex="1/I" /> 为横轴、<Katex tex="U/I" /> 为纵轴作图，斜率给 ε、纵截距给 −r。这种画法对电流较小的数据更敏感，但与 U–I 图给的结果应当一致，可互相校核。</p>

