    <h3 class="sec" id="e10-err">误差：角度读数与光路方向</h3>
    <p>这个实验的系统误差很小，主要误差来自方向定得不够准。</p>
    <p>大头针的间距决定了光线的方向精度。两针相距越近，连线的方向对针的位置偏差越敏感；针插得不竖直，透过玻璃砖看到的像与实际针位错开，四枚针的方向就整体偏转。所以针要插直、针距要大，<Katex tex="P_1P_2" /> 与 <Katex tex="P_3P_4" /> 都尽量长一些。</p>
    <p>界面的位置是另一处来源。所画的界面线要与玻璃砖的边严格重合，铅笔线有粗细，取线的中轴；玻璃砖一旦移动，之前画的界面与现在的砖就对不上，出入点 <Katex tex="O" />、<Katex tex="Q" /> 全部偏移。所以插针的过程中砖不能动，画线与量角都应在移走砖之后进行。</p>
    <p>量角器的读数按最小分度估读，通常读到 0.5° 或 0.1°。<Katex tex="i" /> 与 <Katex tex="r" /> 的绝对误差相同，但 <Katex tex="r" /> 更小，相对误差更大；<Katex tex="\sin i" />–<Katex tex="\sin r" /> 图上靠近原点的点因此更不可靠，这也是要求入射角不小于 15° 的原因。</p>
    <p>若玻璃砖的两个面并不严格平行（上下两条边宽度不等），出射光线与入射光线就不再平行，侧移的判断失效；此时仍可用 <Katex tex="O" />、<Katex tex="Q" /> 的连线求 <Katex tex="r" />，但要知道所测的是玻璃砖在该位置的性质，与标准长方体的结果会有一点差别。玻璃砖的折射率本身随波长变化，白光下看到的是彩色的边缘，用单色光或取中心亮纹读数更稳定。</p>

