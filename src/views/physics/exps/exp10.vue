        <li><strong>提示四：插针过程中挪动玻璃砖或重新画界面。</strong>砖一动，之前的出入点与界面全部作废，得到的 <Katex tex="r" /> 与真实值无关。整套操作里玻璃砖只在最后一步才允许移走。</li>
