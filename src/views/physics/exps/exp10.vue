        <li><strong>提示二：观察时正对玻璃砖面看。</strong>正对砖面时透过砖看到的是折射后的像，视线方向与光线方向不一致，插出的针会系统性偏移。眼睛要沿砖面贴着纸面观察，让远处的两枚针的像重合在一条直线上。</li>
