    <h3 class="sec" id="e10-prin">原理：折射定律与用针定位光线</h3>
    <p>折射定律：光从介质 1 斜射入介质 2，入射光线、折射光线与法线共面，入射光线与折射光线分居法线两侧，且</p>
    <p style="text-align:center"><Katex tex="\frac{\sin i}{\sin r}=\frac{n_2}{n_1}" display /></p>
    <p>光从空气进入玻璃时 <Katex tex="n_2>n_1" />，折射角小于入射角，光线折向法线；从玻璃射回空气时反过来，折射角大于入射角。玻璃砖的两个面平行，射出时那次折射刚好把角度还原，所以<strong>出射光线与入射光线平行</strong>，只是沿垂直方向错开一段距离，这段距离叫侧移。</p>
    <p>光线本身不可见，实验里靠两条事实把它定位。其一，光在均匀介质里沿直线传播，所以一段光路上的任意两点都在同一条直线上。其二，从针的正后方看过去，若近处的针恰好把远处的针挡住，两针与眼睛就落在同一条光线上。把大头针竖直插在纸面上，透过玻璃砖观察并调整位置，使后一枚针遮住前一枚针的像，四枚针的位置就记录了两条光线。</p>
    <p>玻璃砖两面平行这一点筛选了做法：出射光线与入射光线平行，两者不会在玻璃砖附近相交，连线的形状干净；若改用三棱镜或两个面不平行，出射光线会拐一个角度，虽仍可量出折射角，但判断光路是否正确就麻烦得多。</p>
    <p>玻璃里的那一段光线也由两枚针的位置定出：光在玻璃内部同样沿直线传播，所以只要知道光线从界面上哪一点进入、从哪一点射出，把这两点连起来就得到玻璃中的光线，它与法线的夹角就是折射角 <Katex tex="r" />。</p>

    <h3 class="sec" id="e10-step">器材与步骤：描界面、插针、连线</h3>
    <p>器材：玻璃砖、白纸、图钉（或胶带）、大头针四枚、直尺、量角器、铅笔。</p>
    <p>第一步，把白纸固定在桌面上，玻璃砖放在纸的中间，用铅笔沿玻璃砖的两条长边画出两条平行直线，作为两个界面的位置。画线要紧贴玻璃砖的边，笔尖沿着砖边平移，不能把砖移开后再凭印象补画。</p>
    <p>第二步，在玻璃砖的一侧插两枚大头针 <Katex tex="P_1" />、<Katex tex="P_2" />，两针的连线就是入射光线的工作段，间距取两针到玻璃砖距离的中间值，大一些方向定得准。</p>
    <p>第三步，在玻璃砖的另一侧透过玻璃砖观察，先插 <Katex tex="P_3" /> 使它的像恰好挡住 <Katex tex="P_1" />、<Katex tex="P_2" /> 的像，再插 <Katex tex="P_4" /> 使它同时挡住 <Katex tex="P_3" /> 与 <Katex tex="P_1" />、<Katex tex="P_2" /> 的像。观察时眼睛要贴着纸面沿砖的侧面移动，不要正对着砖面看，否则看到的像会因斜视错位。插针过程中玻璃砖的位置一动都不能动。</p>
    <p>第四步，移走玻璃砖与针，用直线连接 <Katex tex="P_3" />、<Katex tex="P_4" /> 并延长到界面，交点记为 <Katex tex="Q" />；连接 <Katex tex="P_1" />、<Katex tex="P_2" /> 并延长到界面，交点记为 <Katex tex="O" />；再连 <Katex tex="OQ" />，它就是玻璃中的光线。过 <Katex tex="O" /> 作界面的法线，量出入射角 <Katex tex="i" />（<Katex tex="P_1P_2" /> 与法线的夹角）与折射角 <Katex tex="r" />（<Katex tex="OQ" /> 与法线的夹角）。</p>
    <p>改变入射角重复上面的过程，取五组以上数据。<Katex tex="i" /> 取 15° 到 75° 之间：角度太小时两条光线都接近法线，量角器的读数误差在结果里的比重很大；角度太大时反射带走的能量多，透过玻璃砖看到的像变暗，插针容易偏。每次只改变入射方向，玻璃砖与所画的界面线保持不动。</p>

    <h3 class="sec" id="e10-data">数据处理：sin i–sin r 图的斜率</h3>
    <p>把每组数据算出两个正弦值，列出表格。逐组做比 <Katex tex="\sin i/\sin r" />，数值基本一致，这本身就验证了折射定律；但把五六个比值取平均，会把个别读错的角一起摊进来，不如作图稳妥。</p>
    <p>以 <Katex tex="\sin r" /> 为横轴、<Katex tex="\sin i" /> 为纵轴描点。由折射定律，纵坐标与横坐标成正比，各点应当落在一条过原点的直线上；坐标轴都从零起画，直线就能自然延长到原点，摆正这一条，斜率才准。求斜率取直线上的两个相距较远的点，用 <Katex tex="n=\dfrac{\Delta(\sin i)}{\Delta(\sin r)}" />，不要直接拿两个原始测点——原始点各自带误差，未必压在直线上。</p>
    <p>若某组点明显偏离直线，先回查这一组的插针与连线：出入点认错、界面线画歪、量角器零点没对齐，都会让这一组单独跑偏，弃用时说明原因，不要为了图好看硬把它拉回直线。</p>
    <p>由折射率还能得到光在玻璃中的速度：<Katex tex="v=c/n" />。<Katex tex="c=3.0\times10^{8}" /> m/s、<Katex tex="n=1.5" /> 时 <Katex tex="v=2.0\times10^{8}" /> m/s，比真空中慢三分之一。频率不变、波长按 <Katex tex="\lambda=\lambda_0/n" /> 变短，这一点在后面的双缝干涉里会用到。</p>

