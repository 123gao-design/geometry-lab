    <p class="cap">图 实1 · <b>纸带与 v–t 图</b>：上半部分是纸带，密集的小点是 0.02 s 的原始点迹，橙色大点是每五个点取一个的计数点，编号 0 到 6，各段位移以厘米标在下方。看点一：橙色点之间的距离依次增大，相邻两段的差是一个定值，读数栏里「Δx = aT₀²」一行给出的正是这个差。看点二：逐差法用六段数据算出的 a 与设定的 a 一致，说明前后两半相减确实把全部数据用上了。看点三：右栏 v–t 图上的六个点落在一条直线上，橙色斜率三角形的两条直角边之比就是加速度，与逐差法的结果对得上。看点四：把初速度拖大，纸带整体右移、各段都变长，但相邻两段的差不变，加速度仍只由 a 滑块决定。</p>

    <h3 class="sec" id="e1-err">误差来源与改进</h3>
    <p>系统误差主要来自摩擦和空气阻力。纸带与限位孔之间、小车与木板之间都有阻力，小车实际受到的合外力小于绳的拉力，实测加速度偏小。把木板一端垫高、用重力沿斜面的分量抵消摩擦，可以显著减小这一项。</p>
    <p>偶然误差主要来自长度测量。用毫米刻度尺读数时要估读一位，每段位移的读数误差约为 0.5 mm；段长本身只有一两厘米，相对误差不小。改用逐差法、拉长计数间隔、让纸带跑得更远，都能把这一项摊薄。</p>
    <p>计时误差来自电源频率的稳定性。市电频率在 50 Hz 附近有微小波动，记录的周期因此不完全等于 0.02 s；这一项在中学实验里通常忽略，若用打点周期计算速度，它会被系统性地带进结果。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把相邻两段之差当成位移本身。</strong>相邻计数点的位移差才等于 aT₀²，量纲是米；单段位移 s 则是 v₀T₀ + ½aT₀² 那一串，两者不能混用。用逐差法时要先分组相减，再除以 9T₀² 或对应的倍数。</li>
        <li><strong>提示二：计数点间隔按点距数，不按点的个数数。</strong>每五个点取一个计数点时，相邻两个计数点之间隔着四个未取的点和五个打点周期，T₀ = 5 × 0.02 s = 0.10 s。误选成四个间隔会把全部结果差出百分之二十五。</li>
        <li><strong>提示三：先释放小车再接通电源。</strong>这样纸带开头一段没有点迹，第一个点不对应释放时刻，位移的零点无从谈起。正确次序是先接通电源、等打点稳定、再释放。</li>
        <li><strong>提示四：用平均速度公式求速度时选错区间。</strong>v_n = (s_n + s_{n+1})/(2T₀) 给出的是第 n 个计数点时刻的速度，两段必须是该点前后相邻的那两段。取不相邻的两段，得到的只是那段时间内的平均速度。</li>
        <li><strong>提示五：把实测加速度偏小归结为读数不准。</strong>若所有数据都一致地偏小，多半是摩擦造成的系统误差，读数误差只会让点在直线两侧散开，不会让整条直线的斜率整体抬起或压下。</li>
      </ul>
