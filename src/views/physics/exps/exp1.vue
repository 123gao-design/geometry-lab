    <h3 class="sec" id="e1-prin">原理：纸带记录了什么</h3>
    <p>打点计时器由计时装置和打点装置两部分组成。交流电每过一个周期改变一次方向，线圈的磁场随之变化，振针被吸放一次，就在纸带上留下一个点。频率为 50 Hz 时，相邻两点的时间间隔是 <Katex tex="T=0.02\,\mathrm{s}" />。电火花计时器用高压放电在纸带上留下点迹，阻力更小，但计时周期相同。</p>
    <p>纸带与运动物体连在一起，点与点的间距就是物体在相等时间内发生的位移。教材上的题目通常不直接使用 0.02 s 的点，而是每隔四个点取一个计数点，于是相邻计数点的时间间隔</p>
    <p style="text-align:center"><Katex tex="T_0=5T=0.10\,\mathrm{s}" display /></p>
    <p>取计数点的目的一是让间隔拉开、便于测量，二是把点迹过密带来的判读误差摊薄。</p>
    <p>匀变速直线运动在连续相等时间内的位移构成等差数列，公差为</p>
    <p style="text-align:center"><Katex tex="s_{n+1}-s_n=aT_0^2" display /></p>
    <p>这个式子是整个实验的立足点。它只用到加速度恒定这一条，与初速度无关，也不必知道第一个计数点对应哪一时刻。若把间隔再拉开三段，则有 <Katex tex="s_{n+3}-s_n=3aT_0^2" />，两种写法是同一条式子的不同形式。</p>
    <p>中间时刻的瞬时速度用相邻两段的平均速度代替。因为匀变速运动的平均速度等于中间时刻的瞬时速度，第 <Katex tex="n" /> 个与第 <Katex tex="n+1" /> 个计数点之间的中间时刻恰是计数点 <Katex tex="n" /> 之后半个间隔处，于是</p>
    <p style="text-align:center"><Katex tex="v_n=\frac{s_n+s_{n+1}}{2T_0}" display /></p>
    <p>这条式子给出每一个计数点时刻的速度，把它们依次描点连线，就得到 v–t 图。</p>

    <h3 class="sec" id="e1-step">器材与操作步骤</h3>
    <p>器材：电磁打点计时器或电火花计时器、学生电源、纸带、复写纸、刻度尺、小车、长木板、细绳、钩码、导线。</p>
    <p>操作顺序是：把长木板平放在桌面上，一端垫高以平衡摩擦；纸带穿过限位孔，压在复写纸下面，另一端与小车相连；小车停在靠近计时器的一端，先接通电源，待打点稳定后再释放小车；纸带打完后立即断开电源，取下纸带。</p>
    <p>「先接通电源，后释放小车」不是可有可无的次序。电源接通前计时器不打点，先放小车会漏掉开头一段，纸带上第一个点与释放时刻不对应，后面所有位移都失去了共同的零点。同理，实验结束后要先断电再取纸带，否则小车停下时振针还在打点，纸带末端会叠成一团墨迹。</p>
    <p>纸带的选取也有讲究。从点迹清晰的纸带中挑一条，舍去开头过于密集的一段，选一个点作为第 0 个计数点，以后每隔四个点标一个计数点，依次编号 0、1、2……用刻度尺测量各计数点到 0 点的距离，相邻两个读数相减得到各段位移。</p>

    <h3 class="sec" id="e1-data">数据处理：逐差法与 v–t 图</h3>
    <p>设六段位移依次为 <Katex tex="s_1" /> 到 <Katex tex="s_6" />。最直接的办法是把相邻两段相减再取平均：</p>
    <p style="text-align:center"><Katex tex="a=\frac{(s_2-s_1)+(s_3-s_2)+\cdots+(s_6-s_5)}{5T_0^2}" display /></p>
    <p>这个写法有一个毛病：括号里的项两两抵消，最后只剩 <Katex tex="s_6-s_1" />，中间四段其实没有起作用，等于只用了首尾两段。为了用上全部数据，把六段分成前后两半，对应项相减：</p>
    <p style="text-align:center"><Katex tex="s_4-s_1=3aT_0^2,\quad s_5-s_2=3aT_0^2,\quad s_6-s_3=3aT_0^2" display /></p>
    <p>三式相加再除以 <Katex tex="9T_0^2" />，得到逐差法的公式：</p>
    <p style="text-align:center"><Katex tex="a=\frac{(s_4+s_5+s_6)-(s_1+s_2+s_3)}{9T_0^2}" display /></p>
    <p>每一段都出现在分子里，偶然误差在求和过程中部分抵消，这是逐差法比两段相减可靠的地方。段数是奇数时，通常舍去最短或最不可靠的一段再分组。</p>
    <p>第二条处理路线是先求速度、再求斜率。按前面的式子逐点算出 <Katex tex="v_1,v_2,\dots" />，以 <Katex tex="t" /> 为横轴描点，用一条直线拟合这些点。直线过原点与否取决于计时起点，斜率总是加速度；若某个点明显偏离直线，多半是该点测量或判读有误，画线时不必强行穿过它。</p>

