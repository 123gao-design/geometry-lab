    <p class="cap">图 实7 · <b>伏安法测电阻的两种接法</b>：左栏是测量电路，青色圆框是电压表，它的两个接点（青点）画在待测电阻所在的一段上；右栏以 Rₓ 为横轴，橙线是内接的相对误差 R_A/Rₓ、蓝虚线是外接的相对误差 Rₓ/R_V，紫点标出两条线的交点 √(R_A·R_V)。看点一：默认 Rₓ = 50 Ω、R_A = 1 Ω、R_V = 5 kΩ，内接测得 51.00 Ω、偏大 2.00%，外接测得 49.50 Ω、偏小 0.99%，此时 50 Ω 小于临界电阻 70.7 Ω，宜用外接。看点二：切到「电流表内接」，电压表的左边接点从电流表的右侧移到左侧，量程里就多进了电流表那一段，读数栏的测量值随即跳到偏大的一侧。看点三：把 Rₓ 拖到 300 Ω 以上，橙点掉到蓝点下方，判读改口为「宜用内接」——大电阻要让电流表的串联分压尽量小。看点四：把电流表内阻拖小或电压表内阻拖大，紫点向左下方退，两条曲线整体压低，说明表越理想、两种接法的差别越小。</p>

    <h3 class="sec" id="e7-err">误差：内接与外接怎么选</h3>
    <p>内接的系统误差全部来自电流表的内阻。待测电阻只有几欧时，1 Ω 的内阻就能带来百分之几十的偏差，这类小电阻必须用外接。</p>
    <p>外接的系统误差全部来自电压表的内阻。待测电阻几百欧以上时，电压表几 kΩ 的内阻已经不算大，分流比例上去了，这类大电阻必须用内接。</p>
    <p>两个电表的内阻可以用半偏法或替代法另行测定，也可以从表盘或说明书上读出量级。临界电阻 <Katex tex="\sqrt{R_\text{A}R_\text{V}}" /> 按估出的内阻现算，与待测电阻一比就定下接法，不必等到测完再回头改。</p>
    <p>接线本身也会带来误差。接线柱接触不良相当于串了一个几欧的不稳电阻，对小电阻的测量影响很大；导线过长、接头过多也有同样的问题。测量小电阻时尤其要把接线压紧。</p>

