        <li><strong>提示一：以为两种接法只是画法不同。</strong>接法改变的是「测的是谁的电压、谁的电流」：内接的电压含电流表分压，外接的电流含电压表分流。测量值一个偏大、一个偏小，方向必须记清。</li>
        <li><strong>提示二：把比值 U/I 当成电阻真值。</strong>U/I 给出的是这一段的等效电阻，只有把表的内阻影响算进去才能还原 Rₓ。小电阻用外接、大电阻用内接，就是把偏差压在可以忽略的一侧。</li>
        <li><strong>提示三：不估量级就随手接一种。</strong>待测电阻与临界电阻差一个量级时，选错接法的误差可以到百分之几十。先估 Rₓ 的大小，再按 √(R_A·R_V) 定接法，比测完发现偏得离谱再重来省事。</li>
