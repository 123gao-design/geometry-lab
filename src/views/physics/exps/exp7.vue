    <h3 class="sec" id="e7-prin">原理：R = U/I 与两种接法</h3>
    <p>把待测电阻接入电路，让电流通过它，用电流表量这股电流、用电压表量它两端的电压。读数代入 <Katex tex="R=U/I" /> 即得电阻。这一步本身没有近似，问题都出在「电压」与「电流」是不是恰好对应电阻本身。</p>
    <p>先看电流表内接。电流表与待测电阻串联，电压表跨在两者之外，量的电压是电流表内阻上的电压与待测电阻上的电压之和：</p>
    <p style="text-align:center"><Katex tex="U=I(R_\text{x}+R_\text{A}),\qquad R'=R_\text{x}+R_\text{A}" display /></p>
    <p>其中 R′ 是电压表读数与电流表读数之比。电流表读到的正是通过待测电阻的电流，这一路是准的；电压表多量了电流表那一段。测量值比真值大一个 <Katex tex="R_\text{A}" />，相对误差是 <Katex tex="R_\text{A}/R_\text{x}" />，待测电阻越大、这项误差越小。</p>
    <p>再看电流表外接。电压表直接并在待测电阻上，量到的电压就是它两端的电压；电流表却在干路上，读到的电流是流过待测电阻的电流与流过电压表的电流之和：</p>
    <p style="text-align:center"><Katex tex="I=\frac{U}{R_\text{x}}+\frac{U}{R_\text{V}},\qquad R'=\frac{R_\text{x}R_\text{V}}{R_\text{x}+R_\text{V}}" display /></p>
    <p>测量值是两个电阻的并联值，比真值小。相对误差约等于 <Katex tex="R_\text{x}/R_\text{V}" />，待测电阻越小、这项误差越小。</p>
    <p>两条误差曲线的方向相反，因此必有一个交点。令 <Katex tex="R_\text{A}/R_\text{x}=R_\text{x}/R_\text{V}" />，解得</p>
    <p style="text-align:center"><Katex tex="R_\text{x}=\sqrt{R_\text{A}R_\text{V}}" display /></p>
    <p>这就是临界电阻。待测电阻明显大于它时内接的误差更小，明显小于它时外接的误差更小；正好相等时两种接法的相对误差相同。</p>

    <h3 class="sec" id="e7-step">器材与步骤：分压与限流</h3>
    <p>器材：待测电阻、电压表、电流表、滑动变阻器、直流电源、开关、导线。</p>
    <p>先估一下待测电阻的量级，再按临界电阻选定内接或外接。接好电路后，闭合开关前把滑动变阻器调到使电压尽量小的一端，读数从小往大调，避免一开始就把表打满。</p>
    <p>滑动变阻器有两种用法。限流接法把变阻器串进主电路，靠它分担一部分电压来调节被测部分；这种接法简单、耗电少，但电压调不到零，调节范围也有限。分压接法把变阻器整体并在电源上，从滑动端与一端之间引出电压供给测量电路；电压可以从零连续调到电源电压，调节范围宽，代价是干路一直通着电流、耗电较大。</p>
    <p>以下三种情形应当用分压接法：要求电压从零开始调节；待测电阻远大于滑动变阻器的最大阻值，限流时调不动；限流接法下调不出需要的电流或电压。其余情形优先用限流，接线更简单、不易出错。</p>
    <p>如果事先估不准待测电阻的量级，可以用试触法：先把电压表的一个接线端接在被测部分的一端，另一个接线端分别点在电流表的两侧，看两次电压表的示数变化与电流表示数变化谁更明显。电压表示数变化明显，说明电压表分流影响大，应避开外接、选内接；电流表示数变化明显，说明电流表分压影响大，应避开内接、选外接。</p>

    <h3 class="sec" id="e7-data">数据处理：多次测量与图象法</h3>
    <p>单次测量的结果就是一组电压与电流的比值。为了压住偶然误差，改变滑动变阻器的位置测五六组不同的 U 与 I，逐组算出 <Katex tex="R_i=U_i/I_i" /> 再取平均；也可以只取一组就下结论，但那样既看不出偶然误差，也发现不了接错线。</p>
    <p>更稳的做法是图象法。以 I 为纵轴、U 为横轴描点，若待测电阻不随电压变化，各点应落在一条过原点的直线上，直线的斜率是</p>
    <p style="text-align:center"><Katex tex="k=\frac{1}{R'}" display /></p>
    <p>由斜率取倒数即得电阻。作图把每组数据的偶然误差摊薄，斜率由许多点共定，比逐组求比值再平均更抗干扰。若图线不过原点，说明表有零点误差，或者电路中还串着别的不该有的接触电阻。</p>
    <p>最后把测量值与标称值或已知值比较，算出相对误差，并说明这个偏差主要来自哪种接法带来的系统误差。</p>

