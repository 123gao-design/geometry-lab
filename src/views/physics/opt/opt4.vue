    <h3 class="sec" id="o4-coh">相干条件与叠加</h3>
    <p>光波叠加时，空间某点的振动是所有到达该点的振动的合成。若两列波在某点同相（相位差是 <Katex tex="2\pi" /> 的整数倍），合振幅等于振幅之和，该点始终最亮；若反相，合振幅等于振幅之差，该点始终最暗。两种情形都会在屏上留下稳定的图样，合起来就叫干涉条纹。</p>
    <p>能否看到条纹，取决于两束光之间有没有稳定的相位关系。普通光源的原子各自独立发光，两次发光的相位没有联系，两束光叠加后的明暗在极短时间内跳变，人眼看到的是平均效果，条纹就被抹平了。所以相干条件有三条：频率相同、相位差恒定、偏振方向不互相垂直。</p>
    <p>获得相干光的一种常用办法是把同一束光「分」成两束：分波前法让光同时穿过两条狭缝，分振幅法让光在薄膜的两个表面上各反射一次。两束光来自同一个波前，频率天然相同，相位差由走过的路程决定，因此是稳定的。</p>
    <p>需要留意的是，干涉的前提是光有波动性。光波的频率极高（可见光在 <Katex tex="10^{14}" /> Hz 量级），任何探测器都跟不上它的振动，只能测到长时间的平均强度。条纹的稳定正说明这种平均是有结构的：有的位置平均下来仍然是零。</p>

    <h3 class="sec" id="o4-double">双缝干涉与光程差</h3>
    <p>杨氏双缝实验中，一束单色光垂直照到两条相距 <Katex tex="d" /> 的狭缝上，缝后各发出一列柱面波，两列波在屏上叠加。屏距 <Katex tex="L" /> 远大于缝距 <Katex tex="d" />，屏上离中心 <Katex tex="y" /> 处的光程差可以近似为</p>
    <p style="text-align:center"><Katex tex="\Delta r\approx d\sin\theta\approx \dfrac{dy}{L}" display /></p>
    <p>近似成立的条件是 <Katex tex="y\ll L" />：两个缝到该点的距离差，在屏上展开就相当于「缝距投影到倾斜方向上」，取小角近似 <Katex tex="\sin\theta\approx\tan\theta=y/L" />。</p>
    <p>于是光程差与条纹的对应关系是：<Katex tex="\Delta r=k\lambda" /> 处为亮纹，<Katex tex="\Delta r=\left(k+\tfrac12\right)\lambda" /> 处为暗纹，</p>
    <p><Katex tex="k" /> 是条纹的级次。中央 <Katex tex="y=0" /> 处光程差为零，两束光同相，是零级亮纹。两边的亮纹依次对 <Katex tex="k=1,2,\dots" />，级次越高，偏角越大。</p>
    <p>不只是双缝，两块相邻平面之间的劈尖、透镜与平板之间的空气层，都能让同一束光分成两路再合起来。只要光程差落在半个波长的整数倍附近，就出现明暗交替。</p>

