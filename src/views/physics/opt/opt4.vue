    <p class="cap">图 光4 · <b>双缝干涉：一条亮一条暗从哪里来</b>：左栏是光路示意，挡板上两条缝到屏上观察点 P 各连一条光线，缝距按可见比例画大；缝前那一列竖直的线是入射平面波的波前，正以匀速向右移动，过缝后两条缝各发出一圈圈同相波峰，向屏的方向一层层推开。右栏是屏上的光强分布曲线与它下面的彩色条纹。看点一：默认 λ = 550 nm、d = 0.5 mm、L = 1 m，条纹间距约 1.1 mm，观察点正落在第一级亮纹上，读数栏「级次」为 1.00。看点二：把观察点 y 慢慢拖过半条条纹，光强从最亮降到零，读数栏那行从「亮纹」翻成「暗纹」，光程差正好是 λ 的半个奇数倍。看点三：把波长拖向红端，屏上的条纹变宽、条纹颜色随之变化，左栏波峰的间距也跟着拉开；把缝距 d 拖大，条纹被压密——右栏的峰一个挨一个挤在一起，左栏两组圆弧的交错角度同时变小。看点四：盯着左栏两组圆弧看，某些方向上它们正好「峰对峰」、有些方向上「峰对谷」，前一类方向连起来正是右栏的亮纹。看点五：读数栏最后一行「Δx·d/L」拖任何滑块都等于波长，这就是用双缝测波长的原理。</p>

    <h3 class="sec" id="o4-fringe">条纹间距与波长的测量</h3>
    <p>相邻两条亮纹的距离由 <Katex tex="\Delta r=k\lambda" /> 两式相减得到：</p>
    <p style="text-align:center"><Katex tex="\Delta x=\dfrac{L}{d}\,\lambda" display /></p>
    <p>条纹间距与波长成正比，与屏距成正比，与缝距成反比。缝距越窄、屏越远，条纹张得越开，越容易分辨——这正是双缝实验要在暗室里仔细调间距的原因。</p>
    <p>把式子反过来写就得到测波长的办法：</p>
    <p style="text-align:center"><Katex tex="\lambda=\dfrac{d\,\Delta x}{L}" display /></p>
    <p>量出双缝间距、屏距，再用测微目镜测出若干条条纹的总宽度求平均，就能算出波长。这是历史上第一次在实验室里量出光的波长，所得结果与后来用衍射光栅测得的完全一致，也第一次把「光是一种波」落到了具体的数字上。</p>
    <p>白光做双缝干涉时，中央亮纹是各色光共同的零级亮纹，叠加起来是一条白线；两侧的条纹因为各色光的波长不同、间距不同，彩色彼此错开，于是变成一条条彩色带，越往外越模糊，直到相互重叠看不清。单色光则几乎能一直看到高处的条纹，只是亮度随偏角增大而下降。</p>
    <p>屏上能看到多少条条纹，还受缝宽限制。缝太宽时，每条缝自己发出的光也发生衍射，中央亮斑收窄，高处的干涉条纹被包络压低，最后只剩中间几条。这与下一章的衍射同源，双缝实验里两者总是一起出现。</p>

    <h3 class="sec" id="o4-film">薄膜干涉</h3>
    <p>肥皂膜、油膜、镜片上的镀层都能看到彩色条纹，这来自薄膜上下两个表面的反射光叠加。光射到膜的上表面，一部分反射，一部分折射进入膜内；进入膜内的光在膜的下表面再反射一次，返回上表面后射出。两束反射光走过的路程相差一个来回，光程差约为</p>
    <p style="text-align:center"><Katex tex="\Delta r=2nd\cos r" display /></p>
    <p>其中 <Katex tex="n" /> 是膜材料的折射率、<Katex tex="d" /> 是膜厚、<Katex tex="r" /> 是膜内的折射角。垂直入射时 <Katex tex="\cos r=1" />，光程差就是 <Katex tex="2nd" />。</p>
    <p>还有一处必须补上：光从光疏介质射向光密介质时，反射光发生半个波长的相位突变（半波损失）；从光密射向光疏则没有。如果薄膜的折射率介于两侧介质之间，上下两次反射中只有一次有半波损失，两束反射光的相位差里就要额外加半个波长。</p>
    <p>照相机的镜头镀膜就利用了这一点。要让某一波长的反射光相互抵消，膜的光程差应满足</p>
    <p style="text-align:center"><Katex tex="2nd=\left(k+\tfrac12\right)\lambda" display /></p>
    <p>取 <Katex tex="k=0" /> 就得到最薄的一层：<Katex tex="d=\dfrac{\lambda}{4n}" />。</p>
    <p>厚度取四分之一波长除以折射率时，该波长的反射光相消、透射光增强。这种膜叫增透膜，调成蓝紫色是因为人眼对绿光最敏感，而把绿的反射减到最低、剩下的红蓝混合起来看就成了淡蓝紫。反过来，需要高反射率的镜子会镀多层膜，让各层反射光同相叠加。</p>
    <p>肥皂膜上的彩色条纹是同一套道理在膜厚不均匀时的表现。膜受重力往下流、上面薄下面厚，同一级次的条纹落在等厚的地方，于是形成水平的彩色横纹；随着水往下流，条纹慢慢下移，最终破裂。油膜铺在水面上、劈尖形的空气层、牛顿环的同心圆环，都是「等厚干涉」的不同表现。</p>

