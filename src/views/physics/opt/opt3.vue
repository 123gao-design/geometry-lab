    <h3 class="sec" id="o3-convex">凸透镜的成像规律</h3>
    <p>把公式 <Katex tex="v=\dfrac{uf}{u-f}" /> 里的 <Katex tex="u" /> 从大往小扫一遍，像的性质分五段，每段的分界都是焦距的整数倍。</p>
    <p>物体在两倍焦距以外（<Katex tex="u>2f" />）时，<Katex tex="f<v<2f" />，像在另一侧、比物小，是倒立缩小的实像。照相机就工作在这一段：景物很远，底片（或传感器）放在焦点稍外一点，就能把大范围收进一张小图。</p>
    <p>物体恰好放在两倍焦距处（<Katex tex="u=2f" />）时，<Katex tex="v=2f" />，像与物等大、倒立，这是判断焦距常用的方法——把物与屏各摆在透镜两侧，使像与物等大，两边的距离就都是 <Katex tex="2f" />。</p>
    <p>物体在一倍与两倍焦距之间（<Katex tex="f<u<2f" />）时，<Katex tex="v>2f" />，像是倒立放大的，投影仪与幻灯机在这一段工作：幻灯片靠近镜头，屏幕上得到一个远比它大的像。</p>
    <p>物体在焦点上（<Katex tex="u=f" />）时，出射光线互相平行，既不成实像也不成虚像，像在无穷远。探照灯把光源放在焦点上，正是为了得到一束平行光。</p>
    <p>物体在焦距以内（<Katex tex="u<f" />）时，公式给出 <Katex tex="v<0" />，像是与物同侧的虚像，正立放大。放大镜就工作在这一段：透镜贴近被看的东西，透过镜片看到的是一个更大的、正立的图。</p>
    <p>这五段可以压成三句口诀，但每句都能从公式验算：一倍焦距分虚实，二倍焦距分大小，物近像远像变大。最后一句只在成实像时成立——虚像一侧是物越近像越小。</p>

    <h3 class="sec" id="o3-use">凸透镜的三种用法</h3>
    <p>照相机、投影仪、放大镜用的是同一块凸透镜，区别只在物距落在哪一段。</p>
    <p>照相机把 <Katex tex="u>2f" /> 的景物拍成缩小的实像，镜头到传感器的距离由调焦机构改变，让传感器落在像的位置上。近处对焦时物距减小、像距增大，镜头要往前伸一点。</p>
    <p>投影仪把 <Katex tex="f<u<2f" /> 的幻灯片投成放大的实像，屏幕上要亮，所以幻灯片要用强光从背后透射；为了得到正立的画面，幻灯片本身是倒着插进光路的——通光孔成的实像是倒立的，倒的幻灯片正好正过来。</p>
    <p>放大镜用 <Katex tex="u<f" /> 成虚像，像与物同侧、正立放大。它没法投到屏幕上，只能靠近眼睛看；放大倍数大致是 <Katex tex="1+\dfrac{D}{f}" /> 的量级，焦距越短倍数越高，但焦距太短的镜片畸变与色差也更明显。</p>
    <p>眼睛本身也是一套透镜系统，只是这枚「镜头」的焦距可以由睫状肌改变。看近处时晶状体变凸、焦距变短，看远处时放松变扁。近视眼成像落在视网膜之前，用凹透镜先发散一下；远视眼成像落在视网膜之后，用凸透镜先会聚一下。</p>

    <h3 class="sec" id="o3-concave">凹透镜</h3>
    <p>凹透镜中间薄、边缘厚，平行光射入后向外发散，折射光线的反向延长线交于同侧的焦点。按符号约定它的焦距取负值，代进同一条公式即可。</p>
    <p>因为 <Katex tex="f<0" />，<Katex tex="v=\dfrac{uf}{u-f}" /> 恒为负：像总在物的同一侧，总是正立、缩小的虚像。物从远处移近，虚像从焦点向内移动，尺寸逐渐逼近物本身，但始终比物小、始终是正的。</p>
    <p>凹透镜还有一种读法：它把射来的光束「摊开」，让同一孔径里的光对应更大的视角。近视镜片用它，就是先把来自远处物体的发散光再发散一点，使成像点后移到视网膜上；散光镜片则在两个互相垂直的方向上取不同的曲率，把不同方向的光分别校正。</p>
    <p>用凹透镜成像时，三条特殊光线的画法与凸透镜一样，只是「过焦点」那一条改为「射向另一侧焦点」：光线在镜内没有实际的焦点，出射后反向延长过焦点。作图时把延长线画成虚线，提醒它不是真实的光路。</p>

