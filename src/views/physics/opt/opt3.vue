    <h3 class="sec" id="o3-law">薄透镜公式与三条特殊光线</h3>
    <p>先看凸透镜。放在左侧光轴上的物体向四面八方发光，其中射到透镜上的那一束被折射后会聚到另一侧的某一点，这就是像点。薄透镜假定镜片的厚度远小于焦距，光线在镜片上只折一次，镜片可以看作一个平面。</p>
    <p>三条特殊光线的去向是确定的：平行于光轴射入的光线，折射后过另一侧的焦点；过光心的光线不改变方向；过一侧焦点射入的光线，折射后平行于光轴射出。任意两条的交点就是像点，第三条线必然也过这一点。所以作图只要两条，第三条用来核对。</p>
    <p>把这三条光线与相似三角形合起来，就得到薄透镜公式</p>
    <p style="text-align:center"><Katex tex="\dfrac{1}{u}+\dfrac{1}{v}=\dfrac{1}{f}" display /></p>
    <p>放大率是像高与物高之比。由过光心的那条光线所成的相似三角形，<Katex tex="h'/h=v/u" />；按约定倒立的像取负值，于是 <Katex tex="m=-\dfrac{v}{u}" />，<Katex tex="m" /> 的绝对值就是放大的倍数。</p>
    <p>符号约定只有两条：物距 <Katex tex="u" /> 一律取正；像距 <Katex tex="v" /> 在透镜另一侧（实像）为正，与物同侧（虚像）为负。凹透镜的焦距取负值，公式照样成立，不必另记一套。</p>
    <p>实像与虚像的区别在能否承接。实像是折射后真实会聚的光，屏幕上放一张白纸就能看到；虚像是折射后仍在发散的光，这些光线的反向延长线才交于一点，屏幕上接不到，只能顺着光线看过去才觉得像在那里。</p>

