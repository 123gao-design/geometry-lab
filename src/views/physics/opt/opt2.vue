    <h3 class="sec" id="o2-dev">偏向角与最小偏向角</h3>
    <p>出射光线相对入射光线转过的角度叫偏向角。在第一个面上偏转 <Katex tex="i_1-r_1" />，在第二个面上再偏转 <Katex tex="r_2-i_2" />，合起来</p>
    <p style="text-align:center"><Katex tex="\delta=(i_1-r_1)+(r_2-i_2)=i_1+r_2-A" display /></p>
    <p>固定顶角与折射率，让 <Katex tex="i_1" /> 从很小扫到接近 90°，偏向角先减小后增大，中间有一个最小值。取极值的条件是光线在棱镜内与顶角的角平分线平行，此时 <Katex tex="i_1=i_2,\ r_1=r_2=A/2" />，代进折射定律得</p>
    <p style="text-align:center"><Katex tex="\sin\dfrac{A+\delta_m}{2}=n\sin\dfrac{A}{2}" display /></p>
    <p>这个关系把顶角、折射率、最小偏向角三者绑在一起，是测量固体折射率最常用的方法：量出顶角与最小偏向角，就能反解出 <Katex tex="n" />。工作台上的「折射率」一栏就是这么标定的——它的值对应 589 nm 的钠黄光。</p>
    <p>偏向角有下界，是因为两次折射的偏折量此消彼长。入射角小时第一面偏折少、但第二面的入射角大，接近临界角，偏折多甚至发生全反射；入射角大时第一面偏折多、第二面的入射角小。两端都不合算，中间那一处两头的负担相当，总偏转最小。</p>
    <p>如果第二面的入射角超过临界角，光线不从第二面射出，而是在镜内发生全反射。这时偏向角突然变得很大，右栏的曲线也在此处中断——这正是棱镜用作反射棱镜的原理。</p>

    <h3 class="sec" id="o2-disp">色散与光谱</h3>
    <p>以上分析默认折射率是一个常数。实际上同一种介质对不同波长的光折射率不同：波长越短，折射率越大。在可见光范围内，紫光的折射率比红光大百分之几，这就是色散。</p>
    <p>棱镜把这种微小差别放大成可见的分离。两次折射每次都会把不同波长略微拉开，出射角之差再传播一段距离，就成了一条能分辨的光带。工作台上的色散系数取得比普通光学玻璃略大（紫红折射率相差约 0.06，接近重火石玻璃），色带才看得清楚。</p>
    <p>色散随波长的变化常用柯西公式描述：</p>
    <p style="text-align:center"><Katex tex="n(\lambda)=A+\dfrac{B}{\lambda^2}" display /></p>
    <p>波长越短，第二项越大，折射率也就越大。这一形式在可见光波段足够准确，工作台里的折射率正是按这条式子随波长给出的。</p>
    <p>色散也解释了彩虹。空气中的小水滴相当于无数个微型棱镜：阳光射入水滴后在水滴内部反射一次、再折射出来，不同颜色的出射角不同，落进眼睛的方向也就不同。彩虹总是红光在外、紫光在内，正与棱镜中紫光偏折最多保持一致。</p>

    <h3 class="sec" id="o2-app">色散的应用与自然现象</h3>
    <p>分光镜与光谱仪是棱镜最直接的应用。把待测的光送进棱镜，不同波长的成分落在不同方向上，用屏或探测器记录，就得到光谱。原子的特征谱线正是靠这种方法发现的——每种元素发出的谱线位置固定，等于给物质做了一次指纹比对。</p>
    <p>棱镜在光学仪器里还常用来改变光路。等腰直角棱镜让光线在斜面上以 45° 入射，超过临界角发生全反射，方向转过 90°；配合两块棱镜可以把像倒转，用在双筒望远镜与单反相机的取景器里。与镀银反射镜相比，全反射不吸收光，成像更亮。</p>
    <p>反过来，色散在很多场合是需要抑制的。望远镜与显微镜的镜头若用单片玻璃，不同颜色的焦点落不到一处，边缘会出现彩色镶边，这叫色差。解决办法是用折射率与色散系数不同的两种玻璃胶合成透镜组，让两种颜色的偏折互相补偿——这是消色差透镜的设计思路。</p>
    <p>还有一个容易忽略的现象：白光经棱镜分成色带后，若再用一块完全相同的棱镜反向放置，各色光又能重新合回白光。这说明颜色的差别来自它们走过的光路不同，而不是棱镜给光「染了色」。棱镜本身并没有把白光分开的倾向，它只是按波长区别对待而已。</p>

