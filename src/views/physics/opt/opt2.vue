    <h3 class="sec" id="o2-prism">光线穿过棱镜的两次折射</h3>
    <p>把棱镜看成两块互不平行的界面围成的透明介质。光线从左侧面进入时由空气进入玻璃，向法线偏折；从右侧面射出时由玻璃进入空气，偏离法线。两次偏折方向相同，所以出射光线相对入射光线转过了一个明显的角度。</p>
    <p>设光线在第一个面上的入射角为 <Katex tex="i_1" />、折射角为 <Katex tex="r_1" />，在第二个面上的入射角为 <Katex tex="i_2" />、折射角为 <Katex tex="r_2" />。看棱镜内的那个三角形：光线在两界面上的折射角与入射角正好构成顶角 <Katex tex="A" /> 的两部分，于是</p>
    <p style="text-align:center"><Katex tex="r_1+i_2=A" display /></p>
    <p>这是棱镜几何的全部关系，只需在两面各用一次折射定律：<Katex tex="\sin i_1=n\sin r_1" />，<Katex tex="n\sin i_2=\sin r_2" />。三个式子联立，给定顶角、折射率与入射角，光路就唯一确定。</p>
    <p>棱镜与平行玻璃砖的区别正在这里。平行玻璃砖的两个界面互相平行，两次折射的偏折正好抵消，出射光线与入射光线平行，只是侧移了一段。棱镜的两个面成一定夹角，偏折不但不抵消，还叠加在一起。</p>

