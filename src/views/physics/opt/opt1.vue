    <h3 class="sec" id="o1-speed">折射率与光速</h3>
    <p>折射率有两种写法。光从真空射入某种介质时的折射率叫该介质的<strong>绝对折射率</strong>，通常直接简称为折射率；两种介质之间的比值叫<strong>相对折射率</strong>。本章里的 <Katex tex="n_1" />、<Katex tex="n_2" /> 都指绝对折射率。</p>
    <p>折射率与光在介质中的传播速度由下面的关系联系起来：</p>
    <p style="text-align:center"><Katex tex="n=\dfrac{c}{v}" display /></p>
    <p>其中 <Katex tex="c=3.0\times10^8\ \mathrm{m/s}" /> 是真空中的光速。介质的折射率越大，光在其中走得越慢。玻璃的折射率约 1.5，光在玻璃中的速度约为 <Katex tex="2.0\times10^8\ \mathrm{m/s}" />；水的折射率约 1.33，光在水中的速度约为 <Katex tex="2.25\times10^8\ \mathrm{m/s}" />。</p>
    <p>把这一条与折射定律合起来看，就得到另一个等价的写法：</p>
    <p style="text-align:center"><Katex tex="\dfrac{\sin\theta_1}{\sin\theta_2}=\dfrac{v_1}{v_2}" display /></p>
    <p>光速大的那一侧角度大，光速小的那一侧角度小。折射定律的实质是光在两种介质中传播速度不同，在界面处必须改变方向才能保持波前的连续——这一点在波动光学一节还会遇到。</p>
    <p>频率在折射过程中不改变，改变的是波长与速度：<Katex tex="\lambda_1/\lambda_2=v_1/v_2" />。这一条下一节讲色散时要用：不同颜色的光在玻璃中速度不同，折射率也就不同，于是同一束白光经棱镜后分开。</p>

    <h3 class="sec" id="o1-tir">全反射与临界角</h3>
    <p>光从光疏介质射向光密介质时，无论入射角多大，折射角都小于 90°，折射光始终存在。反过来，光从光密介质射向光疏介质时，折射角大于入射角；入射角增大到某个值时，折射角正好达到 90°，折射光贴着界面走。再增大入射角，折射定律给出的 <Katex tex="\sin\theta_2" /> 大于 1，无解——折射光不再存在，入射光的能量全部回到原介质。</p>
    <p>这个临界情形由 <Katex tex="n_1\sin\theta_c=n_2\sin 90^\circ" /> 解出：</p>
    <p style="text-align:center"><Katex tex="\theta_c=\arcsin\dfrac{n_2}{n_1}\qquad(n_1>n_2)" display /></p>
    <p>全反射的两个条件缺一不可：<strong>光从光密介质射向光疏介质</strong>，且<strong>入射角不小于临界角</strong>。第一条不满足时临界角根本不存在；第二条不满足时折射光依然存在。判断一道题有没有全反射，先看方向，再看角度。</p>
    <p>几种常见界面的临界角：水到空气约 48.8°，玻璃（n = 1.5）到空气约 41.8°，钻石到空气约 24.4°。折射率越大，临界角越小，越容易发生全反射——这解释了钻石为什么格外亮：进入钻石的光在内部反复全反射，最后才从少数几个面射出。</p>

    <h3 class="sec" id="o1-app">全反射的用场与常见现象</h3>
    <p>光导纤维是全反射最直接的应用。纤维由内芯与外套两层玻璃组成，内芯折射率大、外套折射率小。光从端面射入后，在内芯与外套的界面上以大于临界角的角度反复全反射，几乎不损失能量地沿着弯曲的纤维传下去。通信用的光纤正是靠这一点把光信号送上千公里。</p>
    <p>全反射棱镜用来改变光路。等腰直角棱镜的临界角约 41.8°，光垂直射入一个直角边后在内侧面上以 45° 入射，大于临界角，发生全反射，方向转过 90°；两块这样的棱镜组合可以把像倒转。与镀银的反射镜相比，全反射没有金属吸收，效率更高。</p>
    <p>自然界的例子也不少。沙漠中的海市蜃楼是空气层温度不同、折射率随高度变化，光线在近地面的热空气层中连续弯折，最后发生全反射而折回观察者的眼睛。夏日柏油路面上的「水面」是同一机制：远处的景物经全反射映入眼中，看上去像倒影。</p>
    <p>反过来，光从空气射入水中时永远不会发生全反射，看到的只是折射与部分反射。水中的潜水员向上看，视野被限制在一个圆锥里，锥外的水面像镜子一样映出水下的景象——那正是从水射向空气的全反射。</p>

