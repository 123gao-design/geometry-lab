    <h3 class="sec" id="o1-law">折射定律</h3>
    <p>把一束光斜射到平静水面上，可以看到两件事：水面反射出一束光，同时水下另有一束光折向深处。前者是反射，后者是折射。折射光不是沿着原方向直行，而是在界面处改变了方向。</p>
    <p>做实验记录入射角与折射角，会发现两组数满足一个简单关系。入射角的正弦与折射角的正弦之比是一个常数，与入射角的大小无关，只由两种介质决定：</p>
    <p style="text-align:center"><Katex tex="\dfrac{\sin\theta_1}{\sin\theta_2}=\dfrac{n_2}{n_1}\quad\Longleftrightarrow\quad n_1\sin\theta_1=n_2\sin\theta_2" display /></p>
    <p>两条光线的偏折方向可以这样记：光线<strong>进入光密介质（折射率较大的一侧）时向法线偏折</strong>，<strong>进入光疏介质时偏离法线</strong>。水中的鱼看起来比实际位置浅，筷子插在水里像是折断了，都是同一个偏折方向的结果。</p>
    <p>公式里的两个角都从<strong>法线</strong>量起，不是从界面量起。这一点在画图与代入数值时最容易出错。另外，反射与折射同时存在，折射定律并不排斥反射：入射光的能量按一定比例分给两支，入射角越大，反射的那一份越多。</p>

