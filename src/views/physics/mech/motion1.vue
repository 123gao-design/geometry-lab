    <h3 class="sec" id="m1-ref">参考系与运动的相对性</h3>
    <p>坐在行驶的列车里，把行李放在行李架上，从车厢里看它纹丝不动；站在站台上看，它正随列车一起前进。同一件行李，两处观察者给出的描述不同，而两种描述都对。差别在于各自选来作为标准的物体不同。</p>
    <p>描述一个物体的运动时，选来作为标准的另一个物体叫<strong>参考系</strong>。参考系的选取是任意的，但选取之后，该物体在这一描述里的位置、速度、轨迹都以此为准。同一运动在不同参考系中的描述可以相差很远：车厢里竖直落下的水滴，在站台上看是一条抛物线，在车厢里看是一条竖直的直线。</p>
    <p>选取参考系的原则是便于研究。研究地面上物体的运动，默认取地面为参考系；研究行星绕太阳的运动，取太阳为参考系要简单得多。参考系一旦改变，此前得到的位移、速度等量都要重新计算，不能直接沿用。</p>

    <h3 class="sec" id="m1-point">质点：理想化的模型</h3>
    <p>真实的物体有大小和形状，各部分在同一时刻的运动情况一般并不相同：车轮上各点的速度方向不同，旋转的乒乓球表面各点也在做圆周运动。若把物体的每一个部分都分别描述，问题会变得极为繁琐。</p>
    <p>当物体的大小和形状对所研究的问题影响可以忽略时，可以用一个有质量的点来代替整个物体，这个点叫<strong>质点</strong>。判断能否看作质点，依据不是物体本身的尺寸，而是它相对研究范围的大小，以及研究的目的是什么：</p>
    <ul>
      <li>研究地球绕太阳的公转，地球直径约为公转轨道直径的万分之一，可以看作质点；</li>
      <li>研究地球的自转，同一时刻各处的运动并不相同，不能看作质点；</li>
      <li>研究乒乓球从桌面落下的时间，可以看作质点；研究它的旋转与弧线，不能看作质点。</li>
    </ul>
    <p>质点是一种<strong>理想化模型</strong>：保留与研究相关的性质（质量、位置），舍弃与研究无关的性质（形状、大小、内部结构）。理想化模型是物理学常用的方法，后面的点电荷、理想气体、光滑面都属同类。模型是否合用，要看它能否给出与实验相符的结论。</p>

    <h3 class="sec" id="m1-time">时刻与时间间隔</h3>
    <p>时间轴上的一点表示<strong>时刻</strong>，例如「第 3 s 末」「t = 5 s」；时间轴上的一段表示<strong>时间间隔</strong>，简称时间，例如「前 3 s 内」「第 3 s 内」。两个时刻之差就是它们之间的时间间隔：</p>
    <p style="text-align:center"><Katex tex="\Delta t=t_2-t_1." display /></p>
    <p>「第 3 s 末」与「第 4 s 初」指的是同一个时刻，两条表述之间没有时间流逝。「前 3 s 内」是从 0 到 3 s 的间隔，长为 3 s；「第 3 s 内」是从 2 s 到 3 s 的间隔，长为 1 s。读题时把这两个说法分清，是列式不出错的前提。</p>

    <h3 class="sec" id="m1-disp">位移与路程</h3>
    <p>在一维情形下，取一条坐标轴，物体所在位置的坐标记为 <Katex tex="x" />。物体从位置 <Katex tex="x_1" /> 运动到 <Katex tex="x_2" />，位置的变化量是</p>
    <p style="text-align:center"><Katex tex="\Delta x=x_2-x_1." display /></p>
    <p><Katex tex="\Delta x" /> 称为<strong>位移</strong>。它的绝对值 <Katex tex="|\Delta x|" /> 是初末两点间的直线距离，符号表示方向：正值沿坐标轴正方向，负值沿负方向。一般的三维情形中，位移是从初位置指向末位置的有向线段，大小是两点间的直线距离。</p>
    <p><strong>路程</strong>是物体运动轨迹的长度，用 <Katex tex="s" /> 表示。路程只累加，不分方向，是标量。两者的差别在物体折返时最清楚：物体向右走 3 m 再原路返回 3 m，位移为零，路程是 6 m。下面的演示把这一过程在数轴与 x-t 图上同时画出来。</p>

    <PhysicsDemo :def="DEMO" />
    <p class="cap">图 力1 · <b>位移与路程</b>：物体以速率 <Katex tex="v" /> 向右走 <Katex tex="T" /> 秒，再以相同速率返回。上排数轴上的绿箭头始终从出发点指向当前所在位置，它的长度是位移的大小；下排 x-t 图给出位置随时间的变化，折返处图线出现尖点。看点：把「折返时刻 T」缩短，物体更早掉头；t 超过 <Katex tex="2T" /> 以后，读数栏里的路程停在 <Katex tex="2vT" />，位移回到零。</p>

    <p>由定义可以写出两者的关系。位移的大小不会超过路程：</p>
    <p style="text-align:center"><Katex tex="|\Delta x|\le s," display /></p>
    <p>等号成立的充要条件是物体做<strong>单向直线运动</strong>，中途没有掉头。任何一次折返都会让路程多出两倍于折返处到终点的距离，而位移不变。反过来，<Katex tex="\Delta x=0" /> 也不说明物体没动，只说明它回到了出发位置。</p>

    <h3 class="sec" id="m1-vec">矢量的正负号</h3>
    <p>既有大小又有方向的量叫<strong>矢量</strong>，位移、速度、加速度、力都是矢量；只有大小没有方向的量叫<strong>标量</strong>，路程、时间、质量、温度都是标量。</p>
    <p>一维问题中，矢量的方向可以借坐标轴的正方向来表示：先规定正方向，与正方向同向的矢量取正号，反向的取负号。位移写成 <Katex tex="-4\ \text{m}" />，意思是大小为 4 m、方向沿坐标轴负方向，读作「沿负方向的 4 米」，而不是「负四米」。矢量的绝对值才是它的大小。</p>
    <p>同为矢量才能相加减，运算结果仍是矢量。标量照常按代数法则相加。把矢量的符号当成普通正负数直接运算，往往在正负相消处出错——<Katex tex="\Delta x" /> 的符号本身已经含了方向信息，不能再对大小取绝对值之后再定方向。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把位移的大小当成路程。</strong>两者只在单向直线运动时相等。出现折返、绕行或有曲线的路径，一律先用轨迹长度求路程，再用初末位置求位移。</li>
        <li><strong>提示二：一维位移的负号当作「负的距离」。</strong>负号只说明方向。求大小要取绝对值，问「走了多远」要答路程。</li>
        <li><strong>提示三：按物体大小判断能否看作质点。</strong>能否简化的依据是研究目的与相对尺度。地球很大却能在公转中看作质点，乒乓球很小却在旋转问题中不能。</li>
        <li><strong>提示四：换了参考系仍沿用原来的位移与速度。</strong>参考系变了，初末位置、轨迹、速度都跟着变，必须重算。同一次运动在不同参考系中的位移一般不同。</li>
      </ul>
    </div>
    <p>回收与预告：位移定下来之后，用位移与时间之比就能衡量运动的快慢，这就是下一章的<strong>平均速度</strong>；把时间间隔取得越来越短，得到的是<strong>瞬时速度</strong>，它的变化快慢又引出加速度。</p>
