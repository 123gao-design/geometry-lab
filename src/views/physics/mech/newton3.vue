    <h3 class="sec" id="n3-vs">与一对平衡力的区别</h3>
    <p>作用力与反作用力大小相等、方向相反，一对平衡力也是这样。两者的差别不在大小方向，而在作用对象与依存关系，列表对照最清楚。</p>
    <ul>
      <li>作用力与反作用力分别作用在<strong>两个</strong>物体上，一对平衡力作用在<strong>同一个</strong>物体上。</li>
      <li>前者不能求合力，谈不上抵消；后者作用在同一物体上，合力为零，物体保持平衡。</li>
      <li>前者性质必然相同，后者可以是不同性质的力，例如重力与地面的支持力。</li>
      <li>前者同时产生、同时消失，互为前提；后者撤去其中一个，另一个可以仍然存在，只是物体不再平衡。</li>
    </ul>
    <p>判断一对力属于哪一种，只看两条：是不是作用在两个物体上，能不能同时消失。前者是，就是作用力与反作用力。</p>

    <h3 class="sec" id="n3-fbd">受力分析的顺序</h3>
    <p>用牛顿定律解题，第一步都是把研究对象受到哪些力弄清楚。做法是把研究对象从周围环境中「隔离」出来，按固定顺序逐个寻找，既不遗漏，也不多画。</p>
    <p><strong>一、找重力。</strong>只要在地球表面附近，研究对象就受重力，大小 <Katex tex="mg" />，方向竖直向下。</p>
    <p><strong>二、找接触力中的弹力。</strong>看研究对象与哪些物体接触、是否被挤压。支持力垂直于接触面，绳的拉力沿绳指向绳收缩的方向。</p>
    <p><strong>三、找摩擦力。</strong>有接触、有挤压、接触面粗糙，且有相对运动或相对运动趋势时才有摩擦。滑动摩擦沿接触面，方向与相对运动方向相反；静摩擦由平衡条件确定。</p>
    <p><strong>四、找其他力。</strong>电场力、磁场力、浮力等，按题目情境补上。</p>
    <p>画完再检查一遍：每个力都能说出施力物体，找不到施力物体的力不存在；研究对象施给别人的力不要画进来。这两条能挡掉绝大多数错误。</p>
    <p>几个物体连在一起运动时，常用<strong>整体法</strong>与<strong>隔离法</strong>交替着用。先取整体，内力不必考虑，直接求出共同的加速度；再取其中一个物体，把内力暴露出来求解。下一章的连接体问题就按这个思路处理。</p>

