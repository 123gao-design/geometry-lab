    <h3 class="sec" id="n3-pair">作用力与反作用力</h3>
    <p>用手压桌面，手掌感到桌面向上的顶力；用力推墙，人会向后退。这类现象说明，一个物体对另一个物体施力时，另一个物体也在对它施力，力的作用从来不是单方面的。</p>
    <p>两个挤在一起的物块也是这样。A 推 B 向右，B 就推 A 向左；把 B 换成弹簧、换成磁铁，作用的方向变了，但成对出现这一点不变。地球吸引苹果，苹果也吸引地球，两个力大小相等。这一点与直觉不符，只因为地球质量太大，同样的力在它那里产生的加速度小到无法察觉。</p>

    <h3 class="sec" id="n3-law">牛顿第三定律</h3>
    <p>定律的内容是：<strong>两个物体之间的作用力和反作用力总是大小相等、方向相反、作用在同一条直线上。</strong>写成矢量式是</p>
    <p style="text-align:center"><Katex tex="\vec F_{AB}=-\vec F_{BA}." display /></p>
    <p>这一对力有几点要紧的性质。</p>
    <p><strong>等大反向。</strong>不论两个物体质量是否相同、运动状态如何，两力大小相等、方向相反，且沿同一条直线。质量大的物体受力并不更小，只是加速度更小。</p>
    <p><strong>同时产生、同时变化、同时消失。</strong>两力互为存在的前提，没有先后之分。撤去推力，两个接触力一起消失。</p>
    <p><strong>同种性质。</strong>两力由同一种相互作用产生：都是弹力，都是摩擦力，或都是万有引力。</p>
    <p><strong>分别作用在两个物体上。</strong>这是最要紧的一条。正因为不在同一个物体上，它们不会抵消。A 受到推力与 B 对它的力，合力不为零，A 才加速；B 只受 A 对它的力，合力就是这个力，B 也加速。</p>

