    <h3 class="sec" id="m2-system">系统、内力与外力</h3>
    <p>上一章研究的是单个物体。可现实中的问题常常不止一个物体：两辆小车相撞、子弹打进木块、人从船上跳下、两块磁铁互相吸引——这些过程里，物体之间互相施力，单看其中一个就要处理那个不断变化的相互作用力，很难算。换一个思路，把<strong>互相作用的几个物体一起</strong>取作研究对象，这些相互作用力就成了「内部的力」，问题反而变简单。</p>
    <p>把由两个或更多物体组成的整体叫<strong>系统</strong>。系统内部各物体之间的相互作用力叫<strong>内力</strong>，系统以外的物体对系统内的物体的力叫<strong>外力</strong>。这个划分只对选定的系统有意义：同样是地面对车的支持力，把车单独取作系统时它是外力，把车和地面一起取作系统时就变成了内力。所以解题第一步永远是选定系统与过程，内外力的身份随之而定。</p>
    <p>内力的关键性质来自牛顿第三定律。两物体 A、B 相互作用，A 对 B 的力与 B 对 A 的力等大反向，而且作用时间完全相同——无论是短暂的碰撞还是持续的挤压，这两个力总是同时出现、同时消失。于是两个力的冲量等大反向，加起来是零：</p>
    <p style="text-align:center"><Katex tex="I_{\text{A}\to\text{B}}+I_{\text{B}\to\text{A}}=\mathbf{0}." display /></p>
    <p>这是一条矢量式，逐个方向都成立。它的意思是：<strong>内力只能把动量从一个物体搬到另一个物体，搬来搬去总量不变</strong>。A 的动量多了多少，B 的动量就少了多少。系统总动量定义为各物体动量的矢量和</p>
    <p style="text-align:center"><Katex tex="\mathbf{P}=\mathbf{p}_1+\mathbf{p}_2+\cdots," display /></p>
    <p>内力动不了它，能动的只有外力的冲量，这就是 <Katex tex="I_{\text{外合}}=\Delta\mathbf{P}" />——把上一章的动量定理从单个物体推广到系统，右边换成系统的总动量。</p>

    <h3 class="sec" id="m2-law">动量守恒定律</h3>
    <p>由此立刻得到这一章的主结论。若系统在某一过程中所受合外力为零，外力的总冲量就为零，于是 <Katex tex="\Delta\mathbf{P}=\mathbf{0}" />，总动量在整个过程中保持不变：</p>
    <p style="text-align:center"><Katex tex="\mathbf{p}_1+\mathbf{p}_2=\mathbf{p}_1'+\mathbf{p}_2'," display /></p>
    <p>写成分量形式，在一直线上的问题里就是带符号的代数和：</p>
    <p style="text-align:center"><Katex tex="m_1v_1+m_2v_2=m_1v_1'+m_2v_2'." display /></p>
    <p>这条式子叫<strong>动量守恒定律</strong>。它的推导只有两步可供核对：两物体之间的力等大反向（牛顿第三定律），作用时间相同，所以两者受到的冲量等大反向；由动量定理，两者的动量变化也等大反向，一个增加多少另一个就减少多少，总和不动。推导中没有用到力的具体形式，也不要求过程是直线运动——斜碰、曲线、力随时间剧烈变化都适用，只要合外力为零。</p>
    <p>「合外力为零」在实际题目里有几种常见情形，都要能对号：一是系统根本不受外力，例如太空中两块碎片的碰撞；二是受了外力但<strong>矢量和为零</strong>，例如光滑水平面上两车相撞，重力和支持力各自竖直、正好抵消；三是过程极短、<strong>内力远大于外力</strong>，例如爆炸、子弹穿木块，重力虽然存在，但在这几毫秒里它的冲量比内力的小很多，可以略去，这也属于可用的情形；四是合外力在某一个方向上为零，那么<strong>只有那个方向的动量守恒</strong>，其余方向照旧用牛顿定律或动量定理处理。光滑水平面上斜着相碰的两球就是这种：竖直方向有重力和支持力，水平方向两个分量各自守恒。</p>
    <p>动量守恒定律的地位比牛顿定律还高一层。牛顿定律在高速与微观情形下要修正，动量守恒却一直成立——它其实是空间平移对称性的直接结果，物理规律在空间各处相同，总量就有守恒量与之对应。所以它既能用在牛顿力学里，也能用在相对论与量子力学里。高中阶段把它当成一条独立的定律使用，不必每次都从牛顿第三定律重新推。</p>

    <h3 class="sec" id="m2-collide">碰撞的类型</h3>
    <p>碰撞是动量守恒最典型的用场。两球相碰，作用时间极短，内力远大于外力，动量守恒；但动能不一定守恒——碰撞过程中两球会形变、发热、发声，一部分动能变成了内能。按动能损失多少，碰撞分三类。</p>
    <p><strong>弹性碰撞</strong>：形变完全恢复，没有动能损失，动量与动能都守恒。一维正碰的两条式子联立</p>
    <p style="text-align:center"><Katex tex="m_1v_1+m_2v_2=m_1v_1'+m_2v_2',\qquad \tfrac12m_1v_1^2+\tfrac12m_2v_2^2=\tfrac12m_1v_1'^2+\tfrac12m_2v_2'^2," display /></p>
    <p>解出碰后速度</p>
    <p style="text-align:center"><Katex tex="v_1'=\frac{(m_1-m_2)v_1+2m_2v_2}{m_1+m_2},\qquad v_2'=\frac{(m_2-m_1)v_2+2m_1v_1}{m_1+m_2}." display /></p>
    <p>三个特例值得记住。一是<strong>质量相等</strong>时 <Katex tex="v_1'=v_2,\ v_2'=v_1" />，两球交换速度：台球正碰后，原来动的停下、原来静的走起来。二是<strong>小撞大</strong>（<Katex tex="m_1\ll m_2" />，且 <Katex tex="v_2=0" />）得 <Katex tex="v_1'\approx -v_1" />，小球原速弹回，像是撞上了一堵墙。三是<strong>大撞小</strong>（<Katex tex="m_1\gg m_2" />）得 <Katex tex="v_1'\approx v_1" />、<Katex tex="v_2'\approx 2v_1" />，重球几乎不受影响，轻球被弹出两倍速。还有一个常用的等价写法：弹性正碰中<strong>碰前接近速度等于碰后分离速度</strong>，即 <Katex tex="v_1-v_2=v_2'-v_1'" />；用它配上动量守恒，比联立两个二次式解起来快得多。</p>
    <p><strong>完全非弹性碰撞</strong>：碰后两物体粘在一起、以同一速度运动，形变完全不能恢复，动能损失最大。由动量守恒直接得共同速度</p>
    <p style="text-align:center"><Katex tex="v=\frac{m_1v_1+m_2v_2}{m_1+m_2}," display /></p>
    <p>损失的动能是碰前动能减去碰后动能。取 <Katex tex="v_2=0" /> 为例，可算出</p>
    <p style="text-align:center"><Katex tex="\Delta E_k=\tfrac12m_1v_1^2-\tfrac12(m_1+m_2)v^2=\frac{m_1m_2}{2(m_1+m_2)}v_1^2." display /></p>
    <p>注意这已经是在动量守恒前提下能损失的最大值，任何碰撞的动能损失都不会超过它。若两物体质量相等，损失正好是碰前动能的一半。</p>
    <p><strong>一般碰撞</strong>介于两者之间：形变部分恢复，碰后有相对速度但比碰前小，动能损失一部分。用<strong>恢复系数</strong>刻画：</p>
    <p style="text-align:center"><Katex tex="e=\frac{v_2'-v_1'}{v_1-v_2}," display /></p>
    <p>它等于碰后分离速度与碰前接近速度之比。弹性碰撞 <Katex tex="e=1" />，完全非弹性碰撞 <Katex tex="e=0" />（碰后不再分离），一般碰撞 <Katex tex="0<e<1" />。配动量守恒可解出任意 <Katex tex="e" /> 下的碰后速度，损失的动能则统一写成</p>
    <p style="text-align:center"><Katex tex="\Delta E_k=(1-e^2)\cdot\frac{m_1m_2}{2(m_1+m_2)}(v_1-v_2)^2." display /></p>
    <p>这条式子在演示里可以逐档核对：把 <Katex tex="e" /> 从 1 拖到 0，最下面两根动能条的差值一点点变大，到 0 时最大；而绿色的总动量线自始至终不动。</p>
    <p>下面那块板把三种碰撞放在同一条光滑轨道上：上方两辆小车相碰，下方是一根动量轴，「碰前」「碰后」两行各自画出 A、B 的动量与两者的总和。</p>

