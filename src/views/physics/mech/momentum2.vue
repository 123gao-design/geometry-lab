    <h3 class="sec" id="m2-use">应用与解题</h3>
    <p><strong>解题的四步。</strong>一是选定系统与过程，明确哪些物体属于系统、过程从哪一时刻到哪一时刻；二是判断守恒条件——合外力是否为零，或者某一方向上是否为零，写清理由（光滑面、水平方向无外力、碰撞时间极短等）；三是规定正方向，此后所有速度都带符号写（向左的、反弹的都要写成负值）；四是列动量守恒式，若题目还问动能或能量，再补一条能量关系，最后检验结果是否合理。</p>
    <p><strong>反冲与爆炸。</strong>系统原来的总动量为零（或某一定值），内部作用后各部分分开，则各部分的动量矢量和仍等于原值。<strong>反冲</strong>就是初动量为零的情形：人从静止的船上跳下，人与船的动量等大反向，<Katex tex="m_1v_1=m_2v_2" />（1 指人、2 指船），质量大的船速度小；火箭喷出气体的动量向下，箭体动量向上。<strong>爆炸</strong>与反冲的式子相同，但动能<strong>增加</strong>了——化学能变成了动能，所以爆炸不能用动能守恒，只能用动量守恒。这类题的共同点是把「原来一体的东西」在某一时刻分成两半，分别写出动量再令其和等于初值。</p>
    <p><strong>碰撞的合理性检验。</strong>算出碰后速度后要回头看一眼。一是<strong>不能穿透</strong>：碰后后面那个物体的速度不能超过前面那个，否则两物体就穿过去了；二是<strong>动能不增</strong>：碰后动能不能大于碰前动能，否则凭空生出了能量。这两条一查，很多符号写错、方程列错的情形立刻暴露出来。用恢复系数判断等价于第一条，<Katex tex="0\le e\le 1" />。</p>
    <p>回到上面那块板，两块小车在光滑轨道上相碰，碰前的初速度、两车质量、恢复系数都能拖。动量轴上「碰前」「碰后」两行分别画出 A、B 的动量：碰后两个点都挪了位置，方向可能反转、大小可能改变，但绿色虚线标出的总动量 <Katex tex="P" /> 一直在原处——这一条线是整段动画里唯一不动的量。把档位切到「弹性碰撞」，最下面的动能条长度不变，损失为零；切到「完全非弹性碰撞」，两车碰后并在一起同速前进，动能条缩到最短，粉色字标出损失的那一部分。改质量比，两点的位置一起变，而总动量线只随初速度与质量之和改变，与恢复系数毫无关系——这正是「碰撞方式不影响总动量」的直接体现。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把动量当成标量，只算大小。</strong>动量是矢量，动量守恒是矢量式。规定正方向后，向左的、反弹的速度都要写成负值；两物体垂直方向运动时，要按两个方向分别列分量式，再各自守恒，不能把大小直接相加。</li>
        <li><strong>提示二：系统选得不对，或漏看外力。</strong>动量守恒的前提是合外力为零，而外力是相对系统说的。两车在粗糙面上相碰，摩擦力是外力，动量不守恒；只有竖直方向的重力和支持力抵消、水平方向光滑时才能用。碰撞极短时重力可以忽略，但要说明理由，且这一条只管过程那一瞬，不管碰前碰后的滑行。</li>
        <li><strong>提示三：混淆弹性碰撞与完全非弹性碰撞的条件。</strong>弹性碰撞同时用动量守恒与<strong>动能守恒</strong>两条；完全非弹性碰撞碰后同速，只用动量守恒，动能<strong>一定减少</strong>，减少量固定为 <Katex tex="m_1m_2v^2/[2(m_1+m_2)]" />。切勿在完全非弹性碰撞里也写动能守恒——那两条式子联立会解出与同速相矛盾的结果。</li>
        <li><strong>提示四：算出结果不做合理性检验。</strong>碰后后面的物体速度不能超过前面的（否则穿透），碰后总动能不能大于碰前（否则凭空生能）。这两条一查，符号写错、方向搞反的情形大多当场显现。若解出 <Katex tex="e>1" /> 或动能增加，一定是式子或符号出了问题。</li>
      </ul>
