    <h3 class="sec" id="g3-maneuver">变轨与发射</h3>
    <p>卫星在轨道上运行时，引力与所需向心力正好匹配。若在 <Katex tex="P" /> 点短暂点火加速，速度变大，所需向心力 <Katex tex="mv^2/r" /> 随之变大，而该处的引力没变，出现「供不应求」，卫星便开始做离心运动，轨道由圆变成椭圆，<Katex tex="P" /> 成为近地点，远地点则被抬到更高处。到了远地点再点一次火，把速度提到该高度圆轨道所需的值，椭圆就变成一个大圆。</p>
    <p>反方向的调整同样成立：减速则向心，轨道缩向低处。整个过程可以概括成一句话：<strong>加速升轨、减速降轨</strong>，两次点火都发生在两条轨道的切点处。</p>
    <p>有一个容易反直觉的细节。卫星升到高轨道之后，速度反而比原来小了——半径变大，<Katex tex="v=\sqrt{GM/r}" /> 就变小。所以「加速」只在点火的瞬间发生，之后的稳态速度是降下来的。若把「变轨后速度变大」与「点火时加速」混在一起，就会得出与 <Katex tex="v=\sqrt{GM/r}" /> 相反的错误结论。</p>
    <p>真实发射因此分成三段：先用火箭把卫星送进一条近地圆轨道（约 200 km，速度接近 7.9 km/s），在适当位置点火进入<strong>转移轨道</strong>（一条远地点正好落在目标高度的椭圆），到达远地点时再点火圆化。同步卫星、月球探测器、火星探测器都走这套流程，只是目标高度不同。演示里看不出这个过程——它画的是稳态圆轨道——但把半径从 2R 拖到 6.6R，读数栏里速度与周期的变化方向，就是变轨前后两端各自的状态。</p>

