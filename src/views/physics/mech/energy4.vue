    <h3 class="sec" id="e4-other">其他力做功与机械能的变化</h3>
    <p>上一章从动能定理出发，把重力做的功换成势能的减少量，得到了机械能守恒。这一步其实没有限定「只有重力做功」，而是可以走得更远一些。仍然从动能定理开始：</p>
    <p style="text-align:center"><Katex tex="W_G+W_{\text{弹}}+W_{\text{其他}}=E_{k2}-E_{k1}." display /></p>
    <p>把 <Katex tex="W_G=-(E_{p2}-E_{p1})" /> 代入并移项，就得到</p>
    <p style="text-align:center"><Katex tex="W_{\text{其他}}=(E_{k2}+E_{p2})-(E_{k1}+E_{p1})=E_2-E_1." display /></p>
    <p>这条式子叫<strong>功能关系</strong>：其他力做的功等于机械能的变化量。当 <Katex tex="W_{\text{其他}}=0" /> 时它退化成机械能守恒律——上一章正是它的特例。这条式子的适用范围比守恒律宽得多，任何过程都成立，因此判断不清是否守恒时，先写它总不会错。</p>
    <p>把常见的力与对应的能量变化列在一起，会看得更清楚。合外力做的功等于动能的变化；重力做的功等于重力势能的减少；弹力做的功等于弹性势能的减少；除重力和弹力外的其他力做的功等于机械能的变化；滑动摩擦力做的功，其绝对值等于转化为内能的那一部分。这些关系合起来就是一张能量转化的对照表，解题时按「哪个力做功、对应哪种能量变」去落笔，比死记公式可靠。</p>
    <p>要注意一个符号上的陷阱：<Katex tex="W_{\text{其他}}" /> 为负时机械能减少，为负得越多减少得越多。物块在粗糙面上滑行，摩擦力做负功，机械能一路减少，减少的正是它转化出去的内能——演示里那根堆叠条把这个过程画得最直白：绿色一段不断缩短，粉色一段等量地补上来，两段加起来的高度始终不变。</p>

    <h3 class="sec" id="e4-heat">摩擦生热与相对位移</h3>
    <p>摩擦生热有一个专门的算法，它最容易出错的地方是「用哪一个位移」。</p>
    <p>单个物体在固定粗糙面上滑行时，摩擦力的大小为 <Katex tex="f=\mu mg" />，方向始终与运动方向相反，做的功是 <Katex tex="W_f=-f\,s" />。这部分功转化为内能，生热 <Katex tex="Q=f\,s" />，其中 <Katex tex="s" /> 是物体相对地面走过的路程。此时「对地位移」与「相对位移」恰好相等，两种说法分不出差别。</p>
    <p>一旦两个物体都在动，两者就分开了。设木板放在光滑地面上，物块以初速滑上木板，木板被摩擦带着一起向前。对物块，摩擦力做负功 <Katex tex="-f\,s_1" />；对木板，摩擦力做正功 <Katex tex="f\,s_2" />。两者相加是 <Katex tex="-f(s_1-s_2)=-f\,s_{\text{相对}}" />，并不是零——这一部分正是转化为内能的能量。所以<strong>摩擦生热的公式是</strong></p>
    <p style="text-align:center"><Katex tex="Q=f\,s_{\text{相对}}," display /></p>
    <p>其中 <Katex tex="s_{\text{相对}}" /> 是两个接触面之间相对滑过的路程。物块与木板最终同速时，用动能定理分别对两者写式再相加，就能验证：两个物体的动能减少量之和，恰好等于 <Katex tex="f" /> 乘相对位移。相对位移为零（两者不打滑）时，摩擦不生热，这时的静摩擦只负责在两者之间转移能量，不做净功。</p>
    <p>还要留心往返的情形。物体滑出去又滑回来，对地位移为零，而摩擦力每一段都在做负功，生热要按路程累加。位移与路程的区别，在功与热这两处都会咬人。</p>
