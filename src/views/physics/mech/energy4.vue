    <h3 class="sec" id="e4-law">能量守恒定律</h3>
    <p>把各种形式的能量都数进来，就得到一条比机械能守恒更普遍的定律：</p>
    <p style="text-align:center"><Katex tex="E_{\text{初}}=E_{\text{末}}," display /></p>
    <p><strong>能量既不会凭空产生，也不会凭空消失，它只会从一种形式转化为另一种形式，或者从一个物体转移到另一个物体，而能的总量保持不变。</strong>这就是能量守恒定律。它不限定具体的力，也不限定能量的形式——机械能、内能、电能、化学能、核能都算在内，只要求把系统划全、把每一种形式都数到。</p>
    <p>机械能守恒是它在「只有重力与弹力做功」这一情形下的简化；摩擦生热是它在「机械能转化为内能」这一方向的体现；带电粒子在电场中加速、电流通过电阻发热、燃料燃烧推动活塞，都是同一条定律在不同场合的写法。物理学上把能量守恒当作最基本的原理之一，凡是一个过程算出来「能量不守恒」，问题一定出在系统没有划全，或者漏算了某种形式的能量。</p>
    <p>使用它时有两件事必须先交代清楚。一是<strong>系统边界</strong>：哪些物体算在内。系统内的能量可以互相转化，跨越边界的部分要作为「外界对系统做功」或「系统向外传热」单独计入。二是<strong>能量的初末状态清单</strong>：初态有哪些形式的能量、各多少，末态又有哪些，一项都不能漏。</p>

    <h3 class="sec" id="e4-use">应用与辨析</h3>
    <p><strong>三种工具怎么选。</strong>题目只要求速度或高度、且过程中只有重力与弹力做功，用机械能守恒，最快；过程中有其他力做功、又要求速度或位移，用动能定理（写全所有力的功，含正负号），最稳；涉及内能、电能、化学能等多种形式的转换，或要问「产生了多少热量」，用能量守恒把各种形式的能量列全。三者可以互相验证：同一道题用两条路算，结果应当一致。</p>
    <p><strong>一个完整的例子。</strong>质量 <Katex tex="m" /> 的物块以初速 <Katex tex="v_0" /> 滑上粗糙水平面，动摩擦因数 <Katex tex="\mu" />，直到停下。用动能定理写：<Katex tex="-\mu mg\,s=0-\tfrac12mv_0^2" />，得滑行距离 <Katex tex="s=v_0^2/(2\mu g)" />。同一过程用功能关系写：其他力（摩擦力）做的功 <Katex tex="-\mu mg\,s" /> 等于机械能的变化 <Katex tex="0-\tfrac12mv_0^2" />，得到同一式子。再用能量守恒写：初态只有动能 <Katex tex="\tfrac12mv_0^2" />，末态只有内能 <Katex tex="Q=\mu mg\,s" />，两者相等，仍是同一条式子。三种写法指向同一件事，这正是功能关系与能量守恒的价值——它们是同一个规律在三种口径下的呈现。</p>
    <p><strong>解题的四步。</strong>一是选系统与过程，明确初、末两个状态；二是列清初末各有哪些能量（动能、重力势能、弹性势能、内能……），缺哪一项都会对不上；三是找出过程中有哪些力做功、哪些能量在转化，把「做功」与「能量变化」一一对应起来；四是列式求解，回头看单位、符号与数量级是否合理。</p>
    <p>演示里那根堆叠条，就是这条规律最直观的图形版本。物块以初速滑上粗糙面，水平方向上唯一的力是摩擦力，它做负功，机械能（此处只有动能）持续减少；减少的那一部分并没有消失，而是变成了内能，粉色一段等量地长起来。两段的高度之和被青色横线卡死——不论把质量、初速、粗糙程度拖成什么样，物块停下时粉色恰好填满整根，绿色归零，总量一分不差。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把重力与弹力也算进「其他力」。</strong>功能关系里的其他力<strong>不含</strong>重力与弹力，因为它们做的功已经记在重力势能与弹性势能的增减上。若把重力也算进左边，就等于把同一份功数了两遍，等式必然失衡。</li>
        <li><strong>提示二：算摩擦生热时用对地位移。</strong>只有单个物体在固定面上滑动时两者才相等。有了相对滑动（物块在运动的木板上滑、传送带上滑），生热必须用相对路程 <Katex tex="s_{\text{相对}}" />；用对地位移会把热量算错，且往往算小。</li>
        <li><strong>提示三：认为「机械能减少」就是「能量消失」。</strong>机械能减少意味着能量转化成了别的形式（内能、电能等），总能量仍然守恒。写能量守恒时若只列动能与重力势能，等式自然不成立——不是定律失效，而是能量清单上没有内能这一项。</li>
        <li><strong>提示四：在同一过程里混用两套零势能面之外的口径。</strong>更常见的情形是：前半段用机械能守恒、后半段有摩擦，却仍然照守恒律写式。判断时要<strong>逐段</strong>看该段内做功的力，中途条件变了（比如进入粗糙段、绳子绷紧），表达式也要跟着换。</li>
      </ul>
