    <h3 class="sec" id="p1-curve">曲线运动的速度方向</h3>
    <p>汽车沿弯道行驶，速度表始终指着某个数，说明速率可以不变，但速度在变：车头在转，方向的改变本身就是一种变化。把时间取得足够短，割线变成切线，所以曲线运动在任一点的速度方向沿该点轨迹的切线，指向运动的前方。</p>
    <p>由牛顿第二定律，速度改变的方向就是合力的方向。合力的方向与速度方向不在同一条直线上，物体才做曲线运动；两者在同一直线上时，物体做直线运动（同向加速、反向减速）。这个判据的用处在于：只要知道合力朝哪边，就知道轨迹向哪边弯——轨迹总是向合力所指的一侧弯曲，且弯曲越急，说明垂直于速度的那部分力越大。</p>
    <p>沿切线方向的分力只改变速率，沿法线方向的分力只改变方向。一端固定的绳子拴着小球做圆周运动，绳的拉力整个垂直于速度，所以速率不变，方向时刻在改。</p>

    <h3 class="sec" id="p1-decomp">合运动与分运动</h3>
    <p>物体同时参与了几种独立的运动，实际表现出来的那个运动叫<strong>合运动</strong>，其中每一种叫<strong>分运动</strong>。两者之间有三条性质：</p>
    <p><strong>等效性</strong>——几个分运动合起来的效果，与实际运动完全相同，可以用分运动代替合运动，也可以用合运动代替分运动。平抛的小球，等价于「水平方向匀速前进的小球」与「竖直方向自由下落的小球」同时进行。</p>
    <p><strong>同时性</strong>——分运动与合运动发生在同一段时间内，合运动的位移、速度、加速度，是同一时刻各分运动的位移、速度、加速度的合成。不存在哪个分运动先开始、哪个先结束。</p>
    <p><strong>独立性</strong>——一个方向上的分运动，按照该方向上的受力与初速度单独发展，不受另一个方向上运动的影响。把小球水平抛出，竖直方向的落体照旧按 <Katex tex="h=\tfrac12gt^2" /> 下落，水平方向的匀速前进照旧进行，两者互不牵扯。</p>
    <p>独立性这一条是分运动的价值所在：它允许我们在一件事上只问一个方向，把复杂的三维问题拆成两个一维问题分别求解，最后再合起来。</p>

    <h3 class="sec" id="p1-rule">平行四边形定则</h3>
    <p>位移、速度、加速度都是矢量，合成时不能直接相加，要按<strong>平行四边形定则</strong>：以两分矢量为邻边作平行四边形，从共同起点出发的对角线就是合矢量。两个分速度 <Katex tex="v_1" />、<Katex tex="v_2" /> 互成 <Katex tex="\theta" /> 角时，合速度的大小为</p>
    <p style="text-align:center"><Katex tex="v=\sqrt{v_1^2+v_2^2+2v_1v_2\cos\theta}." display /></p>
    <p>三种特殊情形值得记住：两边同向（<Katex tex="\theta=0" />）时 <Katex tex="v=v_1+v_2" />，取最大值；反向时 <Katex tex="v=|v_1-v_2|" />，取最小值；相互垂直时 <Katex tex="v=\sqrt{v_1^2+v_2^2}" />。所以两个分速度的合速度，总落在两者之和与两者之差的绝对值之间。</p>
    <p>分解是合成的逆运算，同一个矢量可以有无穷多种分解方式，取哪一种要看问题的方便：正交分解取互相垂直的两个方向（通常沿速度与垂直速度），斜交分解取与已知方向一致的两条边。小船渡河取的是沿河岸与垂直河岸两个方向。</p>

    <h3 class="sec" id="p1-river">小船渡河</h3>
    <p>设河宽为 <Katex tex="d" />，船在静水中的速度为 <Katex tex="v_\text{船}" />，水流速度为 <Katex tex="v_\text{水}" />，船头与河岸的夹角为 <Katex tex="\theta" />。把船速沿河岸与垂直河岸分解，垂直河岸的分量是 <Katex tex="v_\text{船}\sin\theta" />，沿河岸的分量是 <Katex tex="v_\text{船}\cos\theta" />；水速只沿河岸，不参与垂直方向的运动。于是</p>
    <p style="text-align:center"><Katex tex="t=\frac{d}{v_\text{船}\sin\theta},\qquad x=\left(v_\text{水}+v_\text{船}\cos\theta\right)t." display /></p>
    <p><strong>最短时间</strong>。渡河时间只由垂直河岸的分速度决定，与水速无关。让它最大，即 <Katex tex="\theta=90^\circ" />，船头垂直河岸，</p>
    <p style="text-align:center"><Katex tex="t_{\min}=\frac{d}{v_\text{船}}." display /></p>
    <p>此时船并没有垂直过河，因为水把它冲向下游，实际航线偏向河岸的下游一侧，位移为 <Katex tex="\sqrt{d^2+(v_\text{水}t_{\min})^2}" />。</p>
    <p><strong>最短位移</strong>。想让船沿垂直河岸的直线过河，合速度必须垂直于河岸，这要求船速沿河岸的分量与水流速度恰好抵消：</p>
    <p style="text-align:center"><Katex tex="v_\text{船}\cos\theta=v_\text{水},\qquad \cos\theta=\frac{v_\text{水}}{v_\text{船}}." display /></p>
    <p>这一方案的前提是 <Katex tex="v_\text{水}<v_\text{船}" />——船速不够，抵消不了水流，无论船头指向哪里，合速度都会带一个向下的分量，位移就不可能等于河宽。这时最短位移按下式估算</p>
    <p style="text-align:center"><Katex tex="s_{\min}=d\,\frac{v_\text{水}}{v_\text{船}}\qquad\left(v_\text{水}>v_\text{船}\right)," display /></p>
    <p>对应的船头指向上游，与河岸的夹角满足 <Katex tex="\cos\theta=-\dfrac{v_\text{船}}{v_\text{水}}" />，即船头略偏向河岸的上方（<Katex tex="\theta>90^\circ" />）。两个极值不能同时取到：最短时间要求船头垂直河岸，最短位移要求船头指向上游，选哪一个取决于问题问的是什么。</p>
    <p>两种取法的差别，下面那块板画在同一条河上：橙色箭头是船在静水中的速度，蓝色箭头是水流速度，绿色箭头是两者的合速度，蓝色虚线是不计水流时船该走的航线。</p>

