    <h3 class="sec" id="p1-link">关联速度</h3>
    <p>用绳或杆连接的两个物体，速度并不相同，但沿绳（杆）方向的分速度必须相等，否则绳会被拉长或压短。这一条约束叫<strong>关联速度</strong>。</p>
    <p>人以速度 <Katex tex="v" /> 匀速拉绳，绳跨过定滑轮把船拖向岸边，船的速度沿水面方向。把船的速度沿绳与垂直绳的方向分解，沿绳的分量等于人拉绳的速度：</p>
    <p style="text-align:center"><Katex tex="v_\text{船}\cos\theta=v,\qquad v_\text{船}=\frac{v}{\cos\theta}," display /></p>
    <p>其中 <Katex tex="\theta" /> 是绳与水面（船速方向）的夹角。船越靠近岸边，<Katex tex="\theta" /> 越大、<Katex tex="\cos\theta" /> 越小，<Katex tex="v_\text{船}" /> 越大——这就是拉绳时船越靠岸跑得越快的原因。分解的是船速而不是绳速：绳速沿绳，船速沿水面，两者不在同一个方向上，先各自投影再令投影相等，顺序不能反。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：用速度方向判断受力方向。</strong>曲线运动的速度沿切线，而合力的方向既不沿切线也不沿法线。由速度方向能读出轨迹往哪边弯，进而推出合力大致指向哪一侧，不能反过来把合力当成速度。</li>
        <li><strong>提示二：把独立性理解成互不相关的两件事。</strong>独立指的是分运动各自按自己的规律发展，但两个分运动共享同一段时间，合成时要用同一时刻的分量。分别按各自的时间算完再拼起来，轨迹就错了。</li>
        <li><strong>提示三：小船渡河一律取最短位移。</strong>最短位移要求船速大于水速，且船头指向上游；最短时间要求船头垂直河岸。两者取舍看题问的是时间还是位移，条件不满足时最短位移也达不到河宽。</li>
        <li><strong>提示四：关联速度里分解错对象。</strong>绳的方向与物体的运动方向不同，要把物体的实际速度沿绳和垂直绳分解，再令沿绳的分量相等。直接把绳速当作物体速度，或者把物体速度沿绳方向求分量后当成绳速，都会差一个余弦因子。</li>
      </ul>
