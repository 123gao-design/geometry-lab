    <h3 class="sec" id="c3-cond">离心运动的条件</h3>
    <p>匀速圆周运动的等式 <Katex tex="F_{\text{供}}=\dfrac{mv^2}{r}" /> 常被误读成「物体做圆周运动需要这么大的力，所以就一定有这么大力」。实际上等式只是一个恰好兑现的巧合：供给恰好等于需求。供给是由装置与接触面决定的，有上限；需求随速率增长，没有上限。</p>
    <p>两者相等的情形维持圆周运动；需求超过供给以后，多出来的那部分径向力无人承担，物体便以剩余的径向力做加速度指向圆心的曲线运动，而速率方向上的惯性让它越走越远。定量地说，沿半径向外看，物体的径向加速度为</p>
    <p style="text-align:center"><Katex tex="a_{\text{径}}=\frac{v^2}{r}-\frac{F_{\text{供}}}{m}." display /></p>
    <p>前一项是维持圆周所需，后一项是供给能提供的，两者相减即沿半径向外的加速度。第一项大于第二项时 <Katex tex="a_{\text{径}}>0" />，方向背离圆心，物块与圆心的距离开始增大；半径变大后所需向心力 <Katex tex="m\omega^2r" /> 还要继续变大，供给愈发不足，向外滑动越来越快。</p>
    <p>三种情形的界限很清楚，与力6 至力12 里讨论的「合力决定加速度」是同一条规律，只是这里的合力沿半径方向取。</p>

    <h3 class="sec" id="c3-turn">转盘与转弯的临界值</h3>
    <p><strong>转盘上的物块</strong>。物块随水平圆盘一起转动，径向唯一的力是静摩擦，最大值为 <Katex tex="f_{\max}=\mu mg" />。恰好不打滑时</p>
    <p style="text-align:center"><Katex tex="\mu mg=m\omega_c^2 r\quad\Longrightarrow\quad \omega_c=\sqrt{\frac{\mu g}{r}},\qquad v_c=\omega_c r=\sqrt{\mu g r}." display /></p>
    <p>角速度超过 <Katex tex="\omega_c" /> 后，静摩擦顶不住，物块相对盘面沿半径向外滑出，滑出过程中摩擦力反向成为阻力，物块走出的是向外弯的曲线。注意 <Katex tex="\omega_c" /> 与质量无关——质量大时需求与供给同比例变大，临界值不变。</p>
    <p><strong>汽车在水平路面转弯</strong>。把车看作质点，半径 <Katex tex="R" />，径向的力是路面给轮胎的静摩擦（侧向），于是</p>
    <p style="text-align:center"><Katex tex="\mu mg=\frac{mv_c^2}{R}\quad\Longrightarrow\quad v_c=\sqrt{\mu g R}." display /></p>
    <p>雨雪天 <Katex tex="\mu" /> 变小，限速随之降低，正是这个式子的直接结论。把路面外侧垫高（倾斜弯道）以后，支持力也有了径向分量：不计摩擦时竖直方向 <Katex tex="N\cos\theta=mg" />、径向 <Katex tex="N\sin\theta=\dfrac{mv^2}{R}" />，两者相除得</p>
    <p style="text-align:center"><Katex tex="v=\sqrt{gR\tan\theta}," display /></p>
    <p>有摩擦时临界速度还能再提高，倾角与新限速一起由设计者选定。</p>

