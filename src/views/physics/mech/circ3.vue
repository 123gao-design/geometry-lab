    <h3 class="sec" id="c3-app">应用与危害</h3>
    <p><strong>离心机与脱水筒</strong>。把需要分离的混合物放在转鼓里高速旋转，密度大、需要向心力大的成分得不到足够的径向力，便相对转鼓向内壁方向滑移并被甩到壁上，密度小的成分留在中间，从而实现分离。洗衣机的脱水筒原理相同：水滴与衣物之间的附着力不足，水便从筒壁的小孔飞出。</p>
    <p><strong>砂轮与飞轮的限制</strong>。轮缘上的材料靠自身的内聚力提供向心力，转速过高时内聚力不足以把材料留住，轮缘会碎裂飞出。工程上给砂轮标注最大线速度，飞轮设计校核的也是 <Katex tex="\dfrac{mv^2}{r}" /> 是否在内聚力允许的范围之内。</p>
    <p><strong>弯道限速与翻车</strong>。汽车转弯的临界速度由 <Katex tex="\sqrt{\mu gR}" /> 给出，超速时轮胎侧滑；重心高的货车在半径小的弯道上还有侧翻的危险，那是另一种失效：支持力与摩擦力的合力不再能提供所需的向心力，车身绕外侧轮胎倾覆。铁路的弯道要抬高外轨，道理与此相同。</p>
    <p>应用与防范共用同一个判据：需要的向心力与能提供的径向力之间谁大谁小。设计时需要「供不应求」就把它做足，需要「供过于求」就把它卡住。</p>

    <h3 class="sec" id="c3-frame">惯性系里没有离心力</h3>
    <p>站在地面上分析时，物体的加速度指向圆心，合力指向圆心，受力图上只有摩擦力、重力、支持力这些真实的力，不需要也不允许再加一个向外的「离心力」。离心运动是「径向力不够」的结果，不是「有一个向外的力把物体推出去」的结果——这一点与牛顿第一定律的说法一致：物体本就想沿切线走，是摩擦力把它拉回圆周上，摩擦力不够时才越走越远。</p>
    <p>在转动的圆盘上观察，物块确实像是被某种力向外推。若要在转动参照系里使用牛顿定律，就必须补上一个惯性力 <Katex tex="m\omega^2 r" />，方向背离圆心，称为惯性离心力。它只是转动参照系里的修正项，随参照系的选择而有无；用地面参照系解题时不必引入它。</p>

