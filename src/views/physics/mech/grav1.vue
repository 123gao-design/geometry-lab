    <h3 class="sec" id="g1-orbit">椭圆轨道与两个焦点</h3>
    <p>椭圆的定义是到两个定点距离之和为常数的点的集合。这两个定点叫<strong>焦点</strong>，记作 <Katex tex="F" /> 与 <Katex tex="F'" />，常数的一半就是半长轴 <Katex tex="a" />。椭圆上离中心最远的两个点之间的线段是长轴，长轴的一半就是 <Katex tex="a" />；与长轴垂直的那个半轴叫半短轴 <Katex tex="b" />；中心到焦点的距离叫半焦距 <Katex tex="c" />，三者满足</p>
    <p style="text-align:center"><Katex tex="a^2=b^2+c^2." display /></p>
    <p>椭圆有多扁由<strong>离心率</strong>刻画：</p>
    <p style="text-align:center"><Katex tex="e=\frac{c}{a},\qquad 0\le e<1." display /></p>
    <p><Katex tex="e=0" /> 时两个焦点重合于中心，椭圆退化成圆；<Katex tex="e" /> 越接近 1，椭圆越扁。太阳不在椭圆的中心，而在<strong>其中一个焦点</strong>上——这是轨道定律的实质。由此行星到太阳的距离 <Katex tex="r" /> 在一个周期内不断变化：</p>
    <p style="text-align:center"><Katex tex="r_{\text{近}}=a(1-e),\qquad r_{\text{远}}=a(1+e)." display /></p>
    <p>这两点分别叫近日点与远日点，它们都在长轴上，位于太阳的两侧。</p>
    <p>真实的轨道有多接近圆，可以看离心率：地球 <Katex tex="e\approx0.017" />，把地球轨道当圆处理，距离的误差不到 2%；火星 <Katex tex="e\approx0.093" />；哈雷彗星 <Katex tex="e\approx0.967" />，近日点与远日点相差几十倍。演示里拖「离心率 e」这根滑块，两个焦点的位置与轨道的扁圆程度一起改变，太阳始终压在其中一个焦点上。</p>

    <h3 class="sec" id="g1-area">面积定律与近快远慢</h3>
    <p>面积定律说的是：把行星与太阳的连线当作一把扫帚，扫帚在相等的时间里扫过的面积相等。若把一整个周期 <Katex tex="T" /> 分成 <Katex tex="n" /> 段相等的时间，每一段扫过的面积都是</p>
    <p style="text-align:center"><Katex tex="\frac{\pi ab}{T}\cdot\frac{T}{n}=\frac{\pi ab}{n}," display /></p>
    <p>与时间段的起点无关。演示把轨道切成八块等时间的扇形：八块的形状各不相同，面积却一样大。</p>
    <p>面积相等并不意味着路程相等。扇形面积可以近似写成「半径乘弧长的一半」，近日点一侧半径短，要凑出同样的面积，弧就必须长；远日点一侧半径长，弧就短。于是<strong>近日点附近速率大，远日点附近速率小</strong>。演示里行星身后的绿色拖尾按固定时长取，它在近日点那一侧明显更长，在远日点那一侧缩成一小段。</p>
    <p>把两端的面积各写成一次近似，就得到速率之比。设同一小段时间内在近日点、远日点分别走过 <Katex tex="\Delta s_{\text{近}}" /> 与 <Katex tex="\Delta s_{\text{远}}" />，两块的面积相等：</p>
    <p style="text-align:center"><Katex tex="\frac12 r_{\text{近}}\Delta s_{\text{近}}=\frac12 r_{\text{远}}\Delta s_{\text{远}}
      \quad\Longrightarrow\quad \frac{v_{\text{近}}}{v_{\text{远}}}=\frac{r_{\text{远}}}{r_{\text{近}}}=\frac{1+e}{1-e}." display /></p>
    <p>地球 <Katex tex="e=0.017" /> 时这个比值是 1.035，两端的速率只差百分之三点几；哈雷彗星 <Katex tex="e=0.967" /> 时比值接近 60，近日点冲得极快，远日点几乎停住。</p>
    <p>面积定律在牛顿力学里的对应物是角动量守恒：行星对太阳的角动量 <Katex tex="mvr" /> 在运动过程中保持不变，正是「扫过的面积速率恒定」的另一种写法。高中阶段不必引入角动量，只需记住这条规律的直接结论——同一个行星，离太阳越近走得越快。</p>

    <h3 class="sec" id="g1-third">周期定律</h3>
    <p>第三条规律把轨道的尺寸与公转的快慢连在一起。取半长轴的立方与周期的平方作比，绕同一中心天体运行的所有行星都给出同一个数：</p>
    <p style="text-align:center"><Katex tex="\frac{a^3}{T^2}=k." display /></p>
    <p>单位选取得当时这个数可以写成 1：把 <Katex tex="a" /> 用天文单位（地球轨道的半长轴）、<Katex tex="T" /> 用年，则地球给出 <Katex tex="1^3/1^2=1" />，于是任何一颗行星都应当满足 <Katex tex="T^2=a^3" />。以火星为例，<Katex tex="a=1.524" /> AU，<Katex tex="a^3=3.54" />；周期实测 1.881 年，<Katex tex="T^2=3.54" />。两边对得上，误差来自观测精度。</p>
    <p>规律的方向值得留意：轨道越大，周期越长，而且长得更快。半长轴放大到 4 倍，周期放大到 8 倍；半长轴放大到 100 倍，周期放大到 1000 倍。演示右栏把 <Katex tex="a^3" /> 作横坐标、<Katex tex="T^2" /> 作纵坐标，水星、金星、地球、火星四颗行星都落在同一条过原点的直线上，斜率就是 <Katex tex="k" />。拖动两根滑块，橙色的「当前轨道」始终贴着这条直线移动。</p>
    <p>常量 <Katex tex="k" /> 只与中心天体有关，与行星本身无关。太阳系的 <Katex tex="k" /> 是一个数，绕地球运行的卫星系统是另一个数，绕月球运行的探测器又是第三个数。力21 会把它算出来：<Katex tex="k=GM/4\pi^2" />，<Katex tex="M" /> 是中心天体的质量。</p>

