    <h3 class="sec" id="g1-origin">三条规律的来历</h3>
    <p>第谷在二十年间记录了行星位置的观测数据，精度在当时是空前的。开普勒用这些数据反复试算行星的轨道，先后放弃了正圆与匀速两条延续两千年的假设，最终归纳出上述三条规律。三条规律是<strong>运动学</strong>的描述：它们说明行星怎样运动，没有说明为什么这样运动。</p>
    <p>牛顿的工作补上了这一层。他从椭圆轨道与面积定律出发，反推出行星受到的力必须指向太阳、大小与距离的平方成反比，这就是力20 的万有引力定律；反过来，把这条引力代进运动方程，就能解出椭圆轨道，三条规律都成为它的推论。开普勒定律因此被看作万有引力定律的「实验依据」，而万有引力定律又成为其后三百年天体力学的基础。</p>
    <p>需要留出适用范围。三条规律对太阳系的行星、行星的卫星、双星系统都成立，条件是除中心天体外没有第三个天体起明显作用。多体系统（例如受木星扰动的彗星、三体问题）里，轨道不再是严格的椭圆，需要数值计算；广义相对论还会给出水星近日点的额外进动，那是更精密的效应。</p>

