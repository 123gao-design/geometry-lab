    <h3 class="sec" id="e3-work">重力做功与重力势能</h3>
    <p>先看一件在上一章被搁下的事：重力做的功怎么算。物体质量 <Katex tex="m" />，从高 <Katex tex="h_1" /> 处下落到高 <Katex tex="h_2" /> 处，位移的竖直分量是 <Katex tex="h_1-h_2" />，重力方向向下，两者同向，所以</p>
    <p style="text-align:center"><Katex tex="W_G=mg(h_1-h_2)." display /></p>
    <p>关键在于，不论物体是竖直落下、沿斜面滑下、还是沿一条弯曲的滑梯滑下，只要起点与终点的高度相同，重力做的功就完全一样。路径在水平方向绕了多远都不影响：在水平面上移动时重力与位移垂直，功为零；上升一段再下降到同一高度，上升时做的负功与下降时做的正功正好抵消。<strong>重力做功只由高度差决定，与路径无关</strong>。这样的力叫保守力，摩擦力就不是——绕一圈回到原处，摩擦力做的功是实实在在的负值，收不回来。</p>
    <p>既然功只取决于两个高度，就可以把「下降到某高度能拿到多少功」预先记在高度上。取一个参考高度作零，定义</p>
    <p style="text-align:center"><Katex tex="E_p=mgh," display /></p>
    <p>于是重力做的功等于重力势能的减少量：</p>
    <p style="text-align:center"><Katex tex="W_G=E_{p1}-E_{p2}=-\Delta E_p." display /></p>
    <p>这条式子的意思是：重力做正功时，重力势能减少，减少多少，动能就增加多少（若没有别的力做功）；重力做负功（物体被抬升）时，重力势能增加，增加的来源是别的力做的功。势能这个名字就从此而来——它不是物体含有某种特殊的物质，而是一份与位置绑定、可以转化为动能的能量。</p>

    <h3 class="sec" id="e3-ep">势能与零势能面</h3>
    <p>重力势能属于<strong>物体与地球组成的系统</strong>，不属于物体单独所有。说「物体具有重力势能」是习惯上的简写，严格的说法是「物体与地球这一系统具有重力势能」。这一点在分析系统内部的能量转化时很重要：重力做功，是系统内部的势能与动能之间在转换，不涉及系统与外界交换能量。</p>
    <p>零势能面可以任选。选地面为零、选桌面为零、选任意一条水平线为零都可以，选不同的零势能面，同一个位置的 <Katex tex="E_p" /> 数值不同（可以为负），但两点之间的<strong>差值</strong> <Katex tex="\Delta E_p" /> 不变。守恒定律里出现的一直是 <Katex tex="E_{p1}-E_{p2}" /> 或两边同时含 <Katex tex="E_p" />，零势能面一改，等号两边同时平移同一个量，等式照旧成立。所以<strong>零势能面的选择不影响任何物理结论</strong>，只影响算式里的数字是否好看。习惯上把最低点定为零，让例题里的势能都取正值。</p>
    <p>弹簧的弹性势能是同一路数的量。弹簧从原长被拉伸或压缩 <Katex tex="x" />，弹力做的功与形变的路径无关，可以定义一个</p>
    <p style="text-align:center"><Katex tex="E_p=\tfrac12kx^2," display /></p>
    <p>零点是原长。它与重力势能的形式不同（<Katex tex="x" /> 的平方而不是 <Katex tex="x" /> 的一次方），但地位相同：都是位置（形变）的函数，做的功都等于它的减少量。处理竖直弹簧振子时，重力势能与弹性势能会同时出现，两者都要算进去，漏掉任何一个，机械能就不守恒了。</p>

    <h3 class="sec" id="e3-law">机械能守恒定律</h3>
    <p>把动能定理与重力做功的表达式并排放。设物体只受重力做功（支持力、绳的拉力与位移垂直，做功为零），则总功就是重力做的功：</p>
    <p style="text-align:center"><Katex tex="W_{\text{合}}=W_G=E_{p1}-E_{p2}=E_{k2}-E_{k1}." display /></p>
    <p>移项，把下标相同的项并到一起：</p>
    <p style="text-align:center"><Katex tex="E_{k1}+E_{p1}=E_{k2}+E_{p2}," display /></p>
    <p>这就是<strong>机械能守恒定律</strong>：在只有重力（或弹力）做功的情形下，物体的动能与势能相互转化，机械能的总量保持不变。也可以写成增量形式 <Katex tex="E_{k2}-E_{k1}=-(E_{p2}-E_{p1})" />，即「动能的增加量等于势能的减少量」，两种写法等价。</p>
    <p>推导过程说明了一件事：守恒律不是新的物理原理，它是动能定理在「做功的力只有保守力」这一特殊情形下的化简。也正因为如此，它与动能定理各有各的用场：动能定理对所有力都成立，但要把每一项功都算出来；机械能守恒只在条件满足时成立，可一旦满足，就绕开了全部中间过程——不必算中间任何一点的速度，甚至连重力怎么变（自由落体还是沿圆弧下滑）都不必管。</p>
    <p>演示把这条守恒律摆成了两根条。单摆从初角 <Katex tex="\theta_0" /> 由静止放开，摆球沿圆弧来回摆：越往上越慢、势能条长而动能条短；摆到最低点最快、两根条正好互换。无论摆到哪个位置，两根条的长度之和都被同一条青色横线卡住——这条线在整个摆动过程中纹丝不动。把摆长、质量、初角拖成任何一组数，线的高度会变，但摆动中它不再改变。</p>

