    <p class="cap">图 力24 · <b>机械能守恒</b>：单摆从初角 θ₀ 由静止放开，摆球沿圆弧来回摆。左栏一根摆线吊着摆球 m，虚线弧标出摆动范围，青色虚线是零势能面 <Katex tex="h = 0" />，摆球到参考面的竖直距离标作 <Katex tex="h" />，绿色箭头是此刻的速度、随位置变长变短，橙色弧标出摆角 θ。右栏两根竖条分别是动能 <Katex tex="E_k" /> 与重力势能 <Katex tex="E_p" />，青色虚线是两者之和即机械能 <Katex tex="E" />。看点一：摆球摆到任何位置，两根条的高度加起来都正好顶到那条青色横线——一根变长，另一根就以同样的量变短，两者的交换分毫不差。看点二：摆到最低点时势能条缩到零、动能条顶到横线；摆到最高点时反过来，动能条归零，摆球速度也归零。看点三：把初角 θ₀ 拖大，横线整体抬高一档（初始势能变大），但整段摆动中它依然水平不动；把摆长或质量改掉，横线高度跟着变，摆动同样不动它——参数可以改，摆动中的总数不变，这就是守恒。</p>

    <h3 class="sec" id="e3-use">守恒的判断与应用</h3>
    <p>用这条定律的第一步不是代公式，而是判断它到底成立不成立。判断的依据是<strong>做功的力</strong>，不是受力的多少：物体完全可以在受四个力的情况下机械能守恒，只要其中只有重力与弹力做功。</p>
    <p><strong>三步判断。</strong>一是明确研究对象与过程，划清系统边界（含地球、含弹簧）；二是逐项分析受力并判断每个力做不做功、做正功还是负功；三是看剩下的做功的力是否只有重力与弹力。若还有别的力做了功，机械能就不守恒，但动能定理照旧成立，可以用「其他力做的功等于机械能的变化量」来算——这条留到下一章。</p>
    <p><strong>几种典型的成立与不成立。</strong>自由落体与各种抛体运动只受重力，机械能守恒，这是最干净的情形；光滑斜面与光滑圆弧轨道上的滑动，支持力与运动方向始终垂直、不做功，也守恒；单摆与竖直平面内的圆周运动在无摩擦时守恒。与之相对，物体在粗糙面上滑行（摩擦生热）、绳子突然绷紧把速度「拉齐」（有能量变成内能）、两个物体碰撞并粘在一起、爆炸把化学能转成动能，这些过程机械能都不守恒。但它们不守恒并不等于能量消失了，只是有一部分能量从动能与势能转化成了内能或别的形式。</p>
    <p><strong>解题的四步。</strong>一是选过程，确定初、末状态并选定零势能面（整道题只选一次，中途不能改）；二是判断守恒是否成立；三是写出初、末两个状态各自的机械能（动能用 <Katex tex="\tfrac12mv^2" />，势能用 <Katex tex="mgh" />，弹簧另加 <Katex tex="\tfrac12kx^2" />）；四是令二者相等求解，必要时与运动学或圆周运动的径向方程联立。凡是只要求速度、不求时间与加速度的题，这条路通常最短。</p>
    <p>一个常见的用法是把守恒律写成首末两个状态之间的等式：物体从高 <Katex tex="h" /> 处静止滑下，到最低点（取为零势能面）时 <Katex tex="mgh=\tfrac12mv^2" />，立刻得到 <Katex tex="v=\sqrt{2gh}" />，与轨道形状无关。同一结论用牛顿定律求，得先算出每个位置的法向力、再积分，麻烦得多。演示里的单摆就是这个式子的直接体现：把初角 <Katex tex="\theta_0" /> 拖大，最高点抬高、最低点速率随之变大，读数栏的 <Katex tex="v" /> 恰好等于 <Katex tex="\sqrt{2gL(1-\cos\theta_0)}" />。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把「只有重力做功」当成「只受重力」。</strong>支持力、绳的拉力、斜面的弹力常常存在，只要它们与运动方向垂直、做功为零，机械能照样守恒。反过来，只受重力却不是唯一的反例——物体在粗糙斜面上也可能只受重力、支持力与摩擦力三个力，而摩擦力做了负功，机械能不守恒。判断看的是<strong>做功的力</strong>。</li>
        <li><strong>提示二：零势能面中途换。</strong>初、末两个状态必须用同一个零势能面。写到一半改参考高度，两边的势能平移量不同，等式立刻不成立。一条实用的经验是把它定在过程的最低点，让势能取非负值。</li>
        <li><strong>提示三：漏掉系统里的某一项势能。</strong>含弹簧的过程要把 <Katex tex="\tfrac12kx^2" /> 一并写进机械能；两个物体用绳连接时，要写两边的动能。机械能是「整个系统」的量，只算其中一部分，等式两边就对不上。</li>
        <li><strong>提示四：把「机械能守恒」用在有摩擦或有非弹性碰撞的过程上。</strong>摩擦生热、绳突然绷紧、完全非弹性碰撞都会把一部分机械能变成内能，机械能减少。这些过程中能量仍然守恒，但守恒的是<strong>总能量</strong>而不是机械能，这时要改用动能定理或能量守恒的完整形式。</li>
      </ul>
    </div>
    <p>回收与预告：上一章把功与动能接在一起，这一章发现，当做功的力只有重力与弹力时，功可以被记成一种与位置绑定的能量，于是总量成为恒定的量。但这条结论只在「没有别的力做功」时成立。下一章处理剩下的一半：当摩擦力、拉力、安培力等非保守力也做功时，机械能会怎样变化，变化了多少，转化成了什么形式——力25 从功能关系推到能量守恒定律。</p>
