    <h3 class="sec" id="n1-hist">力是不是维持运动的原因</h3>
    <p>推着箱子在地面上走，松手之后箱子滑出一段就停下来；马拉车，马停下车也停下。这类现象见得多了，古希腊的亚里士多德得出一个结论：物体的运动需要力来维持，没有力，运动的物体必然静止。这个看法流传了近两千年。</p>
    <p>另一些现象却与它不符。冰壶被推出后能在冰面上滑出很远，抛出的石块在空中继续飞行，太空中飞了几十年的探测器始终没有人去推。这些物体并没有被谁持续推着，速度却变化得很慢，或者几乎不变。</p>
    <p>把两种情形放在一起比较，差别落在阻力上。地面上的箱子之所以停下，是摩擦力不断减小它的速度；速度减到零，运动才终止。阻力越小，同样的初速度下能滑得越远。由此可以设想：如果阻力完全消失，物体将保持原有的速度一直走下去。伽利略正是沿着这条思路走的。</p>

    <h3 class="sec" id="n1-galileo">伽利略斜面理想实验</h3>
    <p>阻力无法彻底消除，伽利略换了做法：不去追求「没有阻力」，而是把阻力一次比一次减小，看运动的趋势往哪里去。让小球在两个相对的斜面之间往复滚动的实验，就是通常所说的<strong>理想斜面实验</strong>。</p>
    <p>小球从一侧斜面的某一高度由静止释放，滚到底部后沿另一侧斜面上升，几乎回到释放时的高度；把另一侧斜面放得平缓一些，小球沿斜面走得更远，上升的高度仍然相同。这个高度关系可以直接算出来。无摩擦时，小球在倾角为 <Katex tex="\alpha" /> 的斜面上运动的加速度为 <Katex tex="g\sin\alpha" />，从高度 <Katex tex="H" /> 滑到底部，速率的平方为</p>
    <p style="text-align:center"><Katex tex="v^2=2gH." display /></p>
    <p>以这个速率冲上倾角为 <Katex tex="\theta" /> 的另一侧斜面，沿斜面能走的距离由匀减速到零的条件给出：</p>
    <p style="text-align:center"><Katex tex="s=\frac{v^2}{2g\sin\theta}=\frac{H}{\sin\theta}." display /></p>
    <p>沿斜面走过的距离乘上 <Katex tex="\sin\theta" /> 就是上升的高度，即</p>
    <p style="text-align:center"><Katex tex="h=s\sin\theta=H." display /></p>
    <p>上升高度与倾角无关，恒等于释放高度。倾角越小，斜面要走的路 <Katex tex="s" /> 越长，小球却总要慢下来，升到同一高度才停住。把这一侧斜面逐渐放平，<Katex tex="\theta\to 0" />，<Katex tex="s\to\infty" />：小球为了升到同一高度要走无限远的路，事实上永远走不到头，它会一直运动下去。这时沿运动方向没有任何力，速率也不再改变。</p>
    <p>这个推理靠的是「把阻力减小到零」的极限，实际做不出来，所以叫<strong>理想实验</strong>。它的价值在于换了一种提法：运动的物体停下来，原因不在运动本身，而在于阻力。</p>

