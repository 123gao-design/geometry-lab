    <h3 class="sec" id="n1-law">牛顿第一定律</h3>
    <p>牛顿把伽利略的结论整理成一条定律，内容是：<strong>一切物体总保持匀速直线运动状态或静止状态，除非有外力迫使它改变这种状态。</strong></p>
    <p>这条定律包含三层意思。</p>
    <p>其一，它给出了力与运动的正确关系。运动状态改变指的是速度改变，也就是有了加速度。定律说，不受外力时速度不变；反过来，速度发生变化时一定有外力作用。所以<strong>力是改变物体运动状态的原因</strong>。日常说的「用力推才动」，实际是推力与摩擦力共同作用的结果：两者平衡时箱子做匀速运动，推力大于摩擦力时箱子才有加速度。</p>
    <p>其二，它把「静止」与「匀速直线运动」放在同一个位置上。二者都是合力为零时的状态，区别只在参考系怎么选。匀速行驶的车厢里竖直上抛一只小球，小球落回手中；车厢突然加速时，小球落在后方。同一个现象，在不同参考系里的解释并不相同。</p>
    <p>其三，它指明了定律只在一定参考系里成立。定律成立、也就是不受力的物体能保持匀速直线运动的参考系叫<strong>惯性参考系</strong>，简称惯性系。地面在通常的精度下可以当作惯性系；相对地面加速的车厢不是惯性系，车厢里的小球会自己「向后跑」。这不是小球受了力，而是所选参考系的性质。</p>
    <p>牛顿第一定律不能用实验直接验证。任何实验都有摩擦，只能把阻力尽量减小，观察运动是否更接近匀速；定律是把实验趋势外推到阻力为零的结论。它与牛顿第二定律配合，才给出完整的关系：合力为零时加速度为零，速度不变；合力不为零时加速度与合力成正比。</p>

    <h3 class="sec" id="n1-inertia">惯性</h3>
    <p>物体保持原来运动状态不变的性质叫<strong>惯性</strong>。斜面实验里，小球落回同一高度、在水平面上速率不变，靠的都是这种性质。牛顿第一定律因此也叫惯性定律。</p>
    <p>惯性的大小由<strong>质量</strong>量度，与别的因素无关。同样的推力下，质量大的物体速度改变得慢，说明它的运动状态更难改变。满载的卡车比空车难启动，也难停下，区别就在这里。</p>
    <p>惯性不是力。「物体受到惯性的作用而继续运动」这句话把性质当成了相互作用：惯性没有施力物体，没有方向，也没有大小与公式，只能通过质量比较两个物体惯性的大小。正确的说法是「由于惯性，物体保持原来的速度」。</p>
    <p>一些常见现象可以用惯性解释。汽车突然启动，乘客下半身随车前进，上半身由于惯性保持静止，乘客向后仰；急刹车时相反，乘客向前倾，所以要系安全带。拍打衣服，衣服随手运动，衣服上的灰尘由于惯性留在原处，两者分开。跳远运动员助跑一段再起跳，起跳后由于惯性保持较大的水平速度，跳得更远。</p>
    <p>惯性与速度无关。同一辆车速度大时难停下来，是因为需要改变的速度更多、所需的时间更长，不是惯性变大了。惯性只随质量变化，这一点常被混淆。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：认为不受力时物体一定静止。</strong>合力为零时物体也可以做匀速直线运动，静止只是其中一种。物体原来怎样运动，合力为零之后就保持怎样运动。</li>
        <li><strong>提示二：把惯性说成力。</strong>惯性是物体自身的性质，不是相互作用，没有施力物体，也没有方向。分析受力时不要把惯性列进去。</li>
        <li><strong>提示三：认为速度越大惯性越大。</strong>惯性只由质量决定。高速行驶的轿车惯性并不比静止时更大，只是改变它的速度需要更大的冲量。</li>
        <li><strong>提示四：把牛顿第一定律当成能直接验证的实验规律。</strong>阻力无法完全消除，实际只能看到「越光滑滑得越远」的趋势。定律是理想实验加推理的结果，属于牛顿力学的基础假设。</li>
