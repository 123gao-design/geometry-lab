    <h3 class="sec" id="g-weight">重力</h3>
    <p>地面附近的物体都受到地球的吸引，这个力叫重力。重力的大小跟质量成正比：</p>
    <p style="text-align:center"><Katex tex="G=mg." display /></p>
    <p>式中的 <Katex tex="g" /> 叫重力加速度，取 <Katex tex="9.8\ \text{m/s}^2" />，粗略计算时取 <Katex tex="10\ \text{m/s}^2" />。质量是物体的固有属性，不随位置改变；重量随 <Katex tex="g" /> 改变，同一物体搬到高山上会略轻一些。</p>
    <p>重力的方向是<strong>竖直向下</strong>。这个说法与「垂直于接触面」是两件事：放在斜面上的物块，重力竖直向下，而斜面给它的支持力垂直于斜面，两者并不在同一直线上。严格地说，除赤道与两极之外，重力的方向并不精确指向地心，因为地球自转使物体还需要一部分指向地轴的力，重力的方向因此略有偏离。</p>
    <p>处理物体的受力时，可以把整个物体所受的重力看成作用在一点上，这一点叫<strong>重心</strong>。质量分布均匀、形状规则的物体，重心在几何中心上。重心不一定落在物体内部：一只均匀圆环的重心在圆心，那里并没有材料。把物体悬挂起来，静止时悬线的延长线必过重心，这也是实验中确定重心的办法。</p>

    <h3 class="sec" id="g-elastic">形变与弹力</h3>
    <p>物体在力的作用下形状或体积发生改变，叫形变。撤去外力后能恢复原状的叫<strong>弹性形变</strong>；不能恢复的叫塑性形变。弹性形变有一个限度，超过它就发生永久变形，这个限度叫<strong>弹性限度</strong>。</p>
    <p>发生了弹性形变的物体，由于要恢复原状，会对与它接触并使它形变的物体产生力的作用，这个力叫<strong>弹力</strong>。产生弹力必须同时满足两个条件：相互接触，并且发生弹性形变。只接触而不挤压，两物体之间没有弹力。</p>
    <p>形变常常很小，肉眼看不见。书放在桌面上，桌面被压下极微小的一段，正是这个微小形变给书提供了支持力。判断弹力是否存在，通常用假设法：假设撤去接触面，看物体能否保持原来的状态，若不能，说明该处有弹力。</p>
    <p>弹力的方向总与<strong>形变方向相反</strong>，可以按接触方式来定：</p>
    <ul>
      <li>两个面接触时，压力与支持力垂直于接触面，指向被压或被支持的物体；点与面接触时，垂直于面；球与球接触时，沿两球心的连线。</li>
      <li>绳的拉力沿绳，指向绳收缩的方向，只能拉不能推。</li>
      <li>轻杆的弹力不一定沿杆。杆既能拉又能推，方向要由物体的平衡条件或运动状态确定，只有在两端受力的特定情形下才沿杆。</li>
    </ul>

