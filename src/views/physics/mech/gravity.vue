    <h3 class="sec" id="g-tips">读题时的几点</h3>
    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把重力方向说成垂直向下。</strong>竖直向下是以铅垂线为准的方向；垂直于接触面是另一回事，只有水平面两者才一致。</li>
        <li><strong>提示二：认为接触就有弹力。</strong>弹力要求接触<em>并且</em>挤压。两个物体恰好挨在一起而相互间没有压力时，它们之间没有弹力。</li>
        <li><strong>提示三：把弹簧长度当形变量。</strong>公式里的 <Katex tex="x" /> 是伸长量或压缩量。题目给的是总长时，先用 <Katex tex="x=|l-l_0|" /> 换算。</li>
