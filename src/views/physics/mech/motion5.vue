    <h3 class="sec" id="m5-xt">位置—时间图的读法</h3>
    <p>位置—时间图以时间 <Katex tex="t" /> 为横轴、位置坐标 <Katex tex="x" /> 为纵轴。图线上一点的纵坐标是该时刻的位置，横坐标是该时刻。斜率则给出速度：</p>
    <p style="text-align:center"><Katex tex="v=\frac{\Delta x}{\Delta t}." display /></p>
    <p>直线图线表示匀速运动，斜率就是速度；图线越陡，速率越大；图线向下的部分速度为负，表示物体沿坐标轴负方向运动。曲线图线表示变速运动，某点切线斜率是该时刻的瞬时速度。</p>
    <p>两类关键位置要在图上认出来。其一，两条图线的交点：同一时刻两个物体的位置坐标相同，这就是相遇。其二，图线的折返点：位置先增后减（或先减后增），说明速度改变方向。图线与时间轴的交点只说明此刻位置坐标为零，与速度无关。</p>
    <p>位置—时间图不是物体的运动轨迹。一条斜率为正的直线，描述的是物体沿直线向正方向匀速运动，而不是画面上的那条斜线。纵轴的单位是米、横轴的单位是秒，两个轴的单位不同，图上直线的倾角也没有直接的物理含义，只有斜率（带单位）才有。</p>

    <h3 class="sec" id="m5-vt">速度—时间图的读法</h3>
    <p>速度—时间图的斜率是加速度，面积是位移。两物体同向运动时，把两条 v-t 图线画在同一张图上，两线之间的面积之差就是间距的变化量：后车图线在下方时面积小，间距变大；越过交点之后后车速度更大，面积补上，间距缩小。两线交点处速度相等，此后面积差开始回落，间距由增转减，此刻正是间距的极大值。</p>
    <p>速度—时间图中，图线穿过时间轴表示速度方向改变，此时物体速度为零、位移一般不为零，也不是回到了出发点。两图的区别可以概括为一句话：位置—时间图上的交点是相遇，速度—时间图上的交点是速度相等。</p>

    <h3 class="sec" id="m5-chase">追及问题的临界条件</h3>
    <p>设前车在 <Katex tex="t=0" /> 时位于 <Katex tex="x_1(0)=d_0" />，以速度 <Katex tex="v_1" /> 匀速前进；后车从原点由静止出发，以加速度 <Katex tex="a" /> 追赶。两车的位置分别为</p>
    <p style="text-align:center"><Katex tex="x_1(t)=d_0+v_1t,\qquad x_2(t)=\frac12at^2." display /></p>
    <p>两车之间的距离为</p>
    <p style="text-align:center"><Katex tex="\Delta(t)=x_1(t)-x_2(t)=d_0+v_1t-\frac12at^2." display /></p>
    <p>这是一条开口向下的抛物线。对 <Katex tex="t" /> 求导并令其为零，得到间距最大或最小的时刻：</p>
    <p style="text-align:center"><Katex tex="\Delta'(t)=v_1-at=0\ \Longrightarrow\ t^*=\frac{v_1}{a}." display /></p>
    <p>而在 <Katex tex="t^*" /> 处后车的速度正好是 <Katex tex="a t^*=v_1" />，与前车相等。于是得到追及问题的<strong>临界条件</strong>：<strong>两物体速度相等的时刻，就是间距取极值的时刻</strong>。这一结论与后车是加速还是减速无关，只要求两者在同一直线上相向或同向运动。</p>
    <p>后车若带初速度 <Katex tex="v_2" />，把上面推导里的 <Katex tex="v_1" /> 一律换成相对速度 <Katex tex="v_1-v_2" />：临界时刻为 <Katex tex="\frac{v_1-v_2}{a}" />，最大间距为 <Katex tex="d_0+\frac{(v_1-v_2)^2}{2a}" />。演示里保留「后车初速」这一根滑块，正是为了看这一层：初速越接近前车，速度相等的时刻越早，间距的峰值也越小。</p>
    <p>把 <Katex tex="t^*" /> 代回间距公式，得到最大间距</p>
    <p style="text-align:center"><Katex tex="\Delta_{\max}=d_0+\frac{v_1^2}{2a}." display /></p>
    <p>相遇的条件是 <Katex tex="\Delta(t)=0" />，即</p>
    <p style="text-align:center"><Katex tex="\frac12at^2-v_1t-d_0=0\ \Longrightarrow\ t=\frac{v_1+\sqrt{v_1^2+2ad_0}}{a}." display /></p>
    <p>另一个根为负值，舍去。这个根说明：只要后车一直加速下去，它迟早会追上匀速前进的前车——间距先增大到最大值，再逐渐减小到零。</p>

