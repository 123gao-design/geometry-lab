    <h3 class="sec" id="m5-cases">三类追及情形</h3>
    <p>速度相等是临界这一原则是通用的，但间距在临界点取极大还是极小，要看谁的速度更大，由此分出三种常见情形。</p>
    <p><strong>后车加速追匀速前车。</strong>后车起初慢，间距增大；速度相等时间距最大；此后后车更快，间距减小，最终追上。上面的推导就是这一情形。若加速度过小，追上所需的时间会很长，但一定能追上。</p>
    <p><strong>前车加速、后车匀速。</strong>后车起初快，间距减小；速度相等时间距最小；此后前车更快，间距重新增大。能否追上，取决于速度相等时两者是否已经相遇：若此刻间距仍为正，则永远追不上，这也是「恰好追不上」的临界条件。</p>
    <p><strong>后车减速追匀速前车。</strong>后车速度逐渐减小，一旦减到与前车相等之后就比前车慢，间距从此增大。因此能否追上只在速度相等之前决定：若在此时刻之前仍未相遇，此后就再也追不上。汽车刹车避让前方车辆属于这一类，安全距离的计算正是按「速度相等时恰好不相撞」来定的。</p>
    <p>三类情形可以用同一套步骤处理：先写出两个物体的位置随时间的函数，再令两者速度相等求临界时刻，最后判断此刻的间距符号。比起逐段讨论，这一流程更不容易漏掉情形。</p>

