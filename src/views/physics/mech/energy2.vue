    <h3 class="sec" id="e2-why">为什么值得用它</h3>
    <p>牛顿第二定律配运动学公式当然也能解同一道题，但那条路要求：力必须恒定（否则加速度在变，匀变速公式全部失效）、必须知道时间或加速度、过程中间状态要一步步算。<strong>动能定理绕开了这三条</strong>。它只问三件事：初速度多大、末速度多大、全程有哪些力做功各做了多少。</p>
    <p>下面三种题目，用动能定理往往比用牛顿定律短得多。</p>
    <p><strong>过程里有变力。</strong>弹簧把物体推开、空气阻力随速度变化、机车以恒定功率起动，这些过程加速度一直在变。牛顿定律只能逐时刻算，动能定理却可以整段处理，只要能把每一项功算出来（弹簧用 <Katex tex="\tfrac12kx^2" />，恒定功率用 <Katex tex="Pt" />，f–s 图用面积）。</p>
    <p><strong>过程分段很多。</strong>物体先沿斜面下滑、再在水平面上滑行、最后冲上另一段斜面，中间速度往往既不需要也不想知道。可以对全程写一个式子，中间状态的速度自动消掉；也可以分两段各写一个式子再联立。</p>
    <p><strong>只求末速度或位移，不求时间。</strong>刹车距离、子弹穿透木板、物体冲上斜面的最大高度，都属于这一类。</p>
    <p>与之相对，凡是要求某时刻的速度方向、需要知道加速度随时间的变化、或者要分析某一瞬间的受力，仍然得回到牛顿定律。两套工具各有分工：动能定理管「跨越一段过程」，牛顿定律管「某一时刻」。</p>

    <h3 class="sec" id="e2-cases">应用：刹车距离与变力做功</h3>
    <p><strong>刹车距离。</strong>汽车以 <Katex tex="v_0" /> 行驶，紧急刹车后只受滑动摩擦力 <Katex tex="\mu mg" />，滑行 <Katex tex="s" /> 停下。对这段过程写动能定理：</p>
    <p style="text-align:center"><Katex tex="-\mu mg\,s=0-\tfrac12mv_0^2\quad\Longrightarrow\quad s=\frac{v_0^2}{2\mu g}." display /></p>
    <p>质量被消掉了：重的车与轻的车刹车距离相同，因为重力同时放大了惯性与摩擦力。但速度是平方关系——初速翻倍，刹车距离变成四倍。这也是雨天要保持车距的定量依据：路面湿滑把 <Katex tex="\mu" /> 拉低，<Katex tex="s" /> 随 <Katex tex="\mu" /> 成反比地变长。</p>
    <p><strong>变力做功。</strong>力随位移变化时，功等于力—位移图线下方到横轴围出的面积。若图线在横轴上方，功为正；在下方（比如方向相反的力），面积为负。把若干个这样的面积代数和起来就是总功，再代入动能定理求速度。演示右栏的三条直线就是这个面积法则的恒力版本——直线下的面积正是矩形 <Katex tex="Fs" />，三条线的面积分别是拉力、摩擦力与合力各做的功。</p>
    <p><strong>用动能定理的四个步骤。</strong>一是选定研究对象与过程，明确初、末两个状态；二是受力分析，逐项算功，正负号写清，垂直的力不做功；三是写出初末动能，注意 <Katex tex="v" /> 要平方；四是列式求解，结果回头检查单位与符号。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把 <Katex tex="W_{\text{合}}" /> 当成某一个力做的功。</strong>左边必须是<strong>所有</strong>力做功的代数和。少算重力、支持力或摩擦力中的任何一项，右侧的动能变化就对不上。支持力与位移垂直时功为零，仍要在受力分析里过一遍再划掉。</li>
        <li><strong>提示二：把右边的顺序写反。</strong>是<strong>末动能减初动能</strong>，不是初减末。物体减速时右边为负，正好与负的总功相符；写反了两边符号同时错，看似「抵消」却是错的式子。</li>
        <li><strong>提示三：认为动能定理只适用于恒力与直线运动。</strong>它对变力、曲线运动和多过程同样成立，这正是它最有用的地方。但每一项功都要按实际情况算，变力要算真实的功，不能用 <Katex tex="Fs\cos\theta" /> 硬套。</li>
        <li><strong>提示四：算摩擦力做功时用位移而不是路程。</strong>摩擦力的大小不变而方向始终与运动方向相反，物体往返时摩擦力每一段都做负功，所以它的功是 <Katex tex="-\mu mg\cdot s_{\text{路程}}" />，要用走过的<strong>路程</strong>；而总功里其余各项仍按位移算。一个物体滑出去又滑回来，位移为零、路程不为零，这两者不能混。</li>
      </ul>
