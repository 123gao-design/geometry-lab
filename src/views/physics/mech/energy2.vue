    <h3 class="sec" id="e2-ek">动能</h3>
    <p>同样速度的两辆车，载重的那辆刹不住。同样质量的两个球，快的那颗撞得更狠。这两个经验合成一句话：运动物体「能对外做功的本领」由质量与速度共同决定。</p>
    <p>把质量翻倍，动能翻倍；把速度翻倍，动能为原来的四倍。速度出现在平方上，这一点与动量很不一样，也是「快」比「重」更危险的原因：时速从 40 km/h 提到 80 km/h，动能变成四倍，刹车距离也跟着变成四倍。</p>
    <p>动能的单位可以由定义直接看出：<Katex tex="\text{kg}\cdot(\text{m/s})^2=\text{kg}\cdot\text{m/s}^2\cdot\text{m}=\text{N}\cdot\text{m}=\text{J}" />，与功同单位。动能是状态量，由某一时刻的 <Katex tex="m" /> 与 <Katex tex="v" /> 决定；功是过程量，与一段过程对应。动能定理的作用，正是把这两类量连起来。</p>

    <h3 class="sec" id="e2-theorem">动能定理与它的推导</h3>
    <p>先看最简单的情形：质量 <Katex tex="m" /> 的物体在恒力 <Katex tex="F" /> 作用下沿直线运动，速度由 <Katex tex="v_1" /> 变成 <Katex tex="v_2" />，位移为 <Katex tex="s" />。由牛顿第二定律，加速度 <Katex tex="a=F/m" />；由匀变速运动的速度位移关系，</p>
    <p style="text-align:center"><Katex tex="v_2^2-v_1^2=2as." display /></p>
    <p>把 <Katex tex="a=F/m" /> 代入，两边同乘 <Katex tex="m/2" />：</p>
    <p style="text-align:center"><Katex tex="\tfrac12mv_2^2-\tfrac12mv_1^2=\tfrac12m\cdot\frac{F}{m}\cdot 2s=Fs=W." display /></p>
    <p>这就是恒力直线情形的动能定理。演示把这段过程搬到了画面上：横轴是位移 <Katex tex="s" />，纵轴是功，橙色那条线的斜率就是拉力 <Katex tex="F" />，紫色虚线斜率为负、画的是摩擦力做的负功，绿色那条是两者的和即总功，斜率为合力 <Katex tex="F-f" />。右端青色圈标出动能变化 <Katex tex="\tfrac12mv^2" />，它每次都严丝合缝地落在绿色线上——把滑块调成任何一组数，这枚圈都不会跑开。</p>
    <p>真正有用的是这条等式并不限于恒力与直线。把整段路径切成许多足够短的小段，每一小段上力可以看作恒力、路径可以看作直线，于是每一段都满足 <Katex tex="\Delta W=\Delta E_k" />。把各段相加，左边是总功，右边各段的动能增量前后相消，只剩末动能减初动能：</p>
    <p style="text-align:center"><Katex tex="W_{\text{合}}=E_{k2}-E_{k1}." display /></p>
    <p>这个「切成小段再相加」的思路在数学上就是积分，<Katex tex="W=\int F\,dx" />。物理上要在意的只有一点：变力、曲线、多过程都照用，只要把每一项功都算全、正负号都写对。</p>
    <p>把这段恒力过程画出来，三份功与动能变化的关系就摆在眼前：横轴是位移，三条线分别是拉力做的功、摩擦力做的功与两者的和。</p>

