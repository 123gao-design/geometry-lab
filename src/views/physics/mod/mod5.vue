    <h3 class="sec" id="m5-comp">原子核的组成与人工核反应</h3>
    <p>原子核由质子与中子组成，两者统称核子。质子带一个单位的正电荷，中子不带电，它们的质量都约等于一个原子质量单位。原子核的电荷数等于质子数，也就是元素的原子序数；质量数等于质子数与中子数之和。同一元素可以有中子数不同的几种核，它们叫同位素，化学性质相同而核的性质可能差别很大。</p>
    <p>1919 年，卢瑟福用 α 粒子轰击氮核，发现打出的粒子是氢核，这是人类第一次实现人工核转变：</p>
    <p style="text-align:center"><Katex tex="{}^{14}_{7}\mathrm{N}+{}^{4}_{2}\mathrm{He}\;\longrightarrow\;{}^{17}_{8}\mathrm{O}+{}^{1}_{1}\mathrm{H}" display /></p>
    <p>1932 年，查德威克用 α 粒子轰击铍，得到一种不带电、穿透力很强的粒子，这就是中子：</p>
    <p style="text-align:center"><Katex tex="{}^{9}_{4}\mathrm{Be}+{}^{4}_{2}\mathrm{He}\;\longrightarrow\;{}^{12}_{6}\mathrm{C}+{}^{1}_{0}\mathrm{n}" display /></p>
    <p>中子的发现补全了原子核的组成图像：核里只有质子与中子。同年，约里奥—居里夫妇用 α 粒子轰击铝，得到放射性磷，它随后放出正电子变成硅：</p>
    <p style="text-align:center"><Katex tex="{}^{27}_{13}\mathrm{Al}+{}^{4}_{2}\mathrm{He}\;\longrightarrow\;{}^{30}_{15}\mathrm{P}+{}^{1}_{0}\mathrm{n},\qquad {}^{30}_{15}\mathrm{P}\;\longrightarrow\;{}^{30}_{14}\mathrm{Si}+{}^{0}_{+1}\mathrm{e}" display /></p>
    <p>这是第一个人工放射性同位素。放射性同位素能按需要制成，半衰期从几小时到几年不等，医疗、工业、农业的示踪与辐照都靠它。核反应方程的写法与衰变方程一样：左上角的质量数守恒，左下角的电荷数守恒，反应物与产物各类粒子都要写全，不能漏掉中子、正电子这些没有单独名字的产物。</p>

    <h3 class="sec" id="m5-mass">质量亏损与质能方程</h3>
    <p>把参与核反应的粒子质量逐一加起来，会发现反应后的总质量比反应前小一点。这个差额叫质量亏损，记作 <Katex tex="\Delta m" />。爱因斯坦的质能方程指出，物体的能量与质量成正比：</p>
    <p style="text-align:center"><Katex tex="E=mc^2" display /></p>
    <p>于是系统的质量减少 <Katex tex="\Delta m" /> 时，放出的能量是</p>
    <p style="text-align:center"><Katex tex="\Delta E=\Delta m\,c^2" display /></p>
    <p>这个关系对一切能量转化都成立，核反应中的数值特别大，因为光速的平方是一个极大的数。计算中常用原子质量单位：</p>
    <p style="text-align:center"><Katex tex="1\,\mathrm{u}=1.660\,54\times10^{-27}\,\mathrm{kg},\qquad 1\,\mathrm{u}\cdot c^2\approx931.5\,\mathrm{MeV}" display /></p>
    <p>以氘氚聚变为例，反应物质量与产物质量分别为：</p>
    <p style="text-align:center"><Katex tex="m_{\mathrm{D}}+m_{\mathrm{T}}=2.014\,10+3.016\,05=5.030\,15\,\mathrm{u}" display /></p>
    <p style="text-align:center"><Katex tex="m_{\mathrm{He}}+m_{\mathrm{n}}=4.002\,60+1.008\,66=5.011\,26\,\mathrm{u}" display /></p>
    <p>质量亏损 0.018 89 u，折合 <Katex tex="0.018\,89\times931.5\approx17.6\,\mathrm{MeV}" />。这就是一个氘核与一个氚核聚变放出的能量，比化学反应中每个分子放出的几电子伏大六七个数量级。</p>
    <p>质量亏损并不是质量凭空消失。质量与能量是同一实体的两种量度，系统的能量减少多少，质量就减少多少；减少的质量以光子与产物动能的形式带了出去。质子与中子一个也没少，只是它们组成了新的核之后，整体质量比自由时略小。</p>

    <h3 class="sec" id="m5-bind">结合能与比结合能</h3>
    <p>单个质子与中子的质量之和，总比它们结合成的核的质量大。反过来看，把核拆散成自由的质子与中子，必须提供同样多的能量，这份能量叫原子核的结合能。核反应放出的能量，本质上来自反应前后核的结合能差：</p>
    <p style="text-align:center"><Katex tex="\Delta E=B_2-B_1" display /></p>
    <p>其中 <Katex tex="B_2" /> 是产物的结合能总和，<Katex tex="B_1" /> 是反应物的结合能总和。换句话说，核反应放出的能量，就是产物比反应物多出来的那份结合能。</p>
    <p>不同核的结合能相差很大，因为核里的核子数不同。把结合能除以质量数，得到平均每个核子分摊的能量，叫比结合能：</p>
    <p style="text-align:center"><Katex tex="\frac{B}{A}" display /></p>
    <p>比结合能越大，说明核子结合得越紧，核越稳定。</p>
    <p>把各种核的比结合能按质量数画在一条曲线上，得到的形状是：轻核区数值小且起伏大，随质量数迅速上升；在质量数 56 附近（铁峰）达到最大值，约 8.8 MeV；此后随质量数缓慢下降，到铀 238 时约 7.6 MeV。曲线的两端都比峰顶低，中间高，像一个拱形。</p>
    <p>这条曲线把裂变与聚变的能量来源说清楚了。两个轻核合成一个较重的核，产物沿曲线向峰顶靠近，比结合能升高，结合能差以能量形式放出；一个重核分成两个中等核，产物也从峰的右侧移到峰附近，同样升高。反过来，把中等核再劈开或再拼合，产物的比结合能反而降低，必须吸收能量才做得到。所以核能的两种来源正是曲线两侧朝峰顶的两个方向。</p>

    <PhysicsDemo :def="DEMO" />
    <p class="cap">图 原5 · <b>比结合能曲线：裂变与聚变都朝铁峰爬升</b>：横轴是质量数 A，纵轴是比结合能 E/A，蓝线按半经验公式铺出，形状与课本上那条拱形曲线一致。看点一：默认停在铁峰，读数栏给出 A = 56 处比结合能约 8.75 MeV、总结合能约 490 MeV，以及对应的质量亏损。看点二：把 A 拖到 4，比结合能只有 4 MeV 左右，离峰顶差得最多，所以轻核聚变放出的能量可观。看点三：把 A 拖到 238，比结合能落到 7.6 MeV，产物落在 A 约 120 处、比结合能约 8.6 MeV，每核子约放出 1 MeV。看点四：切到「链式反应」档，增殖系数 k = 2.5 时第 9 代已长到几万个中子，累计裂变次数与放能随之暴涨；把 k 拖到 1 以下，中子代代减少，链式反应熄灭。</p>

    <h3 class="sec" id="m5-fis">重核裂变与链式反应</h3>
    <p>铀 235 俘获一个慢中子后，会分裂成两个中等质量的核，同时放出两三个中子：</p>
    <p style="text-align:center"><Katex tex="{}^{235}_{92}\mathrm{U}+{}^{1}_{0}\mathrm{n}\;\longrightarrow\;{}^{144}_{56}\mathrm{Ba}+{}^{89}_{36}\mathrm{Kr}+3\,{}^{1}_{0}\mathrm{n}" display /></p>
    <p>这个反应每次放出约 200 MeV 的能量，质量亏损约 0.2 u。裂变产物不唯一，钡与氪只是其中一种分法，但放出的能量与中子数都在这几倍以内。</p>
    <p>裂变放出的中子如果又能引发别的铀核裂变，反应就会一代接一代地进行，这叫链式反应。能否持续，取决于每次裂变产生的中子里有多少还能触发下一次裂变，这个比值叫中子增殖系数 k。k 大于 1 时反应增长，等于 1 时稳定运行，小于 1 时逐渐熄灭。铀块太小时，中子容易从表面逸出而白白损失；只有体积超过临界体积，k 才可能大于 1。天然铀中铀 235 只占百分之零点七，反应堆需要提高铀 235 的浓度。</p>
    <p>反应堆里还有三类部件：慢化剂（石墨、重水）让快中子减速，因为铀 235 对慢中子的俘获截面大得多；控制棒（镉、硼）吸收多余的中子，插入深浅调节 k；冷却剂把热量带到蒸汽发生器，推动汽轮机发电。核电站的能量密度极高，1 kg 铀 235 完全裂变约放出 <Katex tex="8\times10^{13}" /> J，相当于燃烧约 2800 吨标准煤。</p>

    <h3 class="sec" id="m5-fus">轻核聚变</h3>
    <p>轻核聚合成较重的核也能放出能量。最容易实现的是氘核与氚核的反应：</p>
    <p style="text-align:center"><Katex tex="{}^{2}_{1}\mathrm{H}+{}^{3}_{1}\mathrm{H}\;\longrightarrow\;{}^{4}_{2}\mathrm{He}+{}^{1}_{0}\mathrm{n}+17.6\,\mathrm{MeV}" display /></p>
    <p>按每个核子平均，聚变放出约 3.5 MeV，是裂变的四倍上下。但两个核都带正电，要靠近到核力能起作用的距离，先得克服库仑斥力，因此必须让核有上亿度的动能，这样的反应叫热核反应。太阳内部就靠这类反应发光：四个质子最终合成一个氦核，放出约 26.7 MeV，温度约一千五百万度，靠巨大的密度与漫长的约束时间弥补温度上的差距。</p>
    <p>受控聚变的难点在于「点火」与「约束」。磁约束用强磁场把上亿度的等离子体悬在真空室里，托卡马克装置是代表；惯性约束用激光从四面八方同时压缩一个小靶丸。目前还没有实现输出能量稳定超过输入能量的商业堆，但氘在海水中储量极大，产物又没有长半衰期的放射性废物，这一路线的吸引力正在于此。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把质量亏损理解为「质量消失了」。</strong>质量与能量是同一实体的两种量度，核反应前后系统的总质量确实变小，减少的部分以光子与粒子动能的形式带出去。参与反应的质子与中子一个不少，只是重新组合后整体质量略小。</li>
        <li><strong>提示二：把结合能当成原子核本身具有的能量。</strong>结合能是把核拆成自由核子必须提供的能量，是一个「差值」而不是存量。判断稳定性看比结合能，不看总结合能；铀 238 的总结合能比铁 56 大，比结合能却更小。</li>
        <li><strong>提示三：认为只要铀足够多就一定能持续链式反应。</strong>还要看中子是否够慢、是否逃逸过多、铀 235 的浓度是否够高。体积小于临界体积、或没有慢化剂时，增殖系数小于 1，反应无法自持。</li>
        <li><strong>提示四：认为比结合能大，聚变就会自动发生。</strong>聚变要先让两个带正电的核克服库仑斥力靠近，必须提供极高的温度；太阳内部与托卡马克装置做的都是为了满足这一条件。曲线只说明能量上放得开，不说明反应容易发生。</li>
        <li><strong>提示五：计算质量亏损时漏掉中子或正电子。</strong>核反应方程的产物常带中子、正电子这类没有单独名字的粒子，漏一项质量差就错了整整一个量级。先按两条守恒把方程配平，再逐一核对质量，顺序不能颠倒。</li>
      </ul>
