    <h3 class="sec" id="m4-eq">衰变方程与守恒</h3>
    <p>衰变是原子核变成另一种核的过程，可以用核反应方程表示。方程的书写遵守两条守恒：反应前后的质量数（左上角）相等，电荷数（左下角）相等。核反应中原子核的数目、种类发生改变，但参与反应的粒子数并不消失，这两条守恒式就是配平它的依据。</p>
    <p>α 衰变放出氦核，新核的质量数减 4、电荷数减 2。以铀 238 为例：</p>
    <p style="text-align:center"><Katex tex="{}^{238}_{92}\mathrm{U}\;\longrightarrow\;{}^{234}_{90}\mathrm{Th}+{}^{4}_{2}\mathrm{He}" display /></p>
    <p>β 衰变是一个中子转变成质子，同时放出电子。原子序数加 1，质量数不变：</p>
    <p style="text-align:center"><Katex tex="{}^{234}_{90}\mathrm{Th}\;\longrightarrow\;{}^{234}_{91}\mathrm{Pa}+{}^{0}_{-1}\mathrm{e}" display /></p>
    <p>γ 衰变只是原子核从激发态回到低能级、放出光子，质量数与电荷数都不变，通常在 α 或 β 衰变之后紧接着发生。方程里写 γ 时，左边核的质量数、电荷数原样保留。</p>
    <p>题目常给出一段连续衰变链的起点与终点，要求算出几次 α 衰变、几次 β 衰变。质量数只由 α 衰变改变，每次减 4，所以 <Katex tex="n_\alpha=(A_1-A_2)/4" />。电荷数由两者共同决定，初末电荷数之差与 <Katex tex="2n_\alpha" /> 的差额由 β 衰变补上：</p>
    <p style="text-align:center"><Katex tex="n_\beta=2n_\alpha-(Z_1-Z_2)" display /></p>
    <p>以铀 238 变成铅 206 为例，<Katex tex="A" /> 从 238 减到 206，<Katex tex="n_\alpha=8" />；<Katex tex="8" /> 次 α 衰变使电荷数减少 16，而 <Katex tex="Z" /> 只从 92 减到 82、减少 10，差额 6 由 6 次 β 衰变补回。所以这条链包含 8 次 α 衰变与 6 次 β 衰变。</p>

    <h3 class="sec" id="m4-use">应用与防护</h3>
    <p>半衰期给放射性物质提供了一只天然的钟。碳 14 的半衰期约 5730 年，活的生物体内碳 14 的比例与大气保持一致，死后不再补充，比例按指数衰减，测出残存量就能推算年代，考古上用来测定几万年以内的遗物。铀与铅的比例用来测定岩石与地球的年龄，铀 238 的半衰期长，适合标定亿年尺度。</p>
    <p>医疗与工业上，钴 60 放出的 γ 射线能量高、穿透力强，用于肿瘤放疗与射线探伤；碘 131 的半衰期 8 天，进入体内后集中在甲状腺，可用于诊断与治疗。示踪技术把微量的放射性核引入体系，靠探测器的信号追踪物质在生物体或管道里的走向。</p>
    <p>射线的防护靠三条：距离、时间、屏蔽。射线强度随距离增大而减弱，操作时用长柄工具；受到的剂量与暴露时间成正比，尽量缩短停留；α 射线一张纸即可挡住，β 射线用几毫米铝板，γ 射线要厚铅或混凝土。放射性废料半衰期长，需要长期封存，这部分代价要与它带来的收益一并计算。</p>
    <p>放射性并不只出现在反应堆里：岩石中的铀、钍、钾，建筑材料、甚至人体内的碳 14 与钾 40，都贡献着微小的本底剂量。判断风险要看剂量大小与射线种类，不能笼统地说「有放射性」。</p>

