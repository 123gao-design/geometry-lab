    <h3 class="sec" id="m4-rays">放射性与三种射线</h3>
    <p>1896 年，贝克勒尔发现铀盐能自发地发出一种看不见的射线，使包在暗处的照相底片感光。两年后，居里夫妇从沥青铀矿中先后分离出钋和镭，证明放射现象来自原子内部。这类物质叫放射性元素，它发出射线的性质叫放射性。</p>
    <p>把射线放进磁场，它分成三束：向一方偏转的一束叫 α 射线，向相反方向偏转的一束叫 β 射线，不偏转的一束叫 γ 射线。α 与 β 的偏转方向相反，说明它们带的电荷相反。</p>
    <p>α 射线是氦核流，每个粒子由两个质子与两个中子组成，电荷 <Katex tex="+2e" />，质量是氢原子的四倍。它速度约为光速的十分之一，电离本领最强，但穿透本领最弱，一张纸或几厘米空气就能把它挡住。</p>
    <p>β 射线是高速电子流，速度接近光速。它的电离本领比 α 弱得多，穿透本领较强，能穿过几毫米的铝板。β 射线里的电子不是原子核外原有的电子，而是核内的中子转变成质子时放出来的。</p>
    <p>γ 射线是波长极短的电磁波，也就是光子流，不带电，在磁场中不偏转。它的电离本领最弱、穿透本领最强，能穿过钢板，只能用厚铅板削弱。γ 射线通常伴随 α 衰变或 β 衰变发出：衰变后新核处在激发态，回到低能级时放出光子。</p>
    <p>三种射线的本领排序可以记成两条相反的顺序：电离本领 α > β > γ，穿透本领 γ > β > α。穿透强是因为与物质作用弱，作用弱电离也就弱，两者此消彼长。</p>

    <h3 class="sec" id="m4-law">衰变规律与半衰期</h3>
    <p>放射性元素衰变的快慢用什么衡量？实验发现，对同一种放射性元素，经过相同的时间，衰变的核占总数的比例始终相同，与样品多少、外界条件都无关。平均地看，半数的核发生衰变所需的时间是一个确定值，这个时间叫半衰期，记作 <Katex tex="T" />。</p>
    <p>经过一个半衰期，剩下一半；再过一半衰期，剩下四分之一；经过 <Katex tex="n" /> 个半衰期，剩下 <Katex tex="1/2^n" />。写成连续的形式，</p>
    <p style="text-align:center"><Katex tex="N=N_0\left(\dfrac12\right)^{t/T},\qquad m=m_0\left(\dfrac12\right)^{t/T}" display /></p>
    <p>其中 <Katex tex="N_0" />、<Katex tex="m_0" /> 是初始的核数与质量。<Katex tex="t" /> 不一定是半衰期的整数倍，指数可以取任意实数。这条规律对每一种放射性元素都成立，只是半衰期各不相同：钋 214 只有 <Katex tex="1.6\times10^{-4}" /> s，镭 226 约 1600 年，铀 238 约 45 亿年。</p>
    <p>半衰期由原子核内部的结构决定，与元素所处的化学状态、温度、压强几乎无关。加热、加压、加催化剂都不能让铀 238 衰变得快一些；把它做成化合物，半衰期也不变。要改变半衰期，只能改变核本身。</p>
    <p>需要分清统计规律与单个事件。半衰期 1 小时的样品，取 100 亿个核，1 小时后大约剩 50 亿个，这个比例相当精确；若只取 4 个核，1 小时后剩几个完全无法预测，可能剩 2 个，也可能一个都没剩。半衰期说的是大量核的平均行为，对单个核只能说它在一段时间内衰变的概率。</p>

