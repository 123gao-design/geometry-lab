    <h3 class="sec" id="m3-model">从枣糕模型到核式结构</h3>
    <p>电子的发现说明原子可以再分，原子内部必然有带正电的部分。1904 年汤姆孙提出枣糕模型：正电荷均匀分布在整个原子中，电子像枣子一样嵌在里面，整体呈中性。这个模型能解释原子为什么是电中性的，也能解释气体电离的一些现象，在当时被广泛接受。</p>
    <p>1911 年，卢瑟福让一束 α 粒子射向很薄的金箔，用荧光屏在四周转动，记录各个方向上散射出的 α 粒子数目。结果出乎意料：绝大多数 α 粒子几乎沿原方向穿过，只有少数偏转较大，极少数（约八千分之一）几乎被弹了回来。α 粒子质量是电子质量的七千多倍、速度很高，能把它大角度弹开的东西，必须质量很大而且集中，均匀分布的枣糕模型给不出这样的力。</p>
    <p>卢瑟福由此提出核式结构模型：原子的中心有一个体积很小的原子核，集中了几乎全部质量和正电荷，电子在核外空间运动。核半径的数量级是 <Katex tex="10^{-15}" /> m，原子半径约 <Katex tex="10^{-10}" /> m，两者相差十万倍；把原子放大到足球场，原子核只有一粒芝麻大小。α 粒子只有极少数能靠近核，绝大部分从核外空旷处穿过，这就是散射现象的由来。</p>
    <p>核式结构模型立刻带来两个经典理论解决不了的困难。其一，绕核运动的电子有加速度，按经典电磁理论要不断辐射能量，能量减小、轨道变小，约 <Katex tex="10^{-11}" /> s 就会落进核内，原子不可能稳定存在。其二，连续辐射给出的应是连续谱，而实验测到的氢原子光谱是一组分立的细线。稳定与分立，这两件事经典理论都给不出解释。</p>

    <h3 class="sec" id="m3-bohr">玻尔模型与氢原子能级</h3>
    <p>玻尔在核式结构的基础上引入量子观念，提出三条假设。第一条是定态假设：电子只能在一些分立的轨道上绕核运动，在这些轨道上运动时不向外辐射能量，这样的状态叫定态。第二条是跃迁假设：电子从一个定态跃迁到另一个定态时，吸收或放出一份光子，光子能量等于两定态能量之差。第三条是量子化条件：电子轨道的角动量只能取 <Katex tex="h/2\pi" /> 的整数倍。</p>
    <p>把这三条用到氢原子上，可以解出第 <Katex tex="n" /> 个定态的半径与能量：</p>
    <p style="text-align:center"><Katex tex="r_n=n^2r_1,\qquad E_n=\dfrac{E_1}{n^2}" display /></p>
    <p>其中 <Katex tex="r_1=0.53\times10^{-10}" /> m，<Katex tex="E_1=-13.6" /> eV。<Katex tex="n=1" /> 的状态叫基态，能量最低，也最稳定；<Katex tex="n=2,3,4,\dots" /> 的各个状态叫激发态。能级的具体数值是：</p>
    <p style="text-align:center"><Katex tex="E_1=-13.60,\quad E_2=-3.40,\quad E_3=-1.51,\quad E_4=-0.85,\quad E_5=-0.54\ \mathrm{(eV)}" display /></p>
    <p>能量取负值，因为把电子与核相距无穷远时定为能量的零点；处于束缚态时，把电子移到无穷远去还要补充能量，所以束缚态的能级低于零。能级越高，绝对值越小，越靠近零。低能级之间间隔很大，高能级越来越密，到 <Katex tex="n\to\infty" /> 时趋近于零。</p>
    <p>由基态到 <Katex tex="n\to\infty" /> 需要 13.6 eV 的能量，这个数叫氢原子的电离能。半径随 <Katex tex="n^2" /> 增大，第 2 个定态的轨道半径是基态的四倍，但这仍只是经典图像的借用，量子力学里电子并没有确定的轨道。</p>

