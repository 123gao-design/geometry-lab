      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把能级能量当成正值。</strong>束缚态能量取负，零点在电子与核相距无穷远的状态。<Katex tex="n" /> 越大能量越接近零，从高能级往低能级跃迁放出光子，能量差按 <Katex tex="E_m-E_n>0" /> 算。</li>
        <li><strong>提示二：认为任何能量的光子都能被原子吸收。</strong>只有能量恰好等于两能级之差的光子才被吸收，多余与不足都不行。所谓吸收光谱上的暗线，就是那些恰好对得上能级差的光被吸收掉留下的缺口。</li>
        <li><strong>提示三：把一群原子与一个原子的谱线条数混为一谈。</strong>一个氢原子从第 <Katex tex="n" /> 能级往下跳，最多发 <Katex tex="n-1" /> 个光子；大量原子同时参与，谱线数按 <Katex tex="n(n-1)/2" /> 计。题目若没说原子数，要按题意判断。</li>
        <li><strong>提示四：把跃迁与电离当成同一件事。</strong>电离要的是光子能量不小于电离能，多余部分变成自由电子的动能，光子的能量不必恰好等于某个能级差；跃迁则严格受能量匹配约束。</li>
