    <h3 class="sec" id="m3-spec">氢原子光谱与巴尔末系</h3>
    <p>物体发光的光按波长展开得到光谱。白炽灯、太阳这样的光源给出连续光谱，从红到紫连成一片；稀薄气体通电发光得到的是线状谱，在黑暗背景上排着一组细线。每种元素的线状谱都有自己的特征线，光谱分析就靠这一点辨认元素，氢原子光谱是其中研究得最早、也最简单的。</p>
    <p>1885 年，巴尔末从实验数据里总结出可见光区氢谱线的规律：</p>
    <p style="text-align:center"><Katex tex="\dfrac{1}{\lambda}=R\left(\dfrac{1}{2^2}-\dfrac{1}{n^2}\right),\qquad n=3,4,5,\dots" display /></p>
    <p><Katex tex="R=1.097\times10^{7}\ \mathrm{m^{-1}}" /> 叫里德伯常量。取 <Katex tex="n=3,4,5,6" /> 得 656.3、486.1、434.0、410.2 nm 四条线，依次记作 <Katex tex="\mathrm{H_\alpha}" />、<Katex tex="\mathrm{H_\beta}" />、<Katex tex="\mathrm{H_\gamma}" />、<Katex tex="\mathrm{H_\delta}" />，落在红、蓝绿、蓝紫与紫，正是光谱里能看到的那四条。继续往上 <Katex tex="n" /> 增大，谱线越来越密，最后趋近 <Katex tex="n\to\infty" /> 给出的极限 364.6 nm。</p>
    <p>把这一条推广到其他末态，得到氢光谱的普遍公式：</p>
    <p style="text-align:center"><Katex tex="\dfrac{1}{\lambda}=R\left(\dfrac{1}{n_1^2}-\dfrac{1}{n_2^2}\right),\qquad n_2>n_1" display /></p>
    <p><Katex tex="n_1=1" /> 的一组叫莱曼系，全部在紫外区；<Katex tex="n_1=2" /> 的巴尔末系在可见光并有部分紫外；<Katex tex="n_1=3" /> 的帕申系、<Katex tex="n_1=4" /> 的布拉开系都在红外。系与系之间的区别，就是电子最后停在哪个能级。</p>
    <p>玻尔理论最有力的地方在于，把能级差写成光子能量，上面这条经验公式可以整条推出来。由 <Katex tex="h\nu=E_{n_2}-E_{n_1}" /> 与 <Katex tex="\lambda=c/\nu" /> 得</p>
    <p style="text-align:center"><Katex tex="\dfrac{1}{\lambda}=\dfrac{E_{n_2}-E_{n_1}}{hc}" display /></p>
    <p>代入 <Katex tex="E_n=-13.6/n^2" /> eV，算出的里德伯常量与实验值 1.097×10⁷ m⁻¹ 对得上，谱线位置误差在万分之几。一个从假设推出的式子与一组测了几十年的数据吻合到这个程度，玻尔模型因此被接受。</p>

    <h3 class="sec" id="m3-use">跃迁条件与电离</h3>
    <p>原子吸收或放出光子的条件是光子能量恰好等于两个能级之差，<Katex tex="h\nu=\Delta E" />。多一分、少一分都不被吸收，光子原样穿过，所以气体对连续光的吸收谱是一组暗线，位置与它的发射线一一对应。氢原子从基态跃迁到 <Katex tex="n=2" /> 要 10.2 eV，对应 121.6 nm 的紫外光；换用 11 eV 的光子照射，剩下的 0.8 eV 没有去处，原子不吸收，这条谱线就不会出现。</p>
    <p>一群氢原子处在各种激发态上，各自跃迁，就能同时发出多条谱线。一个氢原子从第 <Katex tex="n" /> 能级往下落，最多只能发 <Katex tex="n-1" /> 个光子；而大量原子从各个激发态下落，能给出 <Katex tex="n(n-1)/2" /> 条谱线这样的组合数。讨论谱线条数时，要先分清问的是一个原子还是一群原子。</p>
    <p>光子能量足够大时情况改变：只要 <Katex tex="h\nu\ge13.6" /> eV（从基态出发），电子就能挣脱核的束缚，原子被电离。多出来的能量变成自由电子的动能，其值连续可变，所以电离以后不再有分立的谱线，吸收谱变成一段连续区。</p>
    <p>这套能级图像的应用很广。光谱分析靠特征谱线辨认元素与测定含量，天文学靠它读出恒星的成分；荧光与激光都建立在受激原子跃迁释放同频光子的基础上；原子钟把跃迁频率当作时间的标尺，精度到几百万年不差一秒。</p>

