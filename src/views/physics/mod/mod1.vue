    <h3 class="sec" id="m1-eq">光子说与光电方程</h3>
    <p>普朗克研究黑体辐射时提出，振子的能量只能一份一份地取，每一份的大小是 <Katex tex="h\nu" />，<Katex tex="h" /> 是普朗克常量，约 <Katex tex="6.63\times10^{-34}\ \mathrm{J\cdot s}" />。爱因斯坦把这个想法往前推了一步：光本身就是由一份份能量组成，每一份叫一个光子，能量是 <Katex tex="h\nu" />。</p>
    <p>在这个图像里，光电效应是单个光子与单个电子的一次碰撞：电子一次性吸收整个光子的能量，不需要积累。电子从金属内部逸出，路上要克服原子核的束缚，至少要付出一个最小能量，这个最小能量叫逸出功 <Katex tex="W" />。扣掉这一份，剩下的才是电子逸出后能带走的动能；能量分配得最好的那些电子带走的动能最大。于是</p>
    <p style="text-align:center"><Katex tex="h\nu=W+E_k" display /></p>
    <p>这就是爱因斯坦光电方程，其中 <Katex tex="E_k" /> 是光电子的最大初动能。四条规律都在这一条式子里：</p>
    <p>频率太低时 <Katex tex="h\nu<W" />，一个光子的能量还不够付逸出功，电子吸收后仍然出不来，增加光强只是让更多不够格的光子到来，仍然没有电子。<Katex tex="h\nu=W" /> 对应的频率就是截止频率 <Katex tex="\nu_0=W/h" />。</p>
    <p>高于截止频率时，<Katex tex="E_k=h\nu-W" /> 只由频率决定，与光强无关。光强增大只是光子数增多，单个光子的能量没变，逸出的电子数目变多、最大动能不变。饱和电流正比于光强，正是这一条的直接结果。</p>
    <p>电子吸收光子的过程极短，没有累积，所以效应几乎是瞬时的。弱光下每秒到达的光子虽少，但只要频率够高，每一个够格的光子都能立刻打出一个电子。</p>

    <h3 class="sec" id="m1-uc">遏止电压与最大初动能</h3>
    <p>遏止电压是让光电流恰好归零的反向电压。电子从阴极到阳极，反向电场对它做负功，最大动能的电子刚好到不了阳极时，有</p>
    <p style="text-align:center"><Katex tex="eU_c=E_k" display /></p>
    <p>代入光电方程得 <Katex tex="eU_c=h\nu-W" />，写成</p>
    <p style="text-align:center"><Katex tex="U_c=\dfrac{h}{e}\nu-\dfrac{W}{e}" display /></p>
    <p>这是一条关于 <Katex tex="\nu" /> 的直线：纵截距为 <Katex tex="-W/e" />，横截距为 <Katex tex="\nu_0=W/h" />，斜率为 <Katex tex="h/e" />。对不同的金属做实验，得到的是一组彼此平行的直线——斜率相同、截距不同。斜率相同说明 <Katex tex="h" /> 是一个与材料无关的普适常量；截距不同说明各金属的逸出功不同。</p>
    <p>历史上正是这条直线的斜率给出了普朗克常量的一个独立测量值，与黑体辐射得到的值一致，光子说由此从假说变成被广泛接受的理论。密立根花了十年做这组实验，本意是检验光子说，结果反而把它证实了。</p>
    <p>遏止电压的意义还在于：它是测量最大初动能的直接手段。电子动能无法直接读出，但电压可以精确测量，两者只差一个电子电荷。</p>

    <h3 class="sec" id="m1-app">逸出功、截止频率与应用</h3>
    <p>逸出功由金属本身决定，与表面状况也有关。碱金属的逸出功小，铯约 1.9 eV，钾约 2.2 eV，可见光就能打出电子；锌约 4.3 eV，银约 4.7 eV，需要紫外光。同一金属表面氧化或沾污后，逸出功会变大，效应变弱。</p>
    <p>用波长表示截止条件，<Katex tex="\nu_0=W/h" /> 对应截止波长 <Katex tex="\lambda_c=hc/W" />。对铯，<Katex tex="\lambda_c" /> 落在红光附近；对锌、银，截止波长已经在紫外区，所以可见光打不出电子。</p>
    <p>应用分两类。一类把光信号变成电信号：光电池、光电管、光电倍增管、摄像机与光纤通信的接收端，都靠光电效应把光转成电流。光电倍增管让光电子在打拿极上逐级倍增，能把单个光子放大成可测的脉冲。另一类做自动控制：路灯天黑自动亮、电梯门被挡住时停住、生产线上的产品计数，用的都是光敏元件受光照后电阻或电流改变的效应。</p>
    <p>光电效应还留下一个用经典理论解释不了的量：光子的能量是一份一份的，光的能量不能无限细分。这一步跨出去，物质的波动性与粒子性就同时进入了物理，下一章把这份量子性推广到电子等实物粒子上。</p>

