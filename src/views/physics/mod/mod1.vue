    <h3 class="sec" id="m1-expt">实验现象与四条规律</h3>
    <p>实验装置是一只抽成真空的玻璃管，管内封着两块金属极板：一块作为阴极 <Katex tex="K" />，一块作为阳极 <Katex tex="A" />，两者接在外电路上，中间串一只电流表。一定频率的光透过石英窗口照到阴极表面，如果阴极发射了电子，这些电子在极板间电场的作用下飞向阳极，外电路里就出现电流。</p>
    <p>把电压从零开始逐渐加大，电流随之增大；到某个电压之后不再增大，这个最大值叫饱和电流。在电压为零时仍然有电流，说明逸出的电子本身带有动能；把电压反向，电流逐渐减小，直到某个反向电压时电流恰好降为零。这个反向电压叫遏止电压，记作 <Katex tex="U_c" />。</p>
    <p>改变光的频率、强度和阴极材料，反复测量，得到四条规律：</p>
    <p>其一，对每一种金属都存在一个截止频率 <Katex tex="\nu_0" />。入射光频率低于它时，无论光强多大、照射多久，都没有光电子产生；高于它时，即使光很弱也会立即有电子逸出。</p>
    <p>其二，光电子的最大初动能由入射光的频率决定，频率越高动能越大，与光的强弱无关。加强光只是让单位时间内逸出的电子变多，多的电子并不比少的时候跑得更快。</p>
    <p>其三，饱和电流与入射光的强度成正比。光强加倍，单位时间内打到阴极的光子数加倍，逸出的电子数也加倍。</p>
    <p>其四，从光照开始到电子逸出，经过的时间不超过 <Katex tex="10^{-9}" /> s。即使光弱到每秒只有几个光子到达，只要频率够高，电子照样立刻出来，没有可测量的延迟。</p>
    <p>这四条用经典波动理论都解释不了。按波动说，光的能量连续地分布在波前上，电子要积累足够的能量才能逸出，弱光下就该有一段延迟；而且只要照射时间够长、光强够大，任何频率的光都该能打出电子。实验与这两条推论针锋相对。</p>

