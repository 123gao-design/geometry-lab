    <h3 class="sec" id="m2-hyp">德布罗意的假设</h3>
    <p>光的干涉、衍射说明光有波动性，光电效应又说明光是一份份的光子，有粒子性。这两种描述各自都有大量实验支持，不能拿一个否掉另一个，只能接受它们同时成立。光子把这两面连起来的桥是</p>
    <p style="text-align:center"><Katex tex="E=h\nu,\qquad p=\dfrac{h}{\lambda}" display /></p>
    <p>能量与频率成正比、动量与波长成反比，比例系数都是普朗克常量 <Katex tex="h" />。对光子来说，这套关系是爱因斯坦光量子说的推论。</p>
    <p>1924 年，德布罗意提出一个大胆的假设：既然光这种「波」也有粒子的一面，那么电子这种「粒子」是否也有波的一面？他假定一切运动的实物粒子都伴随一列波，这列波与粒子的关系同光子完全一样：</p>
    <p style="text-align:center"><Katex tex="\lambda=\dfrac{h}{p},\qquad \nu=\dfrac{E}{h}" display /></p>
    <p>这就是德布罗意关系，对应的波叫物质波，也叫德布罗意波。假设的动因是自然界在这一点上应当是对称的：如果波能是粒子，粒子就该能是波。当时这只是一个思辨性的猜想，没有实验支持，连德布罗意自己也没说清这列波究竟是「什么在振动」。</p>
    <p>判断它是否成立的办法只有一个：算一算波长有多大，看能不能观察到。若波长与实验中的障碍物尺度相差悬殊，波动性就显现不出来，假设也就无法检验；若波长与原子间距、晶面间距同量级，衍射实验就能直接把它照出来。</p>

    <h3 class="sec" id="m2-formula">物质波的波长</h3>
    <p>电子在加速电场中获得的动能等于电场力做的功 <Katex tex="eU" />，速度不大时按非相对论计算，<Katex tex="\tfrac12mv^2=eU" />，于是动量</p>
    <p style="text-align:center"><Katex tex="p=\sqrt{2meU}" display /></p>
    <p>代入德布罗意关系，</p>
    <p style="text-align:center"><Katex tex="\lambda=\dfrac{h}{\sqrt{2meU}}" display /></p>
    <p>把常数代进去：<Katex tex="h=6.63\times10^{-34}" /> J·s，<Katex tex="m=9.11\times10^{-31}" /> kg，<Katex tex="e=1.6\times10^{-19}" /> C，得到一串很好用的数</p>
    <p style="text-align:center"><Katex tex="\lambda\approx\dfrac{1.226}{\sqrt{U}}\ \mathrm{nm}" display /></p>
    <p>电压取 100 V，λ 约 0.12 nm；取 1000 V，约 0.039 nm；取 10000 V，约 0.012 nm。这些数值正好落在原子直径（约 0.1 nm）与晶面间距（零点几 nm）的范围内。也就是说，几百伏加速出来的电子，其波长与晶体里原子排列的尺度相当，穿过晶体时必然发生明显的衍射。这正是实验能够检验假设的前提。</p>
    <p>波长与加速电压的平方根成反比：电压升到四倍，波长减半。想让波长更短、分辨本领更高，就得把加速电压继续往上加，这也是电子显微镜不断追求高压的原因。</p>
    <p>同样的公式对其他粒子也成立，只是质量不同，波长随质量增大而缩短。质子质量是电子的 1836 倍，同样电压下波长只有电子的约四十三分之一。宏观物体的波长更是小得离谱：一粒 1 g 的小球以 1 m/s 运动，波长约 <Katex tex="7\times10^{-31}" /> m，比原子核还小十多个数量级，任何实验都测不出它的波动性。</p>

