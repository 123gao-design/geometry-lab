    <h3 class="sec" id="m2-expt">电子衍射的实验验证</h3>
    <p>1927 年，戴维孙与革末把一束低能电子射向镍单晶，测量不同方向上散射电子的强度，发现强度随角度周期性起伏，起伏的规律与 X 射线在晶体上的衍射完全对应。按布拉格条件 <Katex tex="2d\sin\theta=k\lambda" /> 反算，得到的波长与德布罗意公式给出的数值一致。同年，汤姆孙让电子束穿过一层很薄的金箔，在屏上拍到一组同心圆环，与 X 射线穿过多晶薄膜的图样同一形状。</p>
    <p>两个实验一单晶、一多晶，互相印证。此后类似实验越做越精细：把电子一束一束地发射，短时间内在屏上得到一个一个随机的点，长时间累积才显出明暗相间的条纹。单个电子落在哪里是随机的，大量电子到达的概率却按波动规律分布。这个事实把物质波的含义点明了：它不是介质的机械振动，而是对粒子出现位置的概率描述。</p>
    <p>更重要的是，实验给出的波长严格等于 <Katex tex="h/p" />，误差在千分之几以内。假设从一个猜想变成了一条规律。此后中子、原子、分子也相继做出衍射与干涉：用 C₆₀ 这类大分子做双缝干涉，条纹依然清楚，说明这才是一切物质共有的属性，不是电子独有的特例。</p>

    <h3 class="sec" id="m2-app">波粒二象性与它的应用</h3>
    <p>光和实物粒子都同时具有波动性与粒子性，这个性质叫波粒二象性。两者并不在同一场实验里同时显现：测干涉条纹时，看到的是波；测单个粒子落在哪里、带走多少能量时，看到的是粒子。实验装置决定你看到哪一面。</p>
    <p>量子力学用波函数与概率来统一描述这件事：物质波的强度正比于粒子在该处出现的概率，条纹的极大处是电子经常到达的位置，极小的位置则几乎不出现。这条解释兼顾了两面：波给出概率分布，粒子在其上随机落点。</p>
    <p>波长大小决定哪一面占主导。宏观物体的波长小到无法测量，波动性无从显现，牛顿力学就足够准确；电子、质子、原子的波长与原子尺度相当，波动性必须认真对待；光子的波长在可见光量级，干涉与衍射是日常现象。</p>
    <p>应用分几路。电子显微镜用高压把电子波长压到皮米量级，分辨率远高于光学显微镜，而且用电磁透镜聚焦，能拍到原子。中子不带电、穿透力强，中子衍射用来测磁结构。原子干涉仪利用原子的物质波测量重力加速度与转动，精度极高。这些技术都建立在一个公式上：<Katex tex="\lambda=h/p" />。</p>

