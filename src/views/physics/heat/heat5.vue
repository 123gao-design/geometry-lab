    <h3 class="sec" id="h5-dir">自然过程的方向</h3>
    <p>把一杯热水放在桌上，它会自己凉下来；一块冰放进温水里，它会自己化掉。反过来，桌上的冷水不会自己变热，温水里的冰块化完以后，那杯水也不会自己重新结出冰来。墨滴落进清水会自己散开，直到整杯水颜色均匀；已经染匀的水不会再自己聚回一滴墨。</p>
    <p>这些过程都有一个共同点：自发进行的方向由系统的初末状态决定，与中间怎么走无关。要让它们反向进行，就必须由外界做功——冰箱把热量从冷藏室搬到温度更高的室内，靠的是压缩机消耗电能；要把散开的气体重新压回一个角落，靠的是活塞。第二定律禁止的不是反向过程本身，而是<strong>不付代价</strong>的反向过程。</p>
    <p>这条界线值得与第一定律对照着看。第一定律是能量守恒，只说数量：能量不会凭空产生，也不会凭空消失。一个违反第一定律的过程，账目当场就对不上；而热量自发从低温流向高温，账目完全对得上，只是不曾自发发生过。方向这一半信息，第一定律里没有。</p>

    <h3 class="sec" id="h5-two">第二定律的两种表述</h3>
    <p><strong>克劳修斯表述</strong>：热量不能自发地从低温物体传到高温物体。这里的关键词是「自发」——借助外界做功把热量从低温搬到高温是可以做到的，冰箱与热泵每天都在做，但它要消耗能量，不算自发。</p>
    <p><strong>开尔文表述</strong>：不可能从单一热源吸收热量，使之完全变成功，而不产生其他影响。换句话说，一台只与一个热源打交道、把这些热量百分之百变成有用功、别的一概不变的热机是不存在的。设想中的这类机器叫<strong>第二类永动机</strong>，它不违反能量守恒，却同样造不出来。</p>
    <p>两种说法看起来各说各的，其实是同一件事的两面。假如热量能自发地从低温传到高温，就可以让热机把高温热源送来的热量全部变成功、再把所需的废热自动送回高温热源，于是净效果成了从单一热源取热全变成功；反过来，假如有这样的热机，也能用它把热量从低温搬到高温。二者要么同时成立、要么同时不成立。</p>
    <p>还要注意「不产生其他影响」这句话。理想气体等温膨胀时，吸进来的热量确实可以全部用来对外做功，<Katex tex="\Delta U=0" />，<Katex tex="Q=-W" />；但气体膨胀了，体积这个状态变了，产生了其他影响，所以并不违反开尔文表述。要让它循环往复地做功，就必须把气体压回去，而压缩要耗功，这部分功最终还是以热量形式排给了低温热源。</p>

    <h3 class="sec" id="h5-engine">热机与效率</h3>
    <p>热机是把内能转化为机械能的装置。它工作时从高温热源吸收热量 <Katex tex="Q_1" />，对外做有用功 <Katex tex="W" />，再把余下的热量 <Katex tex="Q_2" /> 排给低温热源。按能量守恒</p>
    <p style="text-align:center"><Katex tex="W=Q_1-Q_2." display /></p>
    <p>效率定义为有用功与吸热之比：</p>
    <p style="text-align:center"><Katex tex="\eta=\frac{W}{Q_1}=1-\frac{Q_2}{Q_1}." display /></p>
    <p>只要热机向低温热源排出热量，<Katex tex="Q_2>0" />，效率就小于 1。这正是第二定律的量化形式：不排出废热的热机，就是开尔文表述所禁止的第二类永动机。</p>
    <p>卡诺证明，给定高温热源与低温热源的温度，任何热机的效率都有一个上限，叫<strong>卡诺效率</strong>：</p>
    <p style="text-align:center"><Katex tex="\eta_c=1-\frac{T_2}{T_1}." display /></p>
    <p>这个上限只由两端的温度决定，与热机用什么工作物质无关。实际热机因为有摩擦、漏热与各种不可逆损失，效率还要更低一些，永远达不到这个上限：<Katex tex="\eta<\eta_c" />。下面那块板里的热机取 <Katex tex="\eta=0.85\,\eta_c" />，读数栏最后一行的 <Katex tex="\eta_c-\eta" /> 因此恒为正。</p>
    <p>两端的温差越大，卡诺效率越高。把高温热源的温度提上去，或者把低温热源的温度压下来，都能提高效率；但无论怎么调，只要 <Katex tex="T_2>0" />，效率就永远小于 1。</p>

