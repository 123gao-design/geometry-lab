    <p class="cap">图 热5a · <b>热机与效率：实际效率压在卡诺上限之下</b>：左栏最上面是橙色的高温热源、最下面是蓝色的低温热源，中间那台热机从高温侧吸进 <Katex tex="Q_1=400\ \text{J}" />，一支绿色箭头 <Katex tex="W" /> 向右去带动轮子，一支蓝色箭头 <Katex tex="Q_2" /> 把余下的热量排进低温热源。右栏横轴是低温热源的温度 <Katex tex="T_2" />，橙线是卡诺上限 <Katex tex="\eta_c=1-T_2/T_1" />，绿色虚线标出此刻的实际效率，橙、绿两枚点都钉在 <Katex tex="T_2" /> 那一条竖线上。看点一：默认 600 K 与 300 K 时 <Katex tex="\eta_c=0.500" />、实际效率 0.425，读数栏里 <Katex tex="W=170\ \text{J}" /> 与 <Katex tex="Q_2=230\ \text{J}" /> 相加正好是 400 J。看点二：同一列上橙点在上、绿点在下，两点的竖直距离就是读数栏最后一行的 <Katex tex="\eta_c-\eta=0.075" />——实际热机有摩擦与漏热，够不到可逆热机的那条上限。看点三：把 <Katex tex="T_1" /> 拖高，橙线的斜度变缓、整条上抬，绿虚线跟着抬高；把 <Katex tex="T_2" /> 拖到 250 K，<Katex tex="\eta_c" /> 升到 0.583、实际效率升到 0.496，同样吸 400 J 时对外做功从 170 J 涨到约 198 J。看点四：绿虚线是把此刻的 <Katex tex="\eta" /> 横着画满整个右栏，它与橙线在右侧会相交——那是同一条水平参考线的画法，不必去读那个交点；要比的高低只取橙点这一列，那里绿点始终落在橙点下方，读数栏的 <Katex tex="\eta_c-\eta" /> 因此始终为正。</p>

    <h3 class="sec" id="h5-entropy">熵与不可逆过程</h3>
    <p>第二定律还有一个统计上的版本：孤立系统总是自发地从有序走向无序，系统的<strong>熵</strong>不会减少。熵是分子运动无序程度的量度，分子分布越均匀、可取的状态越多，熵越大。</p>
    <p>扩散是最好的例子。隔板把容器分成两半，N 个分子全挤在一边。抽走隔板，分子各自乱跑，很快两半都有分子。能否等到它们重新全部回到左半？并非绝对不可能，但每个分子恰好在左半的概率是 <Katex tex="\tfrac12" />，N 个分子同时回到左半的概率是</p>
    <p style="text-align:center"><Katex tex="P=\left(\frac12\right)^{N}=2^{-N}." display /></p>
    <p><Katex tex="N=24" /> 时这个概率约为 <Katex tex="6\times10^{-8}" />；一杯水里约有 <Katex tex="10^{24}" /> 个分子，对应的概率小到无法写出有意义的等待时间。这就是宏观上「不可逆」的来源：反向过程不被力学禁止，只是等不到。下面这块板画的就是这一步：隔板抽走以后分子自己铺满两半，读数栏把这条概率直接写了出来。</p>

    <PhysicsDemo :def="DEMO2" />
    <p class="cap">图 热5b · <b>自发扩散：反向过程不是被禁止，而是等不到</b>：左栏一只隔成两半的盒子，蓝点是此刻落在左半的分子、橙点是落在右半的；右栏画左半分子数随时间的变化。看点一：起初隔板挡在中间，24 个分子全挤在左半，读数栏的右半分子数是 0；1.2 秒后隔板变成一条虚线被抽走，分子向右侧跑，橙点才开始出现。看点二：左半分子数从 24 一路降到 12 附近，此后就在那条标着「两半各占一半」的虚线上下小幅波动，再没有回到 24。看点三：读数栏的「全部回到左半的概率」写着 <Katex tex="2^{-24}\approx6.0\times10^{-8}" />——反向不是力学上被禁止，而是概率小到等不到。看点四：把分子数滑块拖到 48，这个概率降到 <Katex tex="3.6\times10^{-15}" />，盒里的点变密，曲线照旧向一半靠拢；分子数每翻一倍，概率就平方一次，宏观过程的不可逆性正是这样堆出来的。</p>
    <p>热传导、自由膨胀、摩擦生热，都是熵增加的过程，方向都由概率决定。第二定律与第一定律一起构成本章之前的整块热学：第一定律说能量总量不变，第二定律说这些能量只能朝着无序增加的方向转化。</p>

    <h3 class="sec" id="h5-perp">能量守恒与两类永动机</h3>
    <p>历史上人们设想过两类永动机。第一类不消耗任何能量就能源源不断地做功，比如一台不需要上弦却永远走动的钟；它要求能量的产出大于投入，直接违反能量守恒，也就是热力学第一定律。</p>
    <p>第二类永动机不违反能量守恒：它从大海、空气这类单一热源吸热，把这些热量全部变成有用的功，效率为 100%。这种机器仍然造不出来，挡住它的正是第二定律。所以第一定律与第二定律各守一条线：一条管数量，一条管方向。想过效率这道关，两条线必须同时满足。</p>
    <p>能量守恒本身可以写成一句朴素的话：能量既不会凭空产生，也不会凭空消失，只会从一种形式转化为另一种形式，或从一个物体转移到另一个物体，在转化和转移中总量保持不变。热力学第一定律是它在热现象中的具体形式；发展到整个自然界，它是一条普遍规律。</p>

    <h3 class="sec" id="h5-apply">算一遍：热机与扩散</h3>
    <p>取一台热机，高温热源 600 K、低温热源 300 K，每个循环吸热 400 J。先算卡诺上限：</p>
    <p style="text-align:center"><Katex tex="\eta_c=1-\frac{300}{600}=0.50." display /></p>
    <p>实际效率按八五折取 <Katex tex="\eta=0.425" />，于是</p>
    <p style="text-align:center"><Katex tex="W=\eta Q_1=0.425\times400=170\ \text{J},\qquad Q_2=Q_1-W=230\ \text{J}." display /></p>
    <p>三者满足 <Katex tex="W+Q_2=Q_1=400\ \text{J}" />，读数栏的「η_c − η」一行给出 0.075，正是实际热机离上限还差的那一截。</p>
    <p>把低温热源的温度拖到 250 K，卡诺效率升到 <Katex tex="1-250/600\approx0.583" />，实际效率约 0.496，同样吸 400 J 时对外做功约 198 J。温差拉大，排给低温热源的废热就少一些。</p>
    <p>再看扩散。上面那块扩散的板取 24 个分子，抽走隔板后左半分子数从 24 一路降到 12 附近来回波动，从此不再回到 24。读数栏的「全部回到左半的概率」为</p>
    <p style="text-align:center"><Katex tex="2^{-24}\approx6.0\times10^{-8}," display /></p>
    <p>把分子数拖到 48，这个概率降到 <Katex tex="3.6\times10^{-15}" />。分子数每翻一倍，反向概率就平方一次，这就是「宏观过程不可逆」在数字上的样子。</p>

