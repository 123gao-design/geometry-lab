    <p class="cap">图 热1a · <b>布朗运动</b>：左栏是一只装着分子的盒子，分子做匀速直线运动、撞到器壁弹回，快的画橙、慢的画蓝；中央那枚绿色圆点是悬浮颗粒，身后五秒的折线是它走过的路径。看点一：颗粒走的是一条无规则折线，忽左忽右，没有一段能接成规整的曲线——每一处转折都来自某一侧分子撞击暂时强过另一侧。看点二：盒子里的分子比颗粒小得多、数量却极多，颗粒每秒被撞上无数次，读数栏的悬浮颗粒速率却比分子平均速率小得多——颗粒的质量是单个分子的几十倍，撞击换来的速度只分到很小的一份。看点三：把温度拖高，分子跑得更快，颗粒的折线跟着变得更曲折，读数栏的悬浮颗粒速率一行也一并变大——布朗运动的剧烈程度是分子热运动剧烈程度的间接量度。</p>

    <h3 class="sec" id="h1-dist">速率分布与温度</h3>
    <p>单个分子的速率是随机的，但大量分子的速率有确定的统计规律。把某温度下所有分子的速率统计一遍，会发现：速率很小和很大的分子都很少，中等速率的分子最多。若以速率为横轴、以某一速率区间内的分子数占比为纵轴，得到的曲线先升后降、有一个明显的峰，这叫<strong>麦克斯韦速率分布</strong>。下面这块板右栏的橙色曲线就是它，蓝色柱则是盒子里那群分子此刻的实际统计，分子跑得越久，柱子越贴近曲线。</p>
    <p>曲线上几个特征值各有名字：峰所对应的速率叫<strong>最概然速率</strong>，即分子出现机会最大的速率；所有分子速率的平均值叫<strong>平均速率</strong>；速率的平方的平均值再开方叫<strong>方均根速率</strong>。三者都由温度与分子质量决定，温度升高时一起变大，整条曲线向速率大的方向移动、同时变宽变矮。</p>
    <p>这里正是统计思想登场的地方。<strong>温度是分子平均动能的标志</strong>：温度越高，分子热运动的平均动能越大。但要注意，温度升高并不意味着每个分子的速率都变大，而是速率大的分子所占的比例增大，仍有一部分分子速率很小。读数栏里的几个速率都是统计平均值，不是某个具体分子的速率。</p>

