    <h3 class="sec" id="h1-micro">分子的大小与阿伏加德罗常数</h3>
    <p>把一滴油滴在水面上，它会散开成一层极薄的膜。若油膜恰好处在只有单个分子厚度的状态，由油滴的体积与油膜的面积就能估出分子的直径。这类实验给出的结果是：一般分子的直径在 <Katex tex="10^{-10}\ \text{m}" /> 的数量级，也就是 0.1 纳米上下。</p>
    <p>分子的数目极多。<Katex tex="1\ \text{mol}" /> 任何物质所含的分子数都相同，这个数叫<strong>阿伏加德罗常数</strong>：</p>
    <p style="text-align:center"><Katex tex="N_A=6.02\times10^{23}\ \text{mol}^{-1}." display /></p>
    <p>有了它，宏观量就能与微观量互相换算。摩尔质量 <Katex tex="M" /> 除以 <Katex tex="N_A" /> 是一个分子的质量；摩尔体积除以 <Katex tex="N_A" /> 是一个分子平均占有的体积。比如水的摩尔质量是 <Katex tex="18\ \text{g/mol}" />，一个水分子的质量约为 <Katex tex="3\times10^{-26}\ \text{kg}" />。这类估算题的关键是分清「分子的体积」与「分子所占的空间」：对固体与液体，分子挨得很紧，两者近似相等；对气体，分子间空隙很大，占有的空间远大于分子本身。</p>

    <h3 class="sec" id="h1-motion">分子热运动与布朗运动</h3>
    <p>分子在不停地运动，最直接的证据是<strong>扩散</strong>：一滴墨水滴进清水，过一阵整杯水都变了颜色；打开一瓶香水，屋里各处都能闻到。不同物质的分子彼此进入对方，说明分子在动。温度越高扩散越快，说明这种运动与温度有关。</p>
    <p>另一个更细致的证据是<strong>布朗运动</strong>。把花粉或其他微小颗粒悬浮在水中，用显微镜观察，会发现颗粒在做一种不停顿、无规则的运动：忽左忽右，走的是一条曲折的折线，颗粒越小、温度越高，运动越剧烈。这种运动是 1827 年植物学家布朗先看到的。</p>
    <p>要弄清布朗运动是谁的运动。悬浮颗粒比水分子大得多，它自己不会凭空动起来，是被四周水分子的撞击推动的。分子从各个方向撞击颗粒，某一时刻某一侧的撞击稍强，颗粒就往另一侧挪一点，于是走出一条不规则的路线。所以，<strong>布朗运动是悬浮颗粒的运动，它反映的是液体分子的无规则运动</strong>。颗粒越小，同一时刻撞击它的分子数越少，撞击的不平衡越明显，运动越剧烈；温度越高，分子运动越快，撞击越猛，运动也越剧烈。</p>
    <p>把分子这种永不停息的无规则运动叫<strong>分子热运动</strong>。它与温度密切相关：温度越高，分子的平均速率越大，热运动越剧烈。下面这块板停在布朗运动档，绿色大颗粒在四周分子的撞击下缓慢漂移，身后拖出的折线就是它的轨迹；把温度拖高，撞击更频繁、轨迹更活跃。</p>

