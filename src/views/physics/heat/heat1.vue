    <p class="cap">图 热1b · <b>速率分布与温度</b>：左栏盒子里的分子做无规则运动，橙色是此刻较快的一小部分；右栏橙色曲线是麦克斯韦速率分布，紫色竖虚线标出它的峰，蓝色柱是盒中那群分子当前速率的统计。看点一：分子数只有几十个，蓝色柱高低起伏、并不光滑；让它们多跑一阵，柱形渐渐向曲线靠拢——分子越多、时间越长，统计规律越清楚。看点二：把温度从 300 K 拖到 600 K，曲线整体右移、峰变矮，紫色虚线跟着峰走；盒子里的分子也普遍快起来，橙色分子所占的比例随之增大。看点三：读数栏的最概然速率、平均速率与方均根速率三行一起变大，但三者的比值不随温度改变，始终是 <Katex tex="\sqrt2:\sqrt{8/\pi}:\sqrt3" />，约 <Katex tex="1:1.13:1.22" />——温度只是把整条分布按 <Katex tex="\sqrt T" /> 放大。看点四：拖到高温也不会有分子速率真的大到出格，曲线右端的尾巴一直压得很低，「偶尔出现一个特别快的分子」正是尾巴虽低却不为零的含义。</p>

    <h3 class="sec" id="h1-force">分子间的作用力与分子势能</h3>
    <p>分子之间除了碰撞时的接触力，还存在着持续的相互作用。两个分子之间<strong>同时</strong>存在引力和斥力，两者都随距离的增大而减小，但变化的快慢不同：距离减小时斥力增大得更快，距离增大时引力占上风。</p>
    <p>于是合力有两种表现。距离等于某个数值 <Katex tex="r_0" />（平衡距离，约 <Katex tex="10^{-10}\ \text{m}" />）时，引力与斥力恰好相等，合力为零；距离小于 <Katex tex="r_0" /> 时，斥力大于引力，合力表现为<strong>斥力</strong>，把分子推开；距离大于 <Katex tex="r_0" /> 时，引力大于斥力，合力表现为<strong>引力</strong>，把分子拉近。距离大到一定程度（十倍于分子直径以上）时，两力都小到可以忽略，分子间的作用力就消失了。</p>
    <p>与这条合力相对应，分子间存在<strong>分子势能</strong>。分子靠近时若合力表现为斥力，靠近需要外力做功，势能增大；分子远离时若合力表现为引力，远离也需要克服引力做功，势能同样增大。因此在 <Katex tex="r=r_0" /> 处分子势能最小。分子势能与分子间距离的关系决定了物体在体积变化时势能怎样变——这是后面讲内能与做功的关键。</p>

    <h3 class="sec" id="h1-inner">内能</h3>
    <p>物体内所有分子的<strong>热运动动能</strong>与<strong>分子势能</strong>之和，叫物体的<strong>内能</strong>。它与前面学过的机械能是两回事：机械能由宏观的速率与高度决定，内能由分子的热运动与分子间距离决定。一个静止在桌上的杯子，机械能为零，内能却不为零，因为杯里的分子一直在动。</p>
    <p>哪些因素影响内能？分子的平均动能由温度决定，所以温度升高时内能增大（一般情形）；分子势能与分子间的距离有关，体积变化时它随之变化；此外，分子总数越多，内能越大。同样温度的一杯水和一桶水，内能并不相同——温度只决定「平均每个分子分到多少动能」，总数才决定总量。</p>
    <p>理想气体的分子间作用力可以忽略，分子势能取为零，此时内能<strong>只由温度与分子数决定</strong>。这一简化在下一章推导气体实验定律与状态方程时反复用到：等温过程中理想气体的内能不变，体积变化时做功与热传递恰好相抵。</p>

    <div class="note warn tip">
      <div class="tip-t"><span class="tip-ic">💡</span>提示</div>
      <ul class="tip-list">
        <li><strong>提示一：把布朗运动当成分子本身的运动。</strong>布朗运动是<strong>悬浮颗粒</strong>的运动，颗粒由成千上万个分子组成，肉眼在显微镜下才看得见。它之所以值得观察，是因为颗粒的每一次偏折都由液体分子的撞击造成，所以布朗运动是<strong>分子无规则运动的间接证据</strong>，不是分子运动的直接照片。</li>
        <li><strong>提示二：认为分子间只存在引力或只存在斥力。</strong>引力和斥力<strong>同时存在</strong>，只是大小随距离变化的快慢不同。所谓「表现为引力」，指的是引力大于斥力，合力方向沿连线相吸，并不是斥力消失了。距离很大时两者都趋于零，分子间作用力才可忽略。</li>
        <li><strong>提示三：认为温度升高后每个分子的速率都变大。</strong>温度是分子<strong>平均</strong>动能的标志，温度升高时速率大的分子所占比例增大，分布曲线向高速方向移动，但仍有速率很小的分子。单个分子的速率时刻在变，不能用一个分子去验证温度。</li>
        <li><strong>提示四：认为温度相同内能就相等。</strong>内能是全部分子的动能与势能之和，除了温度，还与分子的数目、体积（分子势能）以及物态有关。同温的一杯水与一桶水内能不同；理想气体的内能只由温度与分子数决定，这个特例不能推广到所有物体。</li>
