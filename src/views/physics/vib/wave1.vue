      <ul class="tip-list">
        <li><strong>提示一：认为质点随波迁移。</strong>绳上的每个点只在自己原来的位置附近上下振动，波传过去之后它仍在原处，传到远处的是振动形式与能量。上面那块板里绿色那一点的竖直虚线始终钉在同一个横坐标上，就是这一条的证据。</li>
        <li><strong>提示二：把波速与质点振动的速度混为一谈。</strong>波速是波形向前推进的速度，方向沿绳；质点的速度是它上下振动的速度，方向竖直。两者方向垂直、大小也无固定关系。说「波跑得很快」时指的是前者。</li>
        <li><strong>提示三：把频率与波速的决定因素弄反。</strong>频率由<strong>波源</strong>决定，波速由<strong>介质</strong>决定。波进入另一种介质时频率不变、波速改变、波长跟着变；改变波源的频率时波速不变、波长改变。把这两组关系对上号，后面的多普勒效应与折射才不会乱。</li>
        <li><strong>提示四：把相邻波峰与波谷的距离当成波长。</strong>波峰到相邻波谷的距离是半个波长。波长是相邻两个<strong>同相</strong>点（两个波峰、两个波谷或任意两个状态完全相同的点）之间的距离。</li>
