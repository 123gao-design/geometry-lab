    <p>两种波都可以用波长、周期、频率与波速描述，也都可以画成位移随时间或随位置的曲线，只是横波的起伏直接看得见，纵波需要把疏密程度换成位移才能画出来。地震波里既有横波也有纵波：横波不能通过液体，纵波可以通过，这一点帮助人们推断地核的构成。</p>

