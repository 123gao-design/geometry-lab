    <p>这道起伏为什么能传出去？绳是由许多小段连成的，相邻两段之间有弹力。手先把紧挨着的那一小段拉离平衡位置，这一小段随即对下一小段施加力，把它也拉起来；下一小段带动再下一小段。如此一环扣一环，振动就沿着绳子传下去了。每一小段都在做前一环强加给它的振动，所以严格说来，绳上每个质点做的都是<strong>受迫振动</strong>，它的频率等于波源的频率。</p>
