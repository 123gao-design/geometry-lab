    <h3 class="sec" id="w1-speed">波速与三者的决定因素</h3>
    <p><strong>波速</strong> <Katex tex="v" /> 是振动形式向前传播的速度，也就是波前推进的速度。它不是绳上质点运动的速度：质点只是上下振动，波却向右跑。同一个波里，这两个速度方向互相垂直。</p>
    <p>波速由<strong>介质</strong>决定，与波源的频率无关。同一根绳，张力越大、线密度越小，波速越快；同一段空气，温度不同声速也不同；同一把吉他，弦绷得越紧，声音传得越快。只要介质不变，无论手抖得快还是慢，波速都是同一个值。</p>
    <p>把三个量的决定因素列在一起，这张表就是这一节的骨架：</p>
    <p><strong>频率由波源决定</strong>，介质改变它也不改变；<strong>波速由介质决定</strong>，波源改变它也不改变；<strong>波长由两者共同决定</strong>，<Katex tex="\lambda=v/f" />。当波从一种介质进入另一种介质时，频率不变，波速改变，于是波长跟着变。船上的汽笛声传到岸上、光从空气进入水中，都遵守这一条。</p>
    <p>上面那块板的读数栏把这几个量并排给出：拖频率时 <Katex tex="\lambda" />、<Katex tex="T" />、<Katex tex="f" /> 一起变而波速不动，拖波速时只有 <Katex tex="\lambda" /> 变、<Katex tex="T" /> 与 <Katex tex="f" /> 不动；两种情形下 <Katex tex="\lambda" /> 与 <Katex tex="v/f" /> 始终相等。把这一点看清楚，比背公式有用得多。</p>

    <p>把这三个量再往下写成一条式子，就得到波的方程：远处的质点在重复波源 <Katex tex="\Delta t=x/v" /> 之前的运动，由此引出相位、波数、相位差与波动方程。这一组的最后一章振7「波的方程」专门讲这件事，届时本章的四个量会变成那条式子的系数。下面先把波按振动方向与传播方向的关系分成两类。</p>

    <h3 class="sec" id="w1-kinds">横波与纵波</h3>
    <p>按质点振动方向与传播方向的关系，机械波分两大类。</p>
    <p><strong>横波</strong>：质点的振动方向与波的传播方向垂直。绳波就是标准的横波——质点上下振动，波向右传播。横波有<strong>波峰</strong>与<strong>波谷</strong>，波形起伏明显。下面那块板的上排正是这一类。</p>
    <p><strong>纵波</strong>：质点的振动方向与波的传播方向在同一直线上。介质被交替地压缩与拉伸，形成<strong>密部</strong>与<strong>疏部</strong>，没有波峰波谷。声波是典型的纵波：声源推动空气，空气一疏一密地向前传播，人耳接收到的正是这样的疏密变化。</p>
    <p>下面那块板把两类波并排画在同一张图上。上排是绳上的横波，蓝色小点在原地上下振动；下排是同一列纵波，一根根竖直短线代表介质中的一小段，它们在平衡位置附近沿传播方向前后振动。两排共用同一个波长、频率、波速与波前，拖频率或波速的滑块，上排的起伏与下排的疏密同步改变。</p>

