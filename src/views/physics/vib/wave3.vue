    <p>回收与预告：波2 的叠加原理是这一章的根——干涉是叠加在空间上的稳定图案，衍射是缝上无数子波叠加的结果，多普勒效应则是同一列波在不同运动状态下的观察差异。干涉的加强与减弱，说到底由两列波在这一点上的相位差决定：路程差为波长整数倍时相位差是 <Katex tex="2\pi" /> 的整数倍，两列波同相叠加。下一章振7「波的方程」把这个说法写成式子，从相位滞后出发给出 <Katex tex="y=A\sin(\omega t-kx)" />、相位差 <Katex tex="\Delta\varphi=2\pi\Delta x/\lambda" /> 与波动方程，本章与波2 用到的几个量都在那里收口。波三件事里的「频率、波长、波速」与「相位差」这两组概念，后面在光学里会原样出现：光的干涉、光的衍射、光的偏振都建立在同一套描述之上，只是把机械波换成了电磁波。机械波这一组讲完，机械振动与机械波这一部分也随之结束，下一部分转入热学，从分子的运动讲起，先把温度、压强那些熟悉的量换成微观的图像。</p>
