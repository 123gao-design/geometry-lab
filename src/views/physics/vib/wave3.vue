        <li><strong>提示二：把加强点理解成位移始终最大。</strong>加强点指的是<strong>振幅</strong>最大，等于两列波振幅之和；它仍在振动，经过平衡位置时位移同样为零。减弱点也只有当两列波振幅相等时才真正静止，振幅不等时以 <Katex tex="|A_1-A_2|" /> 振动。</li>
        <li><strong>提示三：认为衍射要求孔比波长小得多。</strong>判断标准是尺寸与波长<strong>差不多</strong>：与波长相当或更小时衍射明显，比波长大很多时不明显。缝宽从与波长大致相当继续缩小，衍射只是更显著，并没有一个「从无到有」的临界点。</li>
