    <h3 class="sec" id="w3-ind">波的干涉</h3>
    <p>取两只完全相同的振子，让它们以相同的频率、相同的步调上下振动，各自在水面激起一圈圈圆波。两套圆波相遇的地方，水面的起伏并不是两套圆波简单地叠在一起，而是出现了一幅稳定的图案：某些方向上水面起伏得特别厉害，某些方向上几乎不动，这些方向都不随时间改变。这种现象叫<strong>波的干涉</strong>。</p>
    <p>干涉之所以能形成稳定的图案，靠的是两个条件：两列波的<strong>频率相同</strong>，且它们之间的<strong>相位差恒定</strong>。满足这两条的波源叫<strong>相干波源</strong>。频率不同时，两列波在某点的相位差一刻不停地变，加强和减弱交替出现、彼此抵消，看不出稳定的图案；相位差变化时也一样。下面那块板的两个波源用同一条时间轴驱动，始终同相，所以图案是稳的。</p>
    <p>为什么会有稳定的加强区与减弱区？取空间中的一点 <Katex tex="P" />，两列波从两个波源分别走过 <Katex tex="r_1" /> 与 <Katex tex="r_2" /> 到达这里。两个波源同相，所以两列波在 <Katex tex="P" /> 点的相位差完全由路程差</p>
    <p style="text-align:center"><Katex tex="\Delta r=|r_1-r_2|" display /></p>
    <p>决定。若 <Katex tex="\Delta r" /> 恰好是波长的整数倍，两列波到达时步调一致，波峰对着波峰，位移相加，振幅最大；若 <Katex tex="\Delta r" /> 是半波长的奇数倍，两列波恰好反相，波峰对着波谷，位移相减，振幅最小。</p>
