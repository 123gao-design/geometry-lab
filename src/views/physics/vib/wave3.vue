    <h3 class="sec" id="w3-fringe">加强线与减弱线</h3>
    <p>把所有加强点连起来，得到一条条从两波源之间向外辐射的曲线；减弱点同样连成曲线，与加强线相间排列。数学上这些曲线是<strong>双曲线</strong>，两个波源就是双曲线的两个焦点。两波源连线的垂直平分线上，任一点到两波源等距，<Katex tex="\Delta r=0" />，总是加强的，这条线叫<strong>零级加强线</strong>。</p>
    <p>上面那块板画出了两套圆波（蓝、橙）与一条条绿色加强线，竖直的绿线就是零级，其余依次标着 <Katex tex="n=1,2,\dots" />。把波长 <Katex tex="\lambda" /> 拖小，或把波源间距 <Katex tex="d" /> 拖大，加强线之间的间隔变窄、条数变多；反过来则变宽变少。读数栏最后一行给出第一级加强线与中垂线的夹角 <Katex tex="\theta" />，满足</p>
    <p style="text-align:center"><Katex tex="\sin\theta=\frac{\lambda}{d}." display /></p>
    <p>这个式子在光学里会反复出现：缝距 <Katex tex="d" /> 越大、波长越短，条纹越密。当 <Katex tex="\lambda\ge d" /> 时，第一级加强线已经不存在，整个空间只剩零级一条，图案变得很简单。</p>
    <p>加强点与减弱点的「加强」「减弱」说的是<strong>振幅</strong>，不是位移。加强点仍在振动，只是振幅达到两列波振幅之和，经过平衡位置时位移照样为零；减弱点也不是一定静止，只有当两列波振幅相等、<Katex tex="A_1=A_2" /> 时，减弱点的振幅才为零、真的不动。板里的两个波源等幅，正是后一种情形。</p>

    <h3 class="sec" id="w3-diff">波的衍射</h3>
    <p>波在传播途中遇到障碍物或小孔时，并不总是沿直线前进，它会拐弯绕到障碍物后面去，或者从孔后向各个方向散开。这种现象叫<strong>波的衍射</strong>。</p>
    <p>解释要借助惠更斯的想法：波面上的每一点都可以看作一个新的小波源，发出球面子波，这些子波叠加起来形成新的波面。障碍物上开一条缝，缝上的每一点都成了子波源，缝后不再是平直的波面，而是从缝出发的一圈圈圆波。缝越窄，参与发波的子波源范围越小，子波向各个方向分布得越均匀，衍射越明显；缝很宽时，缝后很长一段仍近似是平面波，看不出去弯。</p>
    <p>衍射是否显著，看的是<strong>缝宽或障碍物的尺寸与波长的比值</strong>。尺寸比波长大得多时，衍射不明显，波近似沿直线传播；尺寸与波长差不多或更小时，衍射很显著。下面那块板把缝宽 <Katex tex="a" /> 从大到小拖动，橙色的圆波从一条窄窄的光束逐渐张开成半圆，最后几乎向各个方向都散开。读数栏的 <Katex tex="\lambda/a" /> 是判断衍射显著程度的直接指标：它越大，衍射越明显。</p>

    <PhysicsDemo :def="DEMO2" />
    <p class="cap">图 波3b · <b>波的衍射</b>：左侧一排竖直蓝线是不断向右推进的入射平面波，中间的黑色挡板上开一条缝，挡板左侧一段短竖线与小字标出缝宽 <Katex tex="a" />，缝后是一圈圈橙色圆弧。看点一：缝宽比波长大得多时，橙色圆弧只在很窄的角度里张开，缝后近似是一条直射过去的波束——衍射不明显。看点二：把缝宽拖到与波长相近，圆弧明显向两侧张开；再拖小，它接近一个半圆，波向缝后的各个方向都散开。看点三：读数栏给出 <Katex tex="\lambda/a" /> 与第一极小角，前者越大衍射越显著；缝宽小到 <Katex tex="\lambda/a\ge 1" /> 时第一极小角一栏改读「不存在」，圆弧已经张成整个半圆。</p>

    <p>生活里的例子很多。人站在墙后能听到墙那边的说话声，看却看不到人：声波的波长在米的数量级，与门窗的尺寸接近，衍射过去；可见光的波长短得多，日常的墙缝对它来说太大了，衍射不明显。水波通过窄缝、无线电波绕过山丘，都是同一个道理。</p>

    <h3 class="sec" id="w3-doppler">多普勒效应</h3>
    <p>站在路边，救护车鸣笛驶近时音调偏高，驶过之后音调突然变低。音调的变化不是因为司机换了鸣笛，而是因为<strong>你接收到的频率</strong>变了。波源与观察者之间有相对运动时，观察者接收到的频率与波源发出的频率不同，这种现象叫<strong>多普勒效应</strong>。</p>
    <p>用波面来看最清楚。波源静止时，每发出一个波峰，它所在的球面就以波速 <Katex tex="v" /> 向外扩张，相邻波峰之间的距离就是波长 <Katex tex="\lambda" />。波源一旦向某个方向运动，它在新位置发出下一个波峰时，位置比上一次更靠近前方，于是前方的波峰被压紧，波长变短；后方的波峰被拉开，波长变长。观察者站定不动，每秒钟从他面前经过的波峰数就是接收频率：前方的波峰密，接收频率就高；后方的波峰疏，接收频率就低。</p>
    <p>设波源速度大小为 <Katex tex="v_s" />，波速为 <Katex tex="v" />，波源向观察者靠近时，观察者接收到的频率</p>
    <p style="text-align:center"><Katex tex="f'=\frac{v}{v-v_s}f,\qquad f''=\frac{v}{v+v_s}f." display /></p>
    <p>前一式是靠近时，后一式是远离时。波源的速度越接近波速，前方的波长被压得越短、频率越尖；当 <Katex tex="v_s" /> 超过 <Katex tex="v" /> 时，波面会叠成一个锥面，这就是超音速飞机身后的音爆。</p>
    <p>下面那块板让波源一边发声一边向右移动。仔细看蓝圈：前方相邻两圈挨得很紧，后方拉得很开，圆心一个比一个偏右。读数栏给出前后两个观察者接收到的频率，前方大于波源的频率，后方小于它。这里要分清一件事：<strong>波源发出的频率没有变</strong>，波速也没有变，变化的是观察者单位时间里数到的波峰数。</p>

    <PhysicsDemo :def="DEMO3" />
    <p class="cap">图 波3c · <b>多普勒效应</b>：橙色小球是边发声边向右运动的波源，四周的蓝色圆圈是它依次发出的波峰，左右两端各立一枚静止的观察者。看点一：每一圈蓝圈的圆心都落在波源发声那一刻的位置上，所以圆心一个比一个偏右，右侧的圈被压紧、左侧的被拉开。看点二：读数栏分列前后两端接收到的频率，前方大于波源频率、后方小于它；而「波长 λ」与「波速 v」两行在拖声源速度时纹丝不动——波源发出的频率与波速都没有变，变的只是数到的波峰数。看点三：把声源速度拖到 0，所有蓝圈同心、中央标出 v = 0，前后两端接收到的频率都回到波源频率；把速度拖大，读数栏的「前方波长」比波长 <Katex tex="\lambda" /> 更短，声源越快压得越紧。</p>

    <p>多普勒效应的用处很多。交通雷达向行驶的汽车发射电磁波，测出反射波频率的变化，就能算出车速；医学彩超用同一原理测血流速度；天文学家从星光的频率偏移判断星系是在远离还是在靠近，「红移」是光谱向低频方向移动的俗称。测速雷达与彩色多普勒超声，用的都是这一条式子。</p>

