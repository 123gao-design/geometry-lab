    <p>振1 与振2 的分析里都写了「不计空气阻力」。把这一条去掉，摆球每经过一次平衡位置都要克服阻力做功，机械能一点点变成内能。能量减少最直接的表现是振幅变小：同一只摆，第一趟摆到 <Katex tex="10^\circ" />，第二趟只到 <Katex tex="9.5^\circ" />，越往后越小。振幅逐渐减小的振动叫<strong>阻尼振动</strong>。</p>
    <p>振幅减小的规律大致是指数的。每经过一段固定的时间，振幅缩小的比例相同，所以包络线可以写成</p>
    <p style="text-align:center"><Katex tex="A=A_0e^{-\beta t}," display /></p>
    <p>其中 <Katex tex="\beta" /> 与阻力的大小有关：阻力越大，<Katex tex="\beta" /> 越大，振幅衰减得越快。下面那块板的上一半是振子，下一半是位移随时间的曲线，橙色虚线画的正是这条包络：位移曲线在两条包络之间来回穿过，峰顶恰好贴着包络走，一圈比一圈收得紧。</p>
