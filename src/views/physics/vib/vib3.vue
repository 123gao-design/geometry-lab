    <h3 class="sec" id="v3-kinds">三种阻尼</h3>
    <p>阻尼的大小不同，运动的形态完全不同，通常分三种情形。</p>
    <p><strong>欠阻尼</strong>：阻尼较小，物体仍能来回振动，只是振幅逐渐减小，最后停在平衡位置。上一节那块板里阻尼系数取得较小时就是这一种。</p>
    <p><strong>临界阻尼</strong>：阻尼恰好大到让物体不再越过平衡位置，从偏离处释放后，它一次也不往回摆，而是直接回到平衡位置并停住，且回到平衡位置所用的时间最短。</p>
    <p><strong>过阻尼</strong>：阻尼更大，物体同样不来回摆动，但回到平衡位置的过程更慢，要拖上一段时间才停稳。</p>
    <p>这三种情形的分界在阻尼的大小，界线是<strong>临界阻尼系数</strong></p>
    <p style="text-align:center"><Katex tex="b_c=2\sqrt{km}." display /></p>
    <p><Katex tex="b<b_c" /> 时是欠阻尼，<Katex tex="b=b_c" /> 时是临界阻尼，<Katex tex="b>b_c" /> 时是过阻尼。由这个式子还能看出，质量越大、弹簧越硬，就越不容易被阻尼压成不往复的运动。真实振子的 <Katex tex="b" />、<Katex tex="k" />、<Katex tex="m" /> 都由装置本身定下来，量出临界阻尼系数也就等于量出了阻尼的大小。</p>
    <p>实际装置常利用这一条。灵敏电流计、天平的指针都调到接近临界阻尼，指针摆过来后不会来回晃、也不会慢吞吞地爬；汽车减震器同样按这个思路设计，过减速带后车身上下很快平稳下来，而不会连续颠几下。</p>

