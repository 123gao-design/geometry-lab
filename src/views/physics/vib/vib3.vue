    <h3 class="sec" id="v3-forced">受迫振动</h3>
    <p>阻尼振动最终会停下来。要让振动持续，就得不断补充能量，常见的做法是加一个<strong>周期性的驱动力</strong>：荡秋千时别人按节奏推你一把，洗衣机脱水时桶的转动带动整台机器晃动，都是这一类。物体在周期性驱动力作用下发生的振动叫<strong>受迫振动</strong>。</p>
    <p>受迫振动的规律与自由振动很不一样。刚开始时，物体的运动是两种成分的叠加：一部分是系统自身的固有振动，频率为固有频率；另一部分是驱动力强迫出来的振动，频率为驱动力的频率。固有振动那一部分会因阻尼而逐渐衰减，经过一段时间（过渡过程）之后，只剩下驱动力那一部分。于是稳定后的振动有两条结论：</p>
    <p>其一，<strong>频率等于驱动力的频率</strong>，与系统的固有频率无关。推秋千的人推得慢，秋千就摆得慢；推得快，秋千就摆得快。</p>
    <p>其二，<strong>振幅由驱动力频率与固有频率的接近程度决定</strong>，差距越小振幅越大，同时与阻尼的大小有关。这条结论就是后面共振曲线的来源。</p>
    <p>下面那块板画的是这件事。上半是振子：紫色的驱动端按设定的振幅 <Katex tex="A" /> 与频率 <Katex tex="f" /> 来回拉动弹簧的左端，物块被带着振动。下半曲线的纵轴取 <Katex tex="x/A" />：紫色淡虚线是驱动端的位移，它恒在 ±1 之间；蓝色是物块的位移；橙色虚线是稳态振幅 <Katex tex="\pm X/A" />。曲线开头一小段还混着物块自己的固有节奏，随后与紫线同频。读数栏里的「固有频率 <Katex tex="f_0" />」由 <Katex tex="k" /> 与 <Katex tex="m" /> 决定，「稳态 <Katex tex="X/A" />」是过渡过程结束后物块振幅与驱动端振幅的比值。</p>
    <p>能量的角度很清楚：驱动力每个周期输入的能量恰好等于阻尼每个周期消耗的能量，收支平衡，振幅才稳定下来。驱动频率离固有频率越近，同样的驱动力能激起的振幅越大，需要输入的功率并不一定更大，但振动已经变得剧烈。</p>

