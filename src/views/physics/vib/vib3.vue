    <h3 class="sec" id="v3-resonance">共振与共振曲线</h3>
    <p>把驱动频率从低到高慢慢扫过，稳定后的振幅先变大、再变小，在某个频率处达到最大。这个最大值的来历很特殊：<strong>当驱动力的频率等于系统的固有频率时，受迫振动的振幅达到最大</strong>，这种现象叫<strong>共振</strong>。</p>
    <p>下面那块板把这件事画成一条曲线：横轴是驱动频率 <Katex tex="f" />，纵轴是稳态振幅与驱动端振幅之比 <Katex tex="X/A" />。曲线的左端接近 1（驱动很慢时，物块几乎跟着驱动端一起动），右端趋于 0（驱动很快时，物块来不及跟上，几乎不动），中间鼓起一个峰，峰的位置在固有频率 <Katex tex="f_0" /> 附近，绿色虚线与紫色小点标出了这里。橙点是你当前选的驱动频率所对应的位置，它与峰的远近，就是此刻振动的剧烈程度。</p>
    <p>峰顶的高度可以算出来。在 <Katex tex="f=f_0" /> 处分母里剩下的是阻尼那一项，整理后</p>
    <p style="text-align:center"><Katex tex="\left(\frac{X}{A}\right)_{\max}=\frac{\omega_0}{2\beta}=\frac{\sqrt{km}}{b}." display /></p>
    <p>这个式子把阻尼的作用说得很清楚：峰高与 <Katex tex="b" /> 成反比，阻尼减半，共振振幅就翻倍。读数栏的「峰高 X / A」一直列出这一格，可以逐点核对。<Katex tex="k=20\ \text{N/m}" /> 时 <Katex tex="\sqrt{km}=4.47" />，<Katex tex="b=1.6" /> 对应峰高 2.80，把 <Katex tex="b" /> 拖到 0.8 峰高就变成 5.59。下面那块板的纵轴固定在 0 到 7，峰一旦高过 7 就从框顶穿出去，曲线在那一段断开——这本身就是「阻尼越小共振越剧烈」的样子。</p>
    <p>阻尼在曲线上留下的痕迹也很清楚。把阻尼系数 <Katex tex="b" /> 拖大，峰顶变低、变宽；拖小，峰顶变高、变窄，曲线变成一根尖刺。这就是「阻尼越小，共振越剧烈」的定量样子。反过来，如果要在很宽的频率范围内保持平稳（例如扬声器的纸盆、地震仪），就要把阻尼设计得大一些。</p>
    <p>共振既有用处，也有危险。用处这边：乐器的共鸣箱靠共振把弦的微弱振动放大成响亮的声音；共振筛利用共振让筛面大幅振动，分选矿石；收音机的调谐回路通过改变固有频率，选中某个频率的电磁波。危险那边：一队士兵齐步走过桥，脚步的频率若与桥的固有频率接近，桥会被越振越厉害，所以过桥要便步走；机器安装时要把转速避开共振区，或者在底座加减震装置；高层建筑在地震中也要考虑自身的固有频率是否与地震波的主要成分接近。</p>

