    <p>弦乐器上拨动一根两端固定的弦，弦上的波在两端反射回来，与原来的波叠加，形成的正是驻波；手指按住弦上不同位置改变的就是波节的位置，从而改变音高。下一章波3 讲两列相干波叠加时的干涉图样，用的还是这一条叠加原理。</p>

