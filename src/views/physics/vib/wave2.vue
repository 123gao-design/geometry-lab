    <h3 class="sec" id="w2-add">波的叠加原理</h3>
    <p>前面的波都是单独一列。现实里总有多列波同时在介质中传播：水面上两个石子激起的涟漪会相遇，乐器上不同弦的振动会通过琴箱混在一起，空间里还有无数束光。它们相遇时会发生什么？</p>
    <p>实验给出一条简单而牢固的规律：几列波在同一种介质中相遇时，每一列波都<strong>保持自己的频率、波长、振幅与传播方向，像没有遇到别的波一样继续前进</strong>；在它们重叠的区域，任一质点的位移等于各列波<strong>单独</strong>到达时在该点引起的位移的<strong>矢量和</strong>。这就是<strong>波的叠加原理</strong>。</p>
    <p>下面那块板把这件事画得很直白：蓝色脉冲向右、橙色脉冲向左，两个脉冲大小不同、方向相反。它们相向而行，重叠时绿色曲线（合位移）等于两条淡色曲线在每一点的纵坐标之和；重叠的部分过去之后，两个脉冲各自恢复成原来的形状继续走，谁也看不出刚才撞过谁。</p>
    <p>叠加有两种极端情形值得记住。两个脉冲<strong>同相</strong>相遇（峰对峰），合位移的大小相加，振幅变大；<strong>反相</strong>相遇（峰对谷），合位移的大小相减，若两者振幅恰好相等，这一刻该处的质点位移为零、暂时静止。下面那块板里两个脉冲一正一负，重叠处就出现了「抵消」的样子，但抵消只是这一瞬间、这一段的位移为零，两个脉冲本身仍然完整，穿过之后各自照旧。</p>
    <p>要注意叠加是<strong>位移</strong>的相加，不是把两列波「合成一列新波」。几个波源同时发声，空气的振动是几列声波位移的叠加，但每一列声波都在独立地传播，进入耳朵时可以分辨出不同的音色与方向，原因正在这里。</p>

