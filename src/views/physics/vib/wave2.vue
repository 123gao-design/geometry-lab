    <h3 class="sec" id="w2-stand">独立传播与驻波</h3>
    <p>叠加原理的两句话——相遇时位移相加、相遇后独立传播——是同一件事的两面。前者管重叠的那一小段时间，后者管重叠前后。两列波穿过彼此之后都没有被改变，所以叠加是可逆的：把整个过程的录像倒着放，看起来一样合理。</p>
    <p>一个特别重要的情形是两列<strong>振幅相同、频率相同、传播方向相反</strong>的波叠加。它们叠加后的波形不再向前移动，而是在原地上下振动，某些点始终不动，某些点振幅最大，这样的波叫<strong>驻波</strong>。始终不动的点叫<strong>波节</strong>，振幅最大的点叫<strong>波腹</strong>，相邻两个波节之间的距离是半个波长。</p>
    <p>下面那块板把这件事画出来。淡蓝色的一列波向右、淡橙色的一列波向左，两列振幅相同、频率相同，绿色曲线是它们的合位移。绿色小点标出的位置始终为零，是波节；相邻两个波节之间振幅最大的地方是波腹，那里的合振幅是两列波振幅之和 2A，橙色小点就在 ±2A 之间上下往复。拖动频率 <Katex tex="f" /> 或波速 <Katex tex="v" />，波长改变，波节随之疏密，紫色双箭头量出的相邻波节距离始终是半个波长。</p>

