    <h3 class="sec" id="p5-persp">中心投影与透视</h3>
    <p>拿一盏点光源照着一张画了两个三角形的平面，把影子投到另一张平面上，两个三角形就处在<b>透视</b>关系里：对应顶点的连线全是那束光线，必过光源 <Katex tex="O" />。射影几何把这件事只留下投影关系本身：两个图形称为透视的，若对应点的连线共点。</p>
    <p>透视这件事是「位置」层面的，度量在这里完全不起作用。两三角形可以一个很胖一个很瘦，边长比例毫无规律，但只要连线过同一个点，它们就透视。德萨格定理说的正是透视关系的另一半：顶点层面共点，会逼着边的层面共线。</p>
    <p>用齐次坐标看，这部分内容可以完全写成行列式。两个三角形对应顶点连线共点，等价于一个 <Katex tex="3\times3" /> 矩阵把三点映到三点；三组对应边的交点共线，等价于某个行列式为零。两条结论其实是同一个代数事实的两种读法。</p>

    <h3 class="sec" id="p5-des">德萨格定理</h3>
    <p>最干净的证明是升到三维。把两个三角形放在两张不平行的平面上，光源 <Katex tex="O" /> 在第三个位置，两张平面交于一条直线 <Katex tex="l" />。对应边的交点是两个三角形公共的点，因此既在第一张平面上又在第二张平面上，只能落在交线 <Katex tex="l" /> 上。三个交点同时属于 <Katex tex="l" />，共线得证。</p>
    <p>平面内的情形由这个三维构形「压平」得到：把两张平面之一绕交线转动到与另一张重合，共线关系在转动中保持。这一步在射影平面上是合法的，因为射影变换只保留共线与交比，不保留距离与角度。</p>
    <p>逆定理也成立：若对应边的三个交点共线，则对应顶点的连线共点。证明同样靠三维提升，或者直接对偶——把「点」与「线」互换，德萨格定理的对偶恰好是自己的逆命题。这种「一条定理同时给出正逆两个方向」的现象，在射影几何里很常见。</p>
    <p>画板左图的三个金色交点，就是这三组对边的交点。拖任何一个顶点，三点始终在同一线上；比例 <Katex tex="t" /> 调大，轴往外移，但没有任何一次脱离共线。</p>

    <h3 class="sec" id="p5-pap">帕普斯定理</h3>
    <p>帕普斯的构形比德萨格简单，结论却更强。两条直线上各取三点，交叉连成六条线：<Katex tex="A_1" /> 连 <Katex tex="B_2" />、<Katex tex="A_2" /> 连 <Katex tex="B_1" />，这两个「交错」的交点记作 <Katex tex="X" />；同样得到 <Katex tex="Y" /> 与 <Katex tex="Z" />。帕普斯定理断言 <Katex tex="X,Y,Z" /> 共线。</p>
    <p>关键在于「交错」。若按顺序连 <Katex tex="A_1B_1" />、<Katex tex="A_2B_2" />、<Katex tex="A_3B_3" />，三线各自独立，没有任何共线结论；只有把下标交叉，才逼出那条直线。画板右图把这六条连线画成虚线，金色三点正是三个交错交点。</p>
    <p>用齐次坐标验证很直接：设两条直线分别是 <Katex tex="z=0" /> 与 <Katex tex="y=0" /> 之类的简单位置，把六个点写成参数形式，三次叉积算交点，最后一行列式自动为零。这个计算没有用到任何度量，纯粹是坐标的代数恒等式。</p>

    <h3 class="sec" id="p5-status">两条定理的地位</h3>
    <p>在欧氏几何里，这两条都是可证的定理；在射影几何里，它们决定公理系统的强弱。射影平面由「点、线、关联」三条公理加上德萨格公理构成时，得到的是一类很广的平面；再补上帕普斯公理，平面就唯一确定到一个域上，可以完全用齐次坐标计算。</p>
    <p>两条定理的关系是单向的：帕普斯可以推出德萨格（这条推导叫海森伯格定理），反过来不行。存在满足德萨格却不满足帕普斯的射影平面，它们来自非交换的除环——四元数就是一个例子。换句话说，帕普斯定理等价于「坐标所在的除环是交换的」，这条等价把几何公理和代数结构直接连了起来。</p>
    <p>这也解释了为什么射影几何的定理常常「一条顶两条」：对偶原理让每条定理自动产生一条对偶版本，帕普斯的对偶版本是它的逆命题，德萨格的对偶版本也是它的逆命题。写证明时可以先证一个方向，另一个方向由对偶直接得到。</p>

